/* INPUT_OUTPUT_CHANNEL_BIT_DESCRIPTIONS.agc, the LM's: Luminary099 pages
 * 54-60. The listing file holds no code, only the description of each
 * input and output channel and of its bits; here it is, word for word, as
 * a table. The channel numbers are octal, as the listing writes them (and
 * as READ, WRITE, WAND and WOR name them); the bits count from 1, the low
 * bit, to 15. A bit the listing skips (channel 32's 11 to 13 and 15) has
 * no entry, and the listing's spelling stands (DESCRIPTIONSF, SPAECRAFT,
 * RENDESVOUS).
 *
 * The CM's listing has no such file. Its channels are the same computer's,
 * with the CM's hardware on the bits. */
