/* CONTROLLED_CONSTANTS.agc, the LM's: Luminary099 pages 38-53. The listing
 * file that gathers the constants of the spacecraft and of nature the
 * mission depends on, away from the routines that use them: engine
 * thrusts and mass flows, radar and accelerometer scales, masses, the
 * gravity of earth and moon, the star table, the coefficients of the
 * lunar and solar ephemerides. It holds no routine. Each group opens with
 * the SETLOC of the routine's own bank tag, so a constant sits in the
 * bank of the code that reaches it.
 *
 * Here the file is a table. A constant keeps the listing's card and
 * operand as text (2DEC 4.3670 B-7), and beside them:
 *
 *   number   what the operand says, as a C number: E-n is a power of ten
 *            and B-n a power of two, the scaling that brings the value
 *            under 1 (4.3670 B-7 is 4.3670 / 128);
 *   address  where the assembler put its first word, in the group's bank;
 *   words    the word, or the two of a double-precision constant.
 *
 * The words are the number: a number under 1 in size is a fraction of
 * 2(14) for a single word and of 2(28) for a pair, rounded to the nearest
 * (a half away from zero), and a whole number written with no point and
 * no scale is itself; a negative one is the one's complement of each
 * word. make assembly-cases works every pair of words out again from its
 * number, and holds the words to the rope.
 *
 * The CM's listing has no such file; its constants stand with its
 * routines. */
