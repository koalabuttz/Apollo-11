"""Write the keys of the faithful port's P20-P25 tables, each mission's
(c64-port/src/<m>_p20_p25.c: <m>_p20_p25_basic and
<m>_p20_p25_interpretive), as src/binding/p20_p25_keys.inc (the LM's) and
src/binding/cm_p20_p25_keys.inc (the CM's), for the readable bindings
(src/binding/p20_p25_routines.c and cm_p20_p25_routines.c).

P20-P25.agc is written readable part by part. A binding must define the
faithful tables' names with the same keys in the same order, so it takes
them from here: one line per key, BASIC(index, bank, address) or
PAIR(index, bank, address), beside the faithful routine's own comment (its
label, or where control comes back to it from).

  p20_p25_keys.py          write both files
  p20_p25_keys.py --check  fail if either differs from the faithful tables
"""
import re
import sys
from pathlib import Path

READABLE = Path(__file__).resolve().parents[1]
# Each mission's faithful file, and the file of its keys.
MISSIONS = (('lm', READABLE / 'src/binding/p20_p25_keys.inc'),
            ('cm', READABLE / 'src/binding/cm_p20_p25_keys.inc'))


def generate(m):
    text = (READABLE.parent / f'c64-port/src/{m}_p20_p25.c').read_text()
    # Each routine's comment, by its name.
    comments = dict((found.group(2), found.group(1).strip()) for found in re.finditer(
        r'/\* (\d\d,\d{4} [^*]*)\*/\nstatic enum exec_status (r\d+)\(', text))
    out = ['/* SPDX-License-Identifier: MIT; generated by readable/tools/p20_p25_keys.py',
           f' * from c64-port/src/{m}_p20_p25.c. Do not edit.',
           ' *',
           ' * The keys of the faithful P20-P25 tables, in their order: BASIC for',
           f' * {m}_p20_p25_basic, PAIR for {m}_p20_p25_interpretive; each with its index',
           ' * in the table, its bank and its address (in the bank, or 04000-07777 in',
           ' * fixed-fixed memory, banks 2 and 3). */']
    for table, macro in (('interpretive', 'PAIR'), ('basic', 'BASIC')):
        body = re.search(r'static const agc_routine_entry %s_entries\[\]=\{(.*?)\n\};' % table,
                         text, re.S).group(1)
        # (the CM's routines are called through wrappers, <routine>_abi)
        entries = re.findall(r'\{(\d+),(r\d+)(?:_abi)?\}', body)
        last = -1
        for i, (physical, name) in enumerate(entries):
            physical = int(physical)
            if physical <= last:
                raise SystemExit('p20_p25_keys: %s keys out of order' % table)
            last = physical
            bank, offset = divmod(physical, 1024)
            address = (0o4000 + 0o2000 * (bank - 2) if bank in (2, 3) else 0o2000) + offset
            out.append('%s(%d, 0%o, 0%o) /* %s */' % (macro, i, bank, address, comments[name]))
    return '\n'.join(out) + '\n'


def main():
    for m, out in MISSIONS:
        text = generate(m)
        if sys.argv[1:] == ['--check']:
            if not out.exists() or out.read_text() != text:
                raise SystemExit('p20_p25_keys: %s is not the faithful tables\' keys' % out)
            continue
        out.write_text(text)


if __name__ == '__main__':
    main()
