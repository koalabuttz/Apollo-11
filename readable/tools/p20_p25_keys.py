"""Write the keys of the faithful port's routine tables for the files
whose bindings take them from here: P20-P25, each mission's
(c64-port/src/<m>_p20_p25.c: <m>_p20_p25_basic and
<m>_p20_p25_interpretive), as src/binding/p20_p25_keys.inc (the LM's) and
src/binding/cm_p20_p25_keys.inc (the CM's); the CM's P30-P37
(c64-port/src/cm_p30_p37.c) as src/binding/cm_p30_keys.inc; and the LM's
P32-P35_P72-P75 (c64-port/src/lm_p32_p35.c) as src/binding/p32_keys.inc;
and the CM's P32-P33_P72-P73 (c64-port/src/cm_p32_p33.c) as
src/binding/cm_p32_keys.inc; and each mission's P34-35_P74-75
(c64-port/src/<m>_p34_p35.c) as src/binding/p34_keys.inc and
cm_p34_keys.inc; and the LM's P40-P47 (c64-port/src/lm_p40_p47.c) as
src/binding/p40_keys.inc. For the readable bindings
(src/binding/p20_p25_routines.c, cm_p20_p25_routines.c,
cm_p30_routines.c, p32_routines.c, cm_p32_routines.c, p34_routines.c,
cm_p34_routines.c and p40_routines.c).

A binding must define the faithful tables' names with the same keys in the
same order, so it takes them from here: one line per key, BASIC(index,
bank, address) or PAIR(index, bank, address), beside the faithful
routine's own comment (its label, or where control comes back to it from).

  p20_p25_keys.py          write the files
  p20_p25_keys.py --check  fail if any differs from the faithful tables
"""
import re
import sys
from pathlib import Path

READABLE = Path(__file__).resolve().parents[1]
# Each faithful file (and its tables' prefix), and the file of its keys.
FILES = (('lm_p20_p25', READABLE / 'src/binding/p20_p25_keys.inc'),
         ('cm_p20_p25', READABLE / 'src/binding/cm_p20_p25_keys.inc'),
         ('cm_p30_p37', READABLE / 'src/binding/cm_p30_keys.inc'),
         ('lm_p32_p35', READABLE / 'src/binding/p32_keys.inc'),
         ('cm_p32_p33', READABLE / 'src/binding/cm_p32_keys.inc'),
         ('lm_p34_p35', READABLE / 'src/binding/p34_keys.inc'),
         ('cm_p34_p35', READABLE / 'src/binding/cm_p34_keys.inc'),
         ('lm_p40_p47', READABLE / 'src/binding/p40_keys.inc'))


def generate(m):
    text = (READABLE.parent / f'c64-port/src/{m}.c').read_text()
    # Each routine's comment, by its name.
    comments = dict((found.group(2), found.group(1).strip()) for found in re.finditer(
        r'/\* (\d\d,\d{4} [^\n]*?)\*/\nstatic enum exec_status (r\d+)\(', text))
    out = ['/* SPDX-License-Identifier: MIT; generated by readable/tools/p20_p25_keys.py',
           f' * from c64-port/src/{m}.c. Do not edit.',
           ' *',
           ' * The keys of the faithful tables, in their order: BASIC for',
           f' * {m}_basic, PAIR for {m}_interpretive; each with its index',
           ' * in the table, its bank and its address (in the bank, or 04000-07777 in',
           ' * fixed-fixed memory, banks 2 and 3). */']
    for table, macro in (('interpretive', 'PAIR'), ('basic', 'BASIC')):
        body = re.search(r'static const agc_routine_entry %s_entries\[\]=\{(.*?)\n\};' % table,
                         text, re.S).group(1)
        # (the CM's routines are called through wrappers, <routine>_abi)
        entries = re.findall(r'\{(\d+),(r\d+)(?:_abi)?\}', body)
        last = -1
        for i, (physical, name) in enumerate(entries):
            physical = int(physical)
            if physical <= last:
                raise SystemExit('p20_p25_keys: %s keys out of order' % table)
            last = physical
            bank, offset = divmod(physical, 1024)
            address = (0o4000 + 0o2000 * (bank - 2) if bank in (2, 3) else 0o2000) + offset
            out.append('%s(%d, 0%o, 0%o) /* %s */' % (macro, i, bank, address, comments[name]))
    return '\n'.join(out) + '\n'


def main():
    for m, out in FILES:
        text = generate(m)
        if sys.argv[1:] == ['--check']:
            if not out.exists() or out.read_text() != text:
                raise SystemExit('p20_p25_keys: %s is not the faithful tables\' keys' % out)
            continue
        out.write_text(text)


if __name__ == '__main__':
    main()
