#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Write the routine tables of the three files the flight program enters
through tables of their own: PINBALL_GAME_BUTTONS_AND_LIGHTS,
DISPLAY_INTERFACE_ROUTINES and EXTENDED_VERBS (the faithful port calls
their lane "lanec": c64-port/src/lanec_pin_routines.c and the keypress
groups' lanec_pin_keys_*_routines.c, lanec_di_routines.c and
lanec_ev_routines.c).

A key is a word of fixed memory a step of the program may start at. The
flight program (c64-port/platform/x86/flight_dispatch.c) looks the word up
in the tables its index names and runs the routine it finds, and charges
the AGC's clock by the key; so the readable program must hold the same
keys in tables of the same names as the faithful port's. This writes
them, for each mission, as C the bindings include:

  src/binding/pinball_tables.inc, cm_pinball_tables.inc
      (src/binding/pinball_routines.c)
  src/binding/display_interface_tables.inc, cm_display_interface_tables.inc
      (src/binding/display_interface_routines.c)
  src/binding/extended_verbs_tables.inc, cm_extended_verbs_tables.inc
      (src/binding/extended_verbs_routines.c)

Each key stands with the routine of the binding that takes it (the part
of the file that holds the word; for Pinball, the one routine that runs a
step, or the one for a word a BANKCALL comes back to) and with the
listing's label for the word.

  lanec_keys.py          write the files
  lanec_keys.py --check  fail if any differs from the faithful tables
"""
import re
import sys
import textwrap
from pathlib import Path

READABLE = Path(__file__).resolve().parents[1]
PORT = READABLE.parent / 'c64-port'
sys.path.insert(0, str(Path(__file__).resolve().parent))
import listing_names  # noqa: E402

BINDING = READABLE / 'src/binding'
PREFIX = {'lm': '', 'cm': 'cm_'}
ENTRIES = re.compile(r'static const agc_routine_entry (\w+)\[[^\]]*\] = \{(.*?)\};', re.S)
ENTRY = re.compile(r'\{\s*(\d+)u,\s*(\w+)\s*\}')
TABLE = re.compile(r'const agc_routine_table (\w+) = \{ ?(\w+),')


def labels(m):
    """{physical: label} and the sorted physicals, from the listing's
    symbol table."""
    by_word = {}
    for name, physical in sorted(listing_names.symbols(
            str(PORT / listing_names.IL.LISTINGS[m])).items()):
        by_word.setdefault(physical, name)
    return by_word


def label(by_word, physical):
    """The listing's name for a word: its label, or the label before it in
    its bank and how far on it is (in octal, as the listing counts)."""
    bank = physical // 1024
    for back in range(1024):
        at = physical - back
        if at // 1024 != bank:
            break
        if at in by_word:
            return by_word[at] + (' +%o' % back if back else '')
    return 'bank %o' % bank


def key(physical):
    bank, offset = divmod(physical, 1024)
    if bank in (2, 3):
        return 'FF(0%o)' % (0o4000 + 0o2000 * (bank - 2) + offset)
    return 'SWITCHED(0%o, 0%o)' % (bank, 0o2000 + offset)


def arrays(text):
    """{array: [(physical, routine)]}, each in the faithful order."""
    out = {}
    for name, body in ENTRIES.findall(text):
        rows = [(int(physical), routine) for physical, routine in ENTRY.findall(body)]
        if [p for p, _ in rows] != sorted({p for p, _ in rows}):
            raise SystemExit(f'lanec_keys: {name} is out of order')
        if rows:  # (not the one key written as a sum: EXTENDED_VERBS's INTPRET)
            out[name] = rows
    return out


def table(out, m, name, rows, routine, by_word):
    array = name.replace('lanec_', '').replace(f'_{m}', '') + '_keys'
    out.append(f'static const agc_routine_entry {array}[] = {{')
    for physical, faithful in rows:
        out.append('    {%s, %s}, /* %s */' % (key(physical), routine(faithful),
                                               label(by_word, physical)))
    out.append('};')
    out.append(f'const agc_routine_table {name} = {{')
    out.append(f'    {array}, COUNT({array})}};')
    out.append('')


def header(sources, what):
    return ['/* SPDX-License-Identifier: MIT; generated by readable/tools/lanec_keys.py',
            ' * from ' + ',\n * '.join(f'c64-port/src/{s}' for s in sources) + '. Do not edit.',
            ' *'] + [' * ' + line for line in textwrap.wrap(' '.join(what), 72)] + [' */', '']


def parts(m, file, sources, tables, what):
    """A file whose tables name a routine for each part (display
    interface, extended verbs): <part>_<m> there, <part>_part here."""
    text = ''.join((PORT / 'src' / s).read_text() for s in sources)
    found = arrays(text)
    named = dict(TABLE.findall(text))
    by_word = labels(m)
    out = header(sources, what)
    for name, array in tables:
        array = array or named[name]
        table(out, m, name, found[array], lambda r: re.sub(r'_[lc]m$', '', r) + '_part', by_word)
    return '\n'.join(out)


def display_interface(m):
    return parts(m, 'di', ('lanec_di_routines.inc', 'lanec_di_routines.c'),
                 [(f'lanec_di_{m}_routines', f'{m}_entries')] +
                 [(f'lanec_di_{m}_{part}', None)
                  for part in ('dsp', 'mark', 'play', 'sleep', 'idle', 'nvdsp')],
                 ['The tables the flight program enters DISPLAY_INTERFACE_ROUTINES through, the',
                  f"{m.upper()}'s: the file's table, every key with the routine of its part, and",
                  "then each part's own table (the faithful port loads the parts one at a",
                  'time on the C64, and the index names them all).'])


def extended_verbs(m):
    lm_only = [('lanec_ev_lm_interpretive', 'lm_interp_entries')] if m == 'lm' else []
    names = ('front', 'short', 'align') + (('radar',) if m == 'lm' else ()) + (
        'dap', 'time', 'track')
    return parts(m, 'ev', ('lanec_ev_routines.inc', 'lanec_ev_routines.c'),
                 [(f'lanec_ev_{m}_routines', f'{m}_entries')] + lm_only +
                 [(f'lanec_ev_{m}_{part}', None) for part in names],
                 ["The tables the flight program enters EXTENDED_VERBS through, the",
                  f"{m.upper()}'s: the file's table, every key of its basic code with the",
                  "routine of its part" + (", the table of the LM's interpretive words (lmi_part),"
                                           if m == 'lm' else ","),
                  "and then each part's own table (the faithful port loads the parts one",
                  "at a time on the C64, and the index names them all)."])


GROUPS = ('num', 'cmd', 'release', 'sign', 'clear')


def pinball(m):
    sources = ('lanec_pin_routines.inc',) + tuple(
        f'lanec_pin_keys_{g}_routines.c' for g in GROUPS)
    text = (PORT / 'src' / sources[0]).read_text()
    # The faithful routines that enter by SWRETURN: the words the file's
    # BANKCALLs come back to.
    returns = set(re.findall(r'static enum exec_status (try\d+_%s)\([^)]*\) \{ return swreturn\('
                             % m, text))
    if not returns:
        raise SystemExit('lanec_keys: no SWRETURN routine in lanec_pin_routines.inc')
    by_word = labels(m)
    out = header(sources, [
        'The tables the flight program enters PINBALL_GAME_BUTTONS_AND_LIGHTS',
        f"through, the {m.upper()}'s: the file's table, and the tables of the keypress",
        'groups (number, command, key release, sign and clear keys), which the',
        'faithful port keeps apart. Every key runs a step of the readable Pinball',
        '(pinball_step); a word one of the file\'s BANKCALLs comes back to runs',
        'SWRETURN first (pinball_step_from_bankcall).'])
    table(out, m, f'lanec_pin_{m}_routines', arrays(text)[f'{m}_entries'],
          lambda r: 'pinball_step_from_bankcall' if r in returns else 'pinball_step', by_word)
    for g, source in zip(GROUPS, sources[1:]):
        text = (PORT / 'src' / source).read_text()
        table(out, m, f'lanec_pin_keys_{g}_{m}_routines', arrays(text)[f'{m}_entries'],
              lambda r: 'pinball_step', by_word)
    return '\n'.join(out)


FILES = tuple((BINDING / f'{PREFIX[m]}{name}_tables.inc', make, m)
              for name, make in (('pinball', pinball), ('display_interface', display_interface),
                                 ('extended_verbs', extended_verbs))
              for m in ('lm', 'cm'))


def main():
    for path, make, m in FILES:
        text = make(m)
        if sys.argv[1:] == ['--check']:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"lanec_keys: {path} is not the faithful tables' keys")
            continue
        path.write_text(text)


if __name__ == '__main__':
    main()
