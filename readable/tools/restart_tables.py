"""Write the restart tables (RESTART_TABLES.agc) as readable C data, for
each mission: src/restart/lm_restart_tables.inc (Luminary099) and
src/restart/cm_restart_tables.inc (Comanche055).

The tables are data in fixed memory, bank 01: SIZETAB, then each group's
"spots", a priority or delta time and a 2CADR per phase. Every word is the
assembled rope's, written next to the listing line that makes it, so the C
reads like the listing. A line's EBANK= setting goes with the 2CADR or
BBCON it shapes.

  restart_tables.py          write both files
  restart_tables.py --check  fail if either differs from the listings
"""
import sys
from pathlib import Path

READABLE = Path(__file__).resolve().parents[1]
PORT = READABLE.parent / 'c64-port'
sys.path.insert(0, str(PORT / 'tools'))
from agc_sites_generate import listing_lines  # noqa: E402
from fixed_data_generate import fixed_address, rope_word  # noqa: E402

MISSIONS = (('lm', 'Luminary099'), ('cm', 'Comanche055'))


def generate(key, mission):
    base = PORT / 'build/fixed-data' / mission
    listing = (base / 'assembly.lst').read_text(errors='replace')
    rope = (base / 'MAIN.agc.bin').read_bytes()
    out = ['/* SPDX-License-Identifier: MIT; generated by readable/tools/restart_tables.py',
           f' * from the {mission} listing. Do not edit.',
           ' *',
           ' * RESTART_TABLES, word by word from SIZETAB on, each beside the listing',
           ' * line that makes it. */']
    first, count, ebank = None, 0, ''
    for path, _, address, emitted, label, op, operands in listing_lines(listing):
        if not path.startswith('RESTART_TABLES'):
            continue
        if op == 'EBANK=':
            ebank = operands.split()[0]
            continue
        if not emitted:
            continue
        if op not in ('TC', 'OCT', 'DEC', '2DEC', 'GENADR', '-GENADR', 'BBCON', '2CADR', '-2CADR'):
            break  # the tables end where code (the CM's NEWPHASE) begins
        physical = fixed_address(address)
        if first is None:
            first = physical
        if physical != first + count:
            raise SystemExit(f'{mission}: RESTART_TABLES word {address} out of sequence')
        for k, word in enumerate(emitted):
            if rope_word(rope, physical + k) != word:
                raise SystemExit(f'{mission}: {address} +{k} differs from the rope')
        words = ', '.join(f'0{w:06o}' for w in emitted) + ','
        shown = " ".join(operands.split())
        for default in ((op == 'DEC' and ' B-14'), (op == '2DEC' and ' B-28')):
            if default and shown.endswith(default):  # the assembler's default scale
                shown = shown[:-len(default)]
        text = f'{label:<9} {op:<8}{shown}'
        if op in ('2CADR', '-2CADR', 'BBCON') and ebank:
            text += f'  (EBANK= {ebank})'
        out.append(f'    {words:<18} /* {text.rstrip()} */')
        count += len(emitted)
    out.append(f'#define RESTART_TABLE_WORDS {count}u')
    return '\n'.join(out) + '\n'


def main(argv):
    bad = 0
    for key, mission in MISSIONS:
        text = generate(key, mission)
        path = READABLE / 'src/restart' / f'{key}_restart_tables.inc'
        if '--check' in argv:
            ok = path.exists() and path.read_text() == text
            print('%s: %s %s the %s listing' % ('PASS' if ok else 'FAIL', path.relative_to(READABLE),
                                               'matches' if ok else 'differs from', mission))
            bad |= not ok
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return bad


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
