import json
import pathlib
import sys
import tempfile
import unittest
from unittest import mock

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import restart_acceptance as ra  # noqa: E402

HEAD = 'abc123abc123'
LM = [x[0] for x in ra.frc.RESTARTS if x[1] == 'lm']


def host_row(name, ok=True, at=None):
    at = at if at is not None else next(x[5] for x in ra.frc.RESTARTS if x[0] == name)
    return dict(scenario=name, ok=ok, routine_mismatches=[], new_mismatches=[], modreg=['00077', '00077'],
                redoctr=[0, 1], failures=[] if ok else ['major mode differs'], gojam=[[at, '00000']],
                c64_gojam=dict(ok=True, module=dict(id='0x01e5'), gojam=dict(words_equal=2048),
                               burst=dict(words_equal=2048)))


def replay(at, **kw):
    r = dict(ok=True, commit=HEAD, snap_at=at, replay_matched_cs=[50, 100, 150, 200, 250, 300], replay_differences=0,
             replay_skipped=[], reu_bounds=dict(ok=True, dma_outside=0, outside=[]), records=[1, 2], exit=0)
    r.update(kw)
    return r


class Fake:
    """Stands in for tools/flight_restart_check.py and flight_scenario_vice.py."""

    def __init__(self, host_exit=0, host_rows=None, write_summary=True, vice=None):
        self.host_exit, self.write_summary = host_exit, write_summary
        self.host_rows = host_rows if host_rows is not None else {n: host_row(n) for n in LM}
        self.vice = vice or {}
        self.calls = []

    def __call__(self, args, log):
        self.calls.append(args)
        log.write_text('log\n')
        if args[0] == 'tools/flight_restart_check.py':
            only = args[args.index('--only') + 1].split(',')
            if self.write_summary:
                name = 'summary-gojam-module.json' if '--gojam-module' in args else 'summary.json'
                rows = [self.host_rows[n] for n in only if n in self.host_rows]
                (ra.frc.OUT / name).write_text(json.dumps(rows))
            return self.host_exit
        name, at = args[args.index('--scenario') + 1], int(args[args.index('--snap-cs') + 1])
        r = self.vice.get(name, replay(at))
        if r is not None:
            ra.VICE_RESULT.write_text(json.dumps(r))
        return 0 if r and r.get('ok') else 1


class RestartAcceptance(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        t = pathlib.Path(self.tmp.name)
        for d in ('restart', 'store', 'out', 'docs', 'evidence'):
            (t / d).mkdir()
        self.patches = [mock.patch.object(ra.frc, 'OUT', t / 'restart'), mock.patch.object(ra, 'STORE', t / 'store'),
                        mock.patch.object(ra, 'VICE_RESULT', t / 'store/flight-scenario-vice.json'),
                        mock.patch.object(ra, 'OUT', t / 'out'), mock.patch.object(ra, 'DOCS', t / 'docs'),
                        mock.patch.object(ra, 'EVIDENCE', t / 'evidence'),
                        mock.patch.object(ra, 'prerequisites', lambda: 0)]
        for p in self.patches:
            p.start()
        self.t = t

    def tearDown(self):
        for p in self.patches:
            p.stop()
        self.tmp.cleanup()

    def generate(self, fake, commits=(HEAD, HEAD)):
        """Run main on the fake tools; (exit code, doc text)."""
        it = iter(commits)
        with mock.patch.object(ra, 'tool', fake), mock.patch.object(ra, 'source_commit', lambda: next(it)), \
                mock.patch.object(ra, 'evidence', lambda m, rows: [r.update(evidence='e', sha256='0' * 64) for r in rows]):
            code = ra.main(['lm'])
        return code, (self.t / 'docs/Luminary099-recovery_and_restart_tests.md').read_text()

    def test_all_good_passes(self):
        fake = Fake()
        code, doc = self.generate(fake)
        self.assertEqual(code, 0, doc)
        self.assertIn(f'Generated by `tools/restart_acceptance.py lm` at commit `{HEAD}`. Result: **PASS**', doc)
        vice = [c for c in fake.calls if c[0] == 'tools/flight_scenario_vice.py']
        self.assertTrue(vice)
        for c in vice:
            self.assertIn('--replay-exact', c)
            self.assertIn('--strict-start', c)
        self.assertTrue(any('--gojam-module' in c for c in fake.calls))

    def test_replay_starts_at_the_hosts_gojam_point(self):
        rows = {n: host_row(n) for n in LM}
        rows['lm-rendezvous-restart'] = host_row('lm-rendezvous-restart', at=20007)
        fake = Fake(host_rows=rows)
        self.assertEqual(self.generate(fake)[0], 0)
        call = next(c for c in fake.calls if 'lm-rendezvous-restart' in c and c[0] == 'tools/flight_scenario_vice.py')
        self.assertEqual(call[call.index('--snap-cs') + 1], '20007')

    def test_stale_summary_does_not_count(self):
        (ra.frc.OUT / 'summary.json').write_text(json.dumps([host_row(n) for n in LM]))
        code, doc = self.generate(Fake(host_exit=2, write_summary=False))
        self.assertEqual(code, 1)
        self.assertIn('Result: **FAIL**', doc)
        self.assertIn('exited 2 without this row', doc)

    def test_failed_run_with_passing_rows_fails(self):
        code, doc = self.generate(Fake(host_exit=1))
        self.assertEqual(code, 1)
        self.assertIn('flight_restart_check.py exited 1', doc)

    def test_a_failing_host_row_fails(self):
        rows = {n: host_row(n) for n in LM}
        rows['lm-p12-restart'] = host_row('lm-p12-restart', ok=False)
        code, doc = self.generate(Fake(host_exit=1, host_rows=rows))
        self.assertEqual(code, 1)
        self.assertIn('lm-p12-restart: host', doc)
        self.assertIn('phase group ascent (P12): no row passes', doc)
        self.assertNotIn('lm-p00-doi-restart: host', doc)

    def test_missing_host_row_fails(self):
        rows = {n: host_row(n) for n in LM if n != 'lm-doi-burn-restart'}
        code, doc = self.generate(Fake(host_rows=rows))
        self.assertEqual(code, 1)
        self.assertIn('lm-doi-burn-restart', doc.split('## Why it fails')[1])

    def test_dirty_or_changing_tree_fails(self):
        code, doc = self.generate(Fake(), commits=(HEAD + ' (dirty)', HEAD + ' (dirty)'))
        self.assertEqual(code, 1)
        self.assertIn('results must come from a clean commit', doc)
        code, doc = self.generate(Fake(), commits=(HEAD, 'def456def456'))
        self.assertEqual(code, 1)
        self.assertIn('the tree changed during the run', doc)

    def test_c64_verdicts(self):
        at = 20000
        self.assertTrue(ra.c64_verdict(replay(at), at, HEAD)[0])
        self.assertEqual(ra.c64_verdict(None, at, HEAD)[0], None)
        cases = {
            'skipped': replay(at, replay_skipped=['DSPCNT']),
            'no REU bounds': replay(at, reu_bounds=None),
            'DMAs outside': replay(at, reu_bounds=dict(ok=False, dma_outside=3, outside=[dict(region='rope')])),
            'not at the GOJAM': replay(at, snap_at=at + 400),
            'not abc123': replay(at, commit='def456def456'),
            'differs from the host': replay(at, ok=False, replay_differences=2, replay_differ_at_cs=50),
            'no replay result': dict(ok=False, failure=['VICE timed out']),
            'exited 3': replay(at, exit=3),
        }
        for why, c in cases.items():
            ok, text = ra.c64_verdict(c, at, HEAD)
            self.assertFalse(ok, why)
            self.assertIn(why, text)

    def test_a_c64_skip_fails_the_doc(self):
        fake = Fake(vice={'lm-p12-restart': replay(185000, replay_skipped=['TIME5 a count apart'])})
        code, doc = self.generate(fake)
        self.assertEqual(code, 1)
        self.assertIn('skipped TIME5 a count apart', doc)

    def test_group_needs_a_c64_pass(self):
        fake = Fake(vice={'lm-p00-doi-restart': None})
        code, doc = self.generate(fake)
        self.assertEqual(code, 1)
        self.assertIn('phase group P00: no row passes on the host and the C64', doc)

    def test_gojam_on_c64_failure_fails(self):
        rows = {n: host_row(n) for n in LM}
        rows['lm-dap-hold-restart'] = dict(host_row('lm-dap-hold-restart'), c64_gojam=dict(ok=False))
        code, doc = self.generate(Fake(host_rows=rows))
        self.assertEqual(code, 1)
        self.assertIn('GOJAM on the C64', doc.split('## Why it fails')[1])

    def test_unplaced_row_fails(self):
        with mock.patch.dict(ra.EXTRA, lm=[]):
            code, doc = self.generate(Fake())
        self.assertEqual(code, 1)
        self.assertIn('restart row lm-dap-hold-restart is in no phase group', doc)

    def test_every_restart_row_is_placed(self):
        # A new flight_restart_check.RESTARTS row needs a place here (a group or EXTRA).
        for m in ra.PROGRAM:
            placed = {n for _, ns in ra.GROUPS[m] for n in ns} | set(ra.EXTRA[m])
            rows = {x[0] for x in ra.frc.RESTARTS if x[1] == m}
            self.assertEqual(rows - placed, set(), m)
            self.assertEqual(placed - rows, set(), m)
            self.assertLessEqual(set(ra.GOJAM_ON_C64[m]), rows, m)


if __name__ == '__main__':
    unittest.main()
