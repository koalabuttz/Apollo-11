/* cm-standard-lead-transfer host checks: every standard_lead stage input
 * entered through the registry equals the certified stage; E/BKCALL and
 * E/CALL round trips through the trampoline equal the hand composition of
 * the certified stages, INTER-BANK entries and interpreter controls. */
#include <stdio.h>
#include <string.h>
#include "cm_standard_lead_routines_cases.h"
static unsigned failures,checks;
static bool ctl(apollo_overlay_state *s,cm_native_io *io,enum standard_lead_interp_boundary b){p66_bias_io l;bool ok;l.superbank=io->superbank;l.interrupt_enabled=io->interrupt_enabled;ok=standard_lead_interp_control(s,&l,STANDARD_LEAD_CM,b);if(ok){io->superbank=l.superbank;io->interrupt_enabled=l.interrupt_enabled;}return ok;}
static void check(int ok,const char *what,unsigned n){++checks;if(!ok&&++failures<20)printf("FAIL %s case %u\n",what,n);}
#define STEP(x) do{if(ok&&!(x))ok=0;else if(ok)++done;}while(0)
int main(int argc,char **argv){uint16_t n;unsigned complete[3]={0,0,0};int vectors=argc>1&&!strcmp(argv[1],"--vectors");
 if(vectors)printf("/* Generated by build/test-cm-standard-lead-transfer --vectors. */\nstatic const struct {uint16_t n,stop;uint32_t digest;} cm_slr_expected[]={\n");
 for(n=0;n<CM_SLR_CASES;++n){apollo_overlay_state s,e;cm_native_io io,eio;const agc_native_program *p;agc_word fixed;enum cm_slr_kind kind=cm_slr_input(&s,&io,n,&p,&fixed);enum exec_status status;uint16_t steps=0,stop=(uint16_t)(AGC_TRANSFER_NONE-1u);int ok=1;unsigned done=0;
  e=s;eio=io;
  if(kind==CM_SLR_STAGE){agc_routine r=agc_transfer_resolve(p,&s,io.superbank);int expect=standard_lead_stage(&e,STANDARD_LEAD_CM,(enum standard_lead_phase)(n/512u),fixed);
   check(r!=0,"resolve",n);if(!r)continue;status=r(p,&s,&io);
   check((status==EXEC_OK)==expect&&!memcmp(&s,&e,sizeof s)&&!memcmp(&io,&eio,sizeof io),"stage",n);complete[0]+=(unsigned)expect;
   {apollo_overlay_state t;cm_native_io tio;uint16_t stop1=expect?agc_transfer_point(p,&e,eio.superbank):(uint16_t)(AGC_TRANSFER_NONE-1u);status=cm_slr_run(&t,&tio,n,stop1,1,&steps);
    check(!memcmp(&t,&e,sizeof t)&&(expect?status==EXEC_OK:status!=EXEC_OK),"stage trampoline",n);
    if(vectors&&n%8u==0u)printf(" {%uu,%uu,0x%08lxul},\n",n,stop1,(unsigned long)cm_slr_digest(status,steps,&t,&tio));}
   continue;}
  if(kind==CM_SLR_BKCALL){agc_word cadr=0;
   (void)agc_transfer_operand(p,&e,eio.superbank,(agc_word)(e.words[0133]&07777u),&cadr);
   STEP(standard_lead_stage(&e,STANDARD_LEAD_CM,STANDARD_LEAD_BANK_PREPARE,cadr));
   STEP(cm_interbank_complete(&e,&eio,CM_IC_SWCALL,0,0));
   STEP(agc_transfer_resolve(p,&e,eio.superbank)!=0&&(e.words[0]=05151,e.words[5]=e.words[2],1));
   STEP(cm_interbank_complete(&e,&eio,CM_IC_SWRETURN,0,0));
   STEP(standard_lead_stage(&e,STANDARD_LEAD_CM,STANDARD_LEAD_BANK_RETURN0,0));
  }else{agc_word cadr=0;
   (void)agc_transfer_operand(p,&e,eio.superbank,(agc_word)((e.words[0164]+1u)&07777u),&cadr);
   STEP(standard_lead_stage(&e,STANDARD_LEAD_CM,STANDARD_LEAD_INTERP_PREPARE,cadr));
   STEP(ctl(&e,&eio,STANDARD_LEAD_CALL));
   /* The native callee's body and its closing RVQ are one routine. */
   STEP(agc_transfer_resolve(p,&e,eio.superbank)!=0&&(e.words[0154]=06161,ctl(&e,&eio,STANDARD_LEAD_RVQ)));
   STEP(ctl(&e,&eio,STANDARD_LEAD_EXIT));
   STEP(standard_lead_stage(&e,STANDARD_LEAD_CM,STANDARD_LEAD_INTERP_RESUME,0));
   STEP(ctl(&e,&eio,STANDARD_LEAD_FINISH));
  }
  if(ok)stop=agc_transfer_point(p,&e,eio.superbank);
  {apollo_overlay_state t;cm_native_io tio;status=cm_slr_run(&t,&tio,n,stop,16,&steps);if(vectors&&n%2u==0u)printf(" {%uu,%uu,0x%08lxul},\n",n,stop,(unsigned long)cm_slr_digest(status,steps,&t,&tio));
   if(ok){check(status==EXEC_OK&&steps==done&&!memcmp(&t,&e,sizeof t)&&!memcmp(&tio,&eio,sizeof tio),kind==CM_SLR_BKCALL?"E/BKCALL trip":"E/CALL trip",n);++complete[kind];}
   else check(((status==EXEC_UNMAPPED&&steps==done)||(status!=EXEC_OK&&status!=EXEC_UNMAPPED&&steps==done+1u))&&!memcmp(&t,&e,sizeof t),"refused trip",n);
  }
 }
 if(vectors){printf("};\n#define CM_SLR_TARGET_CASES (sizeof cm_slr_expected/sizeof cm_slr_expected[0])\n");return failures?1:0;}
 check(complete[1]>=256u&&complete[2]>=256u,"round trips exercised",complete[1]*1000u+complete[2]);
 printf("cm-standard-lead-transfer: %u cases (%u stages accepted, %u E/BKCALL and %u E/CALL round trips), %u checks, %u failures\n",CM_SLR_CASES,complete[0],complete[1],complete[2],checks,failures);
 return failures?1:0;
}
