"""Freeze oracle rows for the host check and the C64 diagnostic: for each
selected case, the oracle's status and every image word that differs from the
case input (tests/cm_tvc_massprop_vectors.h). Reads the delta stream that
tools/cm_tvc_massprop_differential.py keeps; never runs the native code."""
import pathlib,struct,hashlib,subprocess,lzma,sys
R=pathlib.Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'tools'))
from frozen_words import encode_rows,c_header
ROW=2052*2
cases={};path=R/'build/cm-tvc-massprop-reference.deltas.xz'
if not path.exists():path=R/'evidence/cm-tvc-massprop/cm-tvc-massprop-reference.deltas.xz'
with lzma.open(path,'rb') as f:
 h=hashlib.sha256()
 while head:=f.read(10):
  w=struct.unpack('<5H',head);body=f.read(4*w[4]);h.update(head+body);cases[w[0]|w[1]<<16]=(w,struct.unpack(f'<{2*w[4]}H',body))
# Both entries x every DAPDATR1 class x LEM/descent bits x mass modes, plus
# the first non-returning cases.
chosen=sorted({n for n in range(65536) if (n>>9)==0 and (n>>6)&3 in(0,2) and n&0x0c==(n>>4&3)*4}|{n for n in range(64,128)})
extra=[n for n in sorted(cases) if cases[n][0][2]==2][:16]
chosen=sorted(set(chosen)|set(extra))[:128]
rows=[]
for k,n in enumerate(chosen):
 w,pairs=cases[n];rows.append([n&65535,n>>16,w[2],w[3],w[4],*pairs])
width=max(map(len,rows));packed=encode_rows([r+[0]*(width-len(r)) for r in rows])
s=('/* SPDX-License-Identifier: MIT\n * Generated by tools/cm_tvc_massprop_freeze.py from the oracle delta stream SHA256:'+h.hexdigest()+' */\n'
   '#ifndef CM_TVC_MASSPROP_VECTORS_H\n#define CM_TVC_MASSPROP_VECTORS_H\n'+c_header(packed,'cm_tvc_massprop')+'#endif\n')
(R/'tests/cm_tvc_massprop_vectors.h').write_text(s)
print(len(rows),'rows',sum(1 for r in rows if r[2]),'non-returning',packed.storage_bytes,'bytes')
