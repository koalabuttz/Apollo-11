"""Run the original-program oracle for lm-trim-gimbal and freeze digests.

Builds the host-only yaAGC driver tools/lm_trim_gimbal_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-trim-gimbal-native) is byte-identical on every case the native
routines accept, and writes tests/lm_trim_gimbal_vectors.h (one digest per
case: two 16-bit running sums over the outcome, channel 12 and all 2048
erasable words) and tests/lm_trim_gimbal_c64_vectors.h (every
thirty-second). GTS cases the native routine refuses (the zero root with
INDEX SHFTFLAG outside BIT15-BIT2) are left out of the comparison; their
digest is of the unchanged input image, which the host test checks. Also
writes build/lm-trim-gimbal-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_trim_gimbal.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
          'src/lm_interbank_routines.c', 'src/lm_interbank.c', 'src/agc_transfer.c', 'src/agc_multiword.c',
          'tests/lm_trim_gimbal_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Itools', '-I' + str(E)]
STRIDE = 32
REFUSED = 2


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_trim_gimbal_reference.c', *CORE,
                    '-o', 'build/lm-trim-gimbal-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-trim-gimbal-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-trim-gimbal-native'], cwd=R, check=True, capture_output=True).stdout
    rrows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    nrows = [list(map(int, line.split())) for line in nat.decode().splitlines()]
    assert [r[0] for r in rrows] == [r[0] for r in nrows] == list(range(len(nrows)))
    compared = [n for n in nrows if n[1] != REFUSED]
    for n in compared:
        assert n == rrows[n[0]], f'lm-trim-gimbal case {n[0]}: native differs from the original program'
    refused = [n[0] for n in nrows if n[1] == REFUSED]
    assert all(n % 4 == 0 for n in refused)
    digests = [digest(r[1:]) for r in nrows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_trim_gimbal_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channel 12 and all 2048 erasable words (a refused GTS case: its',
           ' * unchanged input image). */',
           f'#define LM_TG_VECTORS {len(digests)}u', *table('lm_tg_expected', digests)]
    (R / 'tests/lm_trim_gimbal_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_trim_gimbal_freeze.py: every',
           ' * thirty-second digest of tests/lm_trim_gimbal_vectors.h, for the C64 diagnostic. */',
           f'#define LM_TG_C64_STRIDE {STRIDE}u', f'#define LM_TG_C64_COUNT {len(c64)}u',
           *table('lm_tg_c64', c64)]
    (R / 'tests/lm_trim_gimbal_c64_vectors.h').write_text('\n'.join(out) + '\n')
    names = ['GTS', 'ACDT+C12', 'TIMEGMBL', '21,3435']
    outcome = ['returned', 'closeout', 'refused', 'none']
    kinds = collections.Counter(f"{names[r[0] % 4]}:{outcome[r[1]]}" for r in nrows)
    oracle_refused = collections.Counter(outcome[rrows[n][1]] for n in refused)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(nrows), 'compared_cases': len(compared),
             'compared_sha256': hashlib.sha256('\n'.join(' '.join(map(str, n)) for n in compared).encode()).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'refused_gts_cases': len(refused), 'refused_gts_oracle_outcomes': dict(sorted(oracle_refused.items())),
             'entries': ['21,3077 GTS', '16,3736 ACDT+C12', '21,3330 TIMEGMBL', '21,3435'],
             'boundary': "each entry from a random image (FB bank 21 or 16, EB 6, random channel 12, trim gimbal "
                         "inputs of random widths) to GTS's DTCB to CLOSEOUT, ACDT+C12's TC Q, TIMEGMBL's IBNKCALL "
                         "arriving at ACDT+C12, or 21,3435's TC RUPTREG2; compared: outcome, channel 12 and all "
                         "2048 erasable words",
             'full_physical_words': 2048}
    (B / 'lm-trim-gimbal-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(compared)} lm-trim-gimbal cases equal the original program '
          f'({len(refused)} GTS cases refused): {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
