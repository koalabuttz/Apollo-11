"""Write tests/lm_servicer_chains.h: the lm-servicer continuation cases.

The C64 build of src/lm_servicer.c is split into segment groups
(LMSV_C64_GROUP): a group's run of a case stops before the first word
another group holds, where the whole-file build runs on. The code a
whole-file case runs only after such a crossing is taken by no group's
cases, so for each case of BASES this follows the case across every
segment end: the host build of the group holding the case's key runs it,
and when the run stops at a word of the file (lmsv_leaves() false, so the
original runs on), the image it leaves, its channels and interrupt state
become a continuation case at the key there, as edits to the base case's
image. Continuations are themselves followed until the run leaves the file
or is refused. A continuation's image is stored as edits to its first
base case's image (the case of BASES it continues), and only in the
builds of the group that runs it, so each C64 group holds only its own.
Case LMSV_BASE_CASES + j is continuation j
(tests/lm_servicer_cases.c); tools/lm_servicer_freeze.py checks every one
against the original program like any other case.

BASES are whole-file cases that take a branch outcome (gcov -b over every
linked source) only after crossing a segment end (#167); the comment says
which.

  python3 tools/lm_servicer_chains.py      (from c64-port/)
"""
import pathlib
import re
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
sys.path.insert(0, str(R / 'tools'))
import lane_f_c64_rows  # noqa: E402

BASES = [
    2091,   # 33,2730 CALCGRAV: lm_interp_orders.c VSQ/UNIT tail (c != 1) after the segment end
    2723,   # 33,2732: GENSCR's CCS +0 (ROUNDSUB) and its default arm
    3995,   # 33,2764: the INDJUMP to erasable in lm_interp_steps.c
    5581,   # 33,3012: DDV's BZF (FINALDV3)
    16643,  # 33,3130 MUNGRAV: SMPAC after a zero shift count
    27810,  # 33,3466 USEVF: TS overflow returns in the DP store
    31095,  # 33,3007: TS rZERO's overflow return
    36432,  # 33,2743: a zero dividend (DANZIG)
    1165,   # 33,2776: PUSHLOC past the work area (refused)
]
NATIVE = ['src/lm_servicer.c', 'src/lm_interp_orders.c', 'src/lm_interp_steps.c', 'src/agc_image_ops.c',
          'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c',
          'tests/lm_servicer_cases.c']
PROBE = r'''#include <stdio.h>
#include <stdlib.h>
#include "lm_servicer_cases.h"
int main(int argc,char **argv){int a;unsigned i;
 for(a=1;a<argc;++a){apollo_overlay_state in,out;lmsv_case c,o;uint16_t n=(uint16_t)atoi(argv[a]);unsigned kind;
  lmsv_input(&in,&c,n);kind=lmsv_run(&out,n,&o);
  printf("%u %u %d %u %u",n,kind,kind==0u&&lmsv_leaves(out.words[5],(agc_word)(out.words[4]&076000u),c.superbank,
         out.words[2],out.words[0164],out.words[0165]),(unsigned)c.superbank,
         (unsigned)agc_fixed_physical(out.words[5]==06070u?out.words[0164]:out.words[5],
                                      out.words[5]==06070u?out.words[0165]:out.words[4],c.superbank));
  printf(" %u %u %u %u %u",(unsigned)o.chan11,(unsigned)o.chan12,(unsigned)o.chan32,(unsigned)o.chan33,
         (unsigned)o.interrupt_enabled);
  for(i=0;i<2048u;++i)printf(" %u",(unsigned)(in.words[i]&(i<2u?0177777u:077777u)));
  for(i=0;i<2048u;++i)printf(" %u",(unsigned)(out.words[i]&(i<2u?0177777u:077777u)));
  putchar('\n');}
 return 0;}
'''
BASE_CASES = 40320


def keys():
    src = (R / 'src/lm_servicer.c').read_text()
    body = re.search(r'lmsv_routine_keys\[LMSV_ROUTINES\]=\{(.*?)\};', src, re.S).group(1)
    return [int(b, 8) * 1024 + int(a, 8) - 0o2000 for b, a in re.findall(r'K(\d\d)\((0[0-7]+)\)', body)]


def write(chains, slot_group):
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_servicer_chains.py: the lm-servicer',
           ' * continuation cases (tests/lm_servicer_cases.h). Continuation j starts where a run of',
           ' * case lmsv_chain_base[j] (a base case) reaches the end of a C64 segment group, at key slot',
           ' * lmsv_chain_slot[j], with that run\'s image (the base image with the lmsv_chain_edits[j]',
           ' * words, address and value, lmsv_chain_count[j] of them), channels 11, 12, 32 and 33 and',
           ' * interrupt state (lmsv_chain_io[j]). A group\'s build holds only its own continuations\'',
           ' * edits. */',
           f'#define LMSV_CHAINS {len(chains)}u']
    out.append('static const uint16_t lmsv_chain_base[LMSV_CHAINS+1u]={%s0};' % ''.join(f'{c[0]}u,' for c in chains))
    out.append('static const uint16_t lmsv_chain_slot[LMSV_CHAINS+1u]={%s0};' % ''.join(f'{c[1]}u,' for c in chains))
    for j, c in enumerate(chains):
        out.append(f'#if !defined(LMSV_C64_GROUP)||LMSV_C64_GROUP=={slot_group[c[1]]}')
        out.append(f'static const uint16_t lmsv_chain_e{j}[{len(c[3])}][2]={{')
        for i in range(0, len(c[3]), 8):
            out.append(''.join(f'{{{a}u,0{v:o}u}},' for a, v in c[3][i:i + 8]))
        out.append('};')
        out.append(f'#define LMSV_CHAIN_E{j} lmsv_chain_e{j}')
        out.append('#else')
        out.append(f'#define LMSV_CHAIN_E{j} 0')
        out.append('#endif')
    out.append('static const uint16_t (*const lmsv_chain_edits[LMSV_CHAINS+1u])[2]={%s0};' % ''.join(
        f'LMSV_CHAIN_E{j},' for j in range(len(chains))))
    out.append('static const uint16_t lmsv_chain_count[LMSV_CHAINS+1u]={%s0};' % ''.join(
        f'{len(c[3])}u,' for c in chains))
    out.append('static const uint16_t lmsv_chain_io[LMSV_CHAINS+1u][5]={%s{0,0,0,0,0}};' % ''.join(
        '{%s},' % ','.join(f'0{v:o}u' for v in c[2]) for c in chains))
    (R / 'tests/lm_servicer_chains.h').write_text('\n'.join(out) + '\n')
    h = R / 'tests/lm_servicer_cases.h'
    h.write_text(re.sub(r'^#define LMSV_CASES \d+u$', f'#define LMSV_CASES {BASE_CASES + len(chains)}u',
                        h.read_text(), flags=re.M))


def probe(group, cases):
    exe = B / f'lm-servicer-chain-probe-g{group}'
    (B / 'lm-servicer-chain-probe.c').write_text(PROBE)
    subprocess.run(['cc', '-std=c99', '-O1', '-w', '-Iinclude', '-Itests', '-Isrc', '-DP66_NATIVE_DISPATCH_ONLY',
                    f'-DLMSV_C64_GROUP={group}', *NATIVE, str(B / 'lm-servicer-chain-probe.c'), '-o', str(exe)],
                   cwd=R, check=True)
    lines = subprocess.run([str(exe), *map(str, cases)], cwd=R, check=True, capture_output=True,
                           text=True).stdout.splitlines()
    return [list(map(int, ln.split())) for ln in lines]


def main():
    B.mkdir(exist_ok=True)
    slot_group = lane_f_c64_rows.servicer_slots()
    key_slot = {ph: i for i, ph in enumerate(keys())}
    chains, slot_of, root, image = [], {}, {}, {}

    def slot(n):
        return n % len(slot_group) if n < BASE_CASES else slot_of[n]
    write(chains, slot_group)
    todo = list(BASES)
    while todo:
        by = {}
        for n in todo:
            by.setdefault(slot_group[slot(n)], []).append(n)
        todo = []
        for g in sorted(by):
            for v in probe(g, by[g]):
                n, kind, leaves, superbank, ph = v[:5]
                io, before, after = v[5:10], v[10:10 + 2048], v[10 + 2048:]
                if n < BASE_CASES:
                    root[n], image[n] = n, before
                if kind != 0 or leaves:
                    print(f'case {n}: {"refused" if kind else "leaves the file"} in group {g}')
                    continue
                if ph not in key_slot:
                    sys.exit(f'case {n} stops at the end of group {g} on a word that is no key ({ph:o})')
                edits = [(i, w) for i, (x, w) in enumerate(zip(image[root[n]], after)) if x != w]
                chains.append((root[n], key_slot[ph], io, edits))
                m = BASE_CASES + len(chains) - 1
                slot_of[m], root[m] = key_slot[ph], root[n]
                print(f'case {n}: crosses from group {g} to group {slot_group[key_slot[ph]]} at '
                      f'{ph // 1024:o},{ph % 1024 + 0o2000:o}: continuation {m}, {len(edits)} words')
                todo.append(m)
        write(chains, slot_group)
    print(f'{len(chains)} continuations in tests/lm_servicer_chains.h')


if __name__ == '__main__':
    main()
