"""Generate (or, with --check, verify) tests/lm_trim_gimbal_ca_table.inc.

After GTSQRT's zero root, DOSHIFT's INDEX SHFTFLAG indexes CA BIT15
(21,3546, word 34735) by ACENTRAL/2, because ININDEX and ACENTRAL are one
cell. For every index that leaves the word a CA (30000-37777) the original
reads the word at 04735 + k: erasable memory below 02000 (read from the
image), bank 21 at 02000-03777 (GTS runs under FB 21) or fixed-fixed
04000-07777. This writes those fixed words, in that order, from the
certified Luminary099 rope (evidence/fixed-data-lm-original.rope.bin, which
tools/lm_trim_gimbal_source.py requires to equal a fresh yaYUL assembly).
"""
import pathlib
import sys

R = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / 'tools'))
from fixed_data_generate import rope_word  # noqa: E402

OUT = R / 'tests/lm_trim_gimbal_ca_table.inc'


def render():
    rope = (R / 'evidence/fixed-data-lm-original.rope.bin').read_bytes()
    words = [rope_word(rope, 0o21 * 1024 + a - 0o2000) for a in range(0o2000, 0o4000)]
    words += [rope_word(rope, 2048 + a - 0o4000) for a in range(0o4000, 0o10000)]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_trim_gimbal_ca_table.py from the',
           ' * certified Luminary099 rope: the fixed words DOSHIFT\'s INDEX SHFTFLAG; CA BIT15 reads',
           ' * after the zero root (bank 21 02000-03777, then fixed-fixed 04000-07777). */',
           f'static const agc_word gts_ca_fixed[{len(words)}]={{']
    for i in range(0, len(words), 10):
        out.append(''.join(f'0{w:o}u,' if w else '0u,' for w in words[i:i + 10]))
    out.append('};')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        if OUT.read_text() != text:
            raise SystemExit('FAIL tests/lm_trim_gimbal_ca_table.inc differs from the certified rope')
        print('PASS tests/lm_trim_gimbal_ca_table.inc equals the certified rope (3072 words)')
    else:
        OUT.write_text(text)
