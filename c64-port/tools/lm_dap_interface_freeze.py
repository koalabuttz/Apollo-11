"""Run the original-program oracle for lm-dap-interface and freeze digests.

Builds the host-only yaAGC driver tools/lm_dap_interface_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-dap-interface-native) is byte-identical, and writes
tests/lm_dap_interface_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and all 2048 erasable words) and
tests/lm_dap_interface_c64_vectors.h (every sixteenth). Also writes
build/lm-dap-interface-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_dap_interface.c', 'src/lm_exec_routines.c', 'src/lm_admission_image.c',
          'src/lm_waitlist_image.c', 'src/waitlist.c', 'src/executive.c', 'src/p66_native.c',
          'src/agc_transfer.c', 'src/agc_multiword.c', 'tests/lm_dap_interface_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_dap_interface_reference.c', *CORE,
                    '-o', 'build/lm-dap-interface-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-dap-interface-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-dap-interface-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-dap-interface: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_dap_interface_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and all 2048 erasable words. */',
           f'#define LM_DAP_VECTORS {len(digests)}u', *table('lm_dap_expected', digests)]
    (R / 'tests/lm_dap_interface_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_dap_interface_freeze.py: every',
           ' * sixteenth digest of tests/lm_dap_interface_vectors.h, for the C64 diagnostic. */',
           f'#define LM_DAP_C64_STRIDE {STRIDE}u', f'#define LM_DAP_C64_COUNT {len(c64)}u',
           *table('lm_dap_c64', c64)]
    (R / 'tests/lm_dap_interface_c64_vectors.h').write_text('\n'.join(out) + '\n')
    names = ['RESTORDB', 'SETMAXDB', 'SETMINDB', 'PFLITEDB', 'ZATTEROR', 'STOPRATE', 'ALLCOAST']
    kinds = collections.Counter()
    for r in rows:
        kinds[f"{names[r[0] % 7]}:{('returned', 'alarm')[r[1]]}"] += 1
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['20,2123 RESTORDB', '20,2124 RESTORDB+1', '20,2127 SETMAXDB', '20,2137 CALLACCS+4',
                         '20,2140 SETMINDB', '20,2142 PFLITEDB', '20,2145 PFLITEDB+3', '20,2153 ZATTEROR',
                         '20,2165 STOPRATE', '20,2204 ALLCOAST', '20,2207 ALLCOAST+3', '20,2225 ALLCOAST+17'],
             'boundary': 'each entry from a random image (FB bank 20, random EB, superbank and DAPBOOLS) to the '
                         "caller's return in Q (SWRETURN, fixed-fixed or bank 20), through the native NOVAC for "
                         '1/ACCJOB; alarm: BAILOUT1 entry (1202, no core set)',
             'full_physical_words': 2048}
    (B / 'lm-dap-interface-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-dap-interface cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
