"""Run unchanged Luminary099 in the pinned yaAGC oracle from every lm-s3435
case (tests/lm_s3435_cases.c) to its first stop, check the native trampoline
run of the S34/35 routines against every row, pin the stream identity, and
freeze per-case digests: tests/lm_s3435_vectors.h (all cases, and the two
C64 groups' samples). Archives the oracle stream as
build/lm-s3435-reference.snapshots.bin.xz and writes build/lm-s3435-proof.json
with the stops per routine. --record rewrites the pinned identity."""
import argparse,collections,hashlib,json,lzma,pathlib,struct,subprocess,sys
R=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(R/'tools'))
from lm_s3435_core import CORE,CASES
ROW=4106;STRIDE=32;ROUTINES=4;STATES=ROUTINES*4096
PIN=R/'evidence/lm-s3435/lm-s3435-source-stream.json'
NAMES=['S34/35.1 (3274)','NOVRWRT (3424)','S34/35.4 (3442)','LOMAT (3447)']
def digest(vals):
 a=b=0
 for v in vals:a=(a+v)&0xffff;b=(b+a)&0xffff
 return b<<16|a
def table(name,values):
 out=[f'static const uint32_t {name}[{len(values)}]={{']
 for i in range(0,len(values),6):out.append(''.join(f'0x{v:08x}ul,'for v in values[i:i+6]))
 return out+['};']
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--record',action='store_true');a=p.parse_args()
(R/'build').mkdir(exist_ok=True)
# CI runs a spec's test- and sanitize- targets at once; both rebuild these build/ outputs, so one waits.
import fcntl;LOCK=open(R/'build'/(pathlib.Path(__file__).stem+'.lock'),'w');fcntl.flock(LOCK,fcntl.LOCK_EX)
if not (R/'build/agc_engine_hardware_dv.o').exists():subprocess.run([sys.executable,'tools/prepare_hardware_dv.py'],cwd=R,check=True)
subprocess.run(['gcc','-std=c99','-O2','-DLM_S3435_NO_TRAMPOLINE','-Iinclude','-Itests','-Ideps/virtualagc/yaAGC','-Itools','tools/lm_s3435_reference.c',*CASES,'tests/cm_executive_cases.c','src/agc_word.c','build/agc_engine_hardware_dv.o','deps/virtualagc/yaAGC/agc_engine_init.o','deps/virtualagc/yaAGC/rfopen.o','-lm','-o','build/lm-s3435-reference'],cwd=R,check=True)
subprocess.run(['cc','-std=c99','-O2','-Wall','-Wextra','-Werror','-Wconversion','-pedantic','-Iinclude','-Itests','tools/lm_s3435_snapshot.c',*CORE,'-lm','-o','build/lm-s3435-native'],cwd=R,check=True)
ref=subprocess.Popen(['build/lm-s3435-reference','deps/lm-rtb-fixture/MAIN.agc.bin',str(STATES)],cwd=R,stdout=subprocess.PIPE)
nat=subprocess.Popen(['build/lm-s3435-native',str(STATES)],cwd=R,stdout=subprocess.PIPE)
out_path=R/'build/lm-s3435-reference.snapshots.bin.xz';tmp=out_path.with_suffix('.xz.part');archive=lzma.open(tmp,'wb',preset=6)
h=hashlib.sha256();size=0;tags=collections.Counter();digests=[];stops=collections.defaultdict(collections.Counter)
for n in range(STATES):
 x=ref.stdout.read(ROW);y=nat.stdout.read(ROW)
 if len(x)!=ROW or x!=y:
  ref.kill();nat.kill()
  if len(x)==ROW==len(y):
   X=struct.unpack('<2053H',x);Y=struct.unpack('<2053H',y)
   print('FAIL case',n,[(f'{i-5:04o}',f'{v:06o}',f'{Y[i]:06o}')for i,v in enumerate(X)if v!=Y[i]][:25])
  else:print('FAIL case',n,'short row')
  raise SystemExit(1)
 X=struct.unpack('<2053H',x);h.update(x);archive.write(x);size+=len(x);tags[X[4]]+=1
 digests.append(digest([X[4],*X[5:],X[2]]))
 w=X[5:]
 if w[5]==0o6070:
  fb=w[4]&0o76000;name=f'NEWOPS 35,{w[0o164]:04o}' if fb==0o72000 else 'NEWOPS of a CADR in another bank'
 else:name='POODOO1 (1302)'
 stops[NAMES[n%ROUTINES]][name]+=1
if ref.stdout.read(1)or nat.stdout.read(1)or ref.wait()or nat.wait():raise SystemExit('FAIL producer exit or trailing bytes')
archive.close();tmp.replace(out_path)
identity=dict(archive='build/lm-s3435-reference.snapshots.bin.xz',decoded_sha256=h.hexdigest(),decoded_bytes=size,cases=STATES,tag_counts={str(k):v for k,v in sorted(tags.items())},oracle='pinned yaAGC hardware-DV variant, deps/lm-rtb-fixture/MAIN.agc.bin (unchanged Luminary099)')
if a.record:PIN.parent.mkdir(parents=True,exist_ok=True);PIN.write_text(json.dumps(identity,indent=2)+'\n')
pin=json.loads(PIN.read_text())
if (pin['decoded_sha256'],pin['decoded_bytes'])!=(identity['decoded_sha256'],size):raise SystemExit('FAIL oracle stream differs from the pinned identity')
head=['/* SPDX-License-Identifier: MIT; generated by tools/lm_s3435_differential.py: digests of the',' * original Luminary099 run of every lm-s3435 case (see tests/lm_s3435_cases.h). */',f'#define LM_S3435_C64_STRIDE {STRIDE}u']
# C64 group 1 samples S34/35.1 and LOMAT, group 2 NOVRWRT and S34/35.4: case
# k*STRIDE plus the group's two routines in turn.
GROUPS={1:(0,3),2:(1,2)};c64={g:[k*STRIDE+r[k%2]for k in range(STATES//STRIDE)]for g,r in GROUPS.items()}
lines=[*head,f'#define LM_S3435_VECTORS {len(digests)}u',f'#define LM_S3435_C64_CASES {STATES//STRIDE}u','#ifndef LM_S3435_C64_GROUP',*table('lm_s3435_expected',digests)]
for g,r in GROUPS.items():lines+=[f'#elif LM_S3435_C64_GROUP=={g}',f'#define LM_S3435_C64_FIRST {r[0]}u',f'#define LM_S3435_C64_SECOND {r[1]}u',*table('lm_s3435_expected',[digests[n]for n in c64[g]])]
(R/'tests/lm_s3435_vectors.h').write_text('\n'.join([*lines,'#endif'])+'\n')
proof=dict(cases=STATES,c64_groups={str(g):len(v)for g,v in c64.items()},stream_sha256=h.hexdigest(),stops={k:dict(sorted(v.items()))for k,v in stops.items()},boundary='each case runs from its routine\'s NEWOPS through the trampoline (the four S34/35 routines) to the first point outside them; the oracle stops at the same NEWOPS outside the routines or at UNIT\'s POODOO1',compared='2048 erasable words (A, L 16-bit), the interrupt-enable state and SUPERBNK')
(R/'build/lm-s3435-proof.json').write_text(json.dumps(proof,indent=1)+'\n')
print(f'PASS {STATES} original S34/35 routine entries equal native trampoline runs',h.hexdigest(),flush=True)
