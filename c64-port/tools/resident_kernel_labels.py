"""Write the address and constant macros of the resident kernel
(src/resident_kernel_body.inc) for each mission from the yaYUL listing:
src/lm_kernel_labels.inc (Luminary099) and src/cm_kernel_labels.inc
(Comanche055).

Each K_<name> is the logical address an instruction names (fixed labels as
the 12-bit Z value, erasable labels as the 10-bit operand under EB), and
each KW_<name> the fixed word at a constant's label. A name missing from a
mission's listing is left undefined; the body uses it only under that
mission's #if.

Usage: resident_kernel_labels.py [--check]"""
import os
import re
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import interp_listing as IL

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MISSIONS = (('lm', 'Luminary099'), ('cm', 'Comanche055'))

# Code labels (EXECUTIVE.agc, WAITLIST.agc and the outside addresses they
# transfer to). Names are the source labels; the macro replaces '.', '-',
# '+' and '/'.
CODE = '''NOVAC FINDVAC SPVACIN SPVAC CHANG1 CHANG2 JOBSLEEP JOBWAKE PRIOCHNG ENDOFJOB
ENDFIND FINDVAC2 VACFOUND NOVAC2 NOVAC3 CORFOUND SPECTEST SETLOC NEXTCORE CHANJOB ENDPRCHG
JOBSLP1 JOBSLP2 NUCHANG2 JOBWAKE2 JOBWAKE4 JOBWAKE3 WAKETEST PRIOCH2 ENDJOB1 EJSCAN EJ1 EJ2
DUMMYJOB ADVAN NUDIRECT SUPDXCHZ
TWIDDLE WAITLIST DLY2 LVWTLIST FIXDELAY VARDELAY SVCT3 SVCT3X TASKOVER RESUME NOQRSM
NOQBRSM LONGCALL WAIT2 WTLST5 WTLST2 WTLST4 WTABORT FILLED T3RUPT T3RUPT2 LNGCALL2
LONGCYCL DPBIT14 LASTTIME LONGRTRN MUCHTIME GETCADR LONGPOOH WAITPOOH WATLST0-
INTRSM NEWOPS NEG CCSHOLE BAILOUT1 BAILOUT POODOO1 POODOO'''.split()
# Erasable labels.
ERASABLE = '''NEWPRIO LOCCTR NEWLOC NEWJOB EXECTEM1 EXECTEM2 MPAC LOC BANKSET PUSHLOC PRIORITY
FIXLOC OVFIND BUF VAC1USE INTBIT15 EDOP WAITEXIT WAITADR WAITTEMP WAITBANK TIME3 LST1 LST2
RUPTAGN ARUPT LRUPT QRUPT ZRUPT BANKRUPT FLAGWRD2 IMUCADR LONGCADR LONGTIME LONGEXIT
SELFRET'''.split()
# Constants the code reads with CAF/AD/MASK/DCS (one word, or two for -2CADR).
WORDS = '''EXECBANK FAKEPRET NO.CORES COREINC -CCSPR LOW9 LOW7 FBANKMSK 2K ZERO ONE TWO NEG2
NEG1/2 POSMAX BIT8 BIT14 POS1/2 NEGMAX OCT40001 OCT40201 WAITBB DELAYEX PRIO35 SELFBANK
TSKOVCDR T3RPTBB'''.split()
WORDS2 = 'ENDTASK DPBIT14 LGCL2CDR'.split()

SYM = re.compile(r'([A-Za-z0-9.+/*&=-]+)\s+(?:(E[0-7]),)?([0-7]{4})\b')


def macro(name):
    return name.replace('.', '_').replace('-', 'M').replace('+', 'P').replace('/', '_')


def erasable_table(path):
    """{label: logical erasable address} from the listing's symbol table."""
    out = {}
    text = open(path, errors='replace').read()
    tail = text[text.index('Symbol Table'):]
    for line in tail.splitlines():
        for part in line.split('\t'):
            part = part.strip()
            m = re.match(r'^\d+,E:\s+(\S+)\s+(?:E([0-7]),)?([0-7]{4})$', part)
            if m:
                out.setdefault(m.group(1), int(m.group(3), 8))
            m = re.match(r'^\d+,C:\s+(\S+)\s+([0-7]{7})$', part)
            if m and int(m.group(2), 8) < 0o2000:
                out.setdefault(m.group(1), int(m.group(2), 8))
    return out


def logical(phys):
    bank, off = divmod(phys, 1024)
    return 0o4000 + (bank - 2) * 1024 + off if bank in (2, 3) else 0o2000 + off


def generate(key, program):
    path = os.path.join(HERE, IL.LISTINGS[key])
    L = IL.Listing(path)
    eras = erasable_table(path)
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/resident_kernel_labels.py',
           ' * from the %s listing. Do not edit. */' % program]
    for n in CODE:
        if n in L.labels:
            out.append('#define K_%s 0%04ou' % (macro(n), logical(L.labels[n])))
    for n in ERASABLE:
        if n in eras:
            out.append('#define K_%s 0%04ou' % (macro(n), eras[n]))
        else:
            raise SystemExit('%s: erasable %s not in the symbol table' % (program, n))
    for n in WORDS:
        if n in L.labels:
            out.append('#define KW_%s 0%05ou' % (macro(n), L.word(L.labels[n])))
    for n in WORDS2:
        if n in L.labels:
            p = L.labels[n]
            out.append('#define KW_%s {0%05ou,0%05ou}' % (macro(n), L.word(p), L.word(p + 1)))
    return '\n'.join(out) + '\n'


def main(argv):
    check = '--check' in argv
    bad = 0
    for key, program in MISSIONS:
        text = generate(key, program)
        dst = os.path.join(HERE, 'src', '%s_kernel_labels.inc' % key)
        if check:
            if not os.path.exists(dst) or open(dst).read() != text:
                print('FAIL: %s differs from the %s listing' % (os.path.relpath(dst, HERE), program))
                bad = 1
            else:
                print('PASS: %s matches the %s listing' % (os.path.relpath(dst, HERE), program))
        else:
            open(dst, 'w').write(text)
    return bad


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
