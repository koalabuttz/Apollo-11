"""Run the original-program oracle for lm-downtelemetry and freeze digests.

Builds the host-only yaAGC driver (tools/lm_downtelemetry_reference.c), runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-downtelemetry-native) is byte-identical, and writes
tests/lm_downtelemetry_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and every second digest to
tests/lm_downtelemetry_c64_vectors.h. Also writes build/lm-downtelemetry-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
CORE = ['tests/lm_downtelemetry_cases.c', 'src/lm_downtelemetry.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
        'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/lm_downtelemetry_reference.c', *CORE, '-o', 'build/lm-downtelemetry-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/lm-downtelemetry-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-downtelemetry-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_downtelemetry_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of channels 13,',
           ' * 34 and 35 after every downrupt, the channel-13 traps and all 2048 erasable words. */',
           f'#define LM_DNTM_VECTORS {len(values)}u']
    table(out, 'lm_dntm_expected', values)
    (R / 'tests/lm_downtelemetry_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_downtelemetry_freeze.py: every',
           ' * second digest of tests/lm_downtelemetry_vectors.h, for the C64 diagnostic. */',
           '#define LM_DNTM_C64_STRIDE 2u', f'#define LM_DNTM_C64_COUNT {len(values[::2])}u']
    table(c64, 'lm_dntm_c64', values[::2])
    (R / 'tests/lm_downtelemetry_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': ['05,3506 DODOWNTM', 'DNTMGOTO (erasable 0335)', '05,3515 DNPHASE1', '05,3523 DNPHASE2',
                         '05,3707 DNDUMPI', '05,3712 DNDUMPI+3', '05,3722 DNDUMP', '05,3735 DNDUMP1'],
             'downrupts': sum(len(r) - 1 - 3 - 2048 for r in rows) // 3,
             'boundary': 'DOWNRUPT lead-in state at DODOWNTM to TCF RESUME, for every downrupt of each case',
             'full_physical_words': 2048}
    (B / 'lm-downtelemetry-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program')


if __name__ == '__main__':
    main()
