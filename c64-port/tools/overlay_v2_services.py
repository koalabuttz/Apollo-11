"""Generate the ABI 2 resident service jump table and the module import map.

docs/overlay-v2-services.json lists resident C functions in table order. The
resident links build/overlay_v2_services.S (one JMP per entry at $6F00); every
module links build/overlay_v2_services.ld, which defines each name as the
absolute address of its JMP, so module code calls the one resident copy with
the normal C ABI instead of linking its own."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Entries each minor version has: later versions only append, so a build whose
# resident does not carry the flight runtime (the legacy ABI 2 proofs, the
# resident flight checks) links an earlier version's prefix.
FIRST_ENTRIES = {2: 3, 3: 24}


def generate(spec):
    names = spec['services']
    if len(set(names)) != len(names):
        raise SystemExit('duplicate service name')
    if spec['entry_bytes'] != 3 or len(names) * 3 > 256:
        raise SystemExit('service table must be 3-byte JMPs within 256 bytes')
    version = spec['major'] << 8 | spec['minor']
    asm = ['/* Generated by tools/overlay_v2_services.py; do not edit. */',
           f'/* Service table version ${version:04x}. */',
           '.section .apollo_services,"ax",@progbits']
    ld = ['/* Generated by tools/overlay_v2_services.py; do not edit. */',
          f'__ov2_services_resident = 0x{version:04x};']
    for i, name in enumerate(names):
        asm.append(f'    jmp {name}')
        ld.append(f'{name} = 0x{spec["base"] + 3 * i:04x};')
    return version, '\n'.join(asm) + '\n', '\n'.join(ld) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--spec', type=Path, default=ROOT / 'docs/overlay-v2-services.json')
    p.add_argument('--out-dir', type=Path, default=ROOT / 'build')
    p.add_argument('--version', type=lambda v: int(v, 0),
                   help='emit an earlier table version: the first entries that version had (FIRST_ENTRIES)')
    args = p.parse_args()
    spec = json.loads(args.spec.read_text())
    if args.version is not None:
        if args.version >> 8 != spec['major'] or args.version & 0xFF not in FIRST_ENTRIES:
            raise SystemExit(f'unknown service table version ${args.version:04x}')
        spec.update(minor=args.version & 0xFF, services=spec['services'][:FIRST_ENTRIES[args.version & 0xFF]])
    version, asm, ld = generate(spec)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / 'overlay_v2_services.S').write_text(asm)
    (args.out_dir / 'overlay_v2_services.ld').write_text(ld)
    print(f'service table ${version:04x}: {len(spec["services"])} entries')


if __name__ == '__main__':
    main()
