"""Comanche055 system-test entry words (lane A): COMPVER, GTSCPSS1 and REDO at
33,2000-2002 through agc_transfer_run. Builds the native snapshot
(platform/host/cm_lead_tests_snapshot.c) and the yaAGC oracle
(tools/cm_lead_tests_reference.c), requires byte-identical output on every case
of tests/cm_lead_tests_cases.c, and freezes one digest per case (the reach flag,
then the 2048 erasable words, Fletcher as clt_digest) into
tests/cm_lead_tests_vectors.h. Writes build/cm-lead-tests-proof.json.
"""
import hashlib, json, pathlib, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
NATIVE = ['tests/cm_lead_tests_cases.c', 'src/agc_transfer.c', 'src/standard_lead_routines.c', 'src/standard_lead.c',
          'src/standard_lead_interp.c', 'src/standard_lead_wake.c', 'src/lm_basic_wake.c', 'src/executive.c',
          'src/cm_basic_wake.c', 'src/cm_native_image.c', 'src/cm_dispatch.c', 'src/cm_executive.c', 'src/agc_word.c']
HEADERS = ['include/agc_transfer.h', 'include/standard_lead_routines.h', 'tests/cm_lead_tests_cases.h']
FLAGS = ['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Itools', '-Iplatform/host']


def digest(fields):
    a = b = 0
    for v in fields:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def main():
    subprocess.run(FLAGS + NATIVE + ['platform/host/cm_lead_tests_snapshot.c', '-o', 'build/cm-lead-tests-snapshot'],
                   cwd=R, check=True)
    subprocess.run(FLAGS + [f'-I{E}', 'tools/cm_lead_tests_reference.c', 'tests/cm_executive_cases.c'] + NATIVE +
                   [str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o'),
                    '-o', 'build/cm-lead-tests-reference'], cwd=R, check=True)
    ropes = [R / 'build/fixed-data/Comanche055/MAIN.agc.bin']
    native = subprocess.run(['./build/cm-lead-tests-snapshot'], cwd=R, check=True, capture_output=True,
                            text=True).stdout
    oracle = subprocess.run(['./build/cm-lead-tests-reference'] + [str(r) for r in ropes], cwd=R, check=True,
                            capture_output=True, text=True).stdout
    nl, ol = native.splitlines(), oracle.splitlines()
    assert len(nl) == len(ol) == 384, (len(nl), len(ol))
    differ = [i for i, (x, y) in enumerate(zip(nl, ol)) if x != y]
    assert not differ, f'native differs from yaAGC on cases {differ[:10]}'
    digests, reached = [], 0
    for i, line in enumerate(ol):
        v = list(map(int, line.split()))
        assert v[0] == i
        reached += v[1]
        digests.append(digest(v[1:] if v[1] else [0]))
    words = ['COMPVER 33,2000 -> GCOMPVER 33,3436', 'GTSCPSS1 33,2001 -> GTSCPSS 33,3131', 'REDO 33,2002 -> NEWMODEX 5354']
    proof = {'cases': 384, 'reached_target': reached, 'native_equals_yaagc': True,
             'by_word': {w: sum(1 for i, l in enumerate(ol) if i % 3 == j and l.split()[1] == '1') for j, w in enumerate(words)},
             'ropes': {'Comanche055': hashlib.sha256(ropes[0].read_bytes()).hexdigest()},
             'oracle_sha256': hashlib.sha256(oracle.encode()).hexdigest(),
             'dependencies': {f: hashlib.sha256((R / f).read_bytes()).hexdigest() for f in NATIVE + HEADERS},
             'boundary': ('from the entry word with FB 033, random erasable (L sign-extended), any A and Q, to the TC '
                          'target; yaAGC stops when Z and FB first equal the native ones')}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_lead_tests_freeze.py from the original',
            ' * Comanche055 program (yaAGC oracle): per case of tests/cm_lead_tests_cases.c,',
            ' * the Fletcher digest of the reach flag and the 2048 erasable words at the TC target. */',
            '#define CLT_VECTORS 384u',
            'static const uint32_t clt_digests[384]={']
    head += [','.join(f'0x{d:08x}u' for d in digests[i:i + 8]) + ',' for i in range(0, 384, 8)] + ['};']
    (R / 'tests/cm_lead_tests_vectors.h').write_text('\n'.join(head) + '\n')
    (R / 'build/cm-lead-tests-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: 384 cm-lead-tests cases identical to yaAGC, {reached} reach the TC target')


if __name__ == '__main__':
    main()
