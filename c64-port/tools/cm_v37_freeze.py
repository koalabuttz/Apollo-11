"""Run the original-program oracle for cm-v37 and freeze digests.

Builds the host-only yaAGC driver (tools/cm_v37_reference.c, with the
per-case trace of tools/case_trace.h), runs it on the unmodified Comanche055
rope, checks the native snapshot (build/cm-v37-native) is byte-identical,
fails if an instruction of bank 04 2000-2366 or VAC5STOR is never executed,
and writes tests/cm_v37_vectors.h (one digest per case: two 16-bit running
sums over the printed values) and the C64 rows chosen by outcome
(tools/c64_rows.py; every 32nd case, as the C64 image must stay below
$c000) to tests/cm_v37_c64_vectors.h. Also writes
build/cm-v37-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import c64_rows  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
# The milestone's own words (bank 04 V37 ... RAKE, bank 20 VAC5STOR), physical.
OWNED = [0o4 * 1024 + w - 0o2000 for w in range(0o2000, 0o2367)] + [0o20 * 1024 + w - 0o2000 for w in range(0o2000, 0o2064)]
CORE = ['tests/cm_v37_cases.c', 'src/cm_v37.c', 'src/cm_fresh_start.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
        'src/cm_interbank_routines.c', 'src/cm_interbank_complete.c', 'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    trace = B / 'cm-v37.trace'
    subprocess.run(['cc', '-std=c99', '-O2', f'-DCASE_TRACE={trace}', '-Iinclude', '-Itests', '-Isrc', '-Itools', '-I' + str(E),
                    'tools/cm_v37_reference.c', *CORE, '-o', 'build/cm-v37-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/cm-v37-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-v37-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_v37_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, SUPERBNK, channels 11, 5, 6, 12, 13, 14 and 33, the trap latches and all 2048',
           ' * erasable words. */',
           f'#define CM_V37_VECTORS {len(values)}u']
    table(out, 'cm_v37_expected', values)
    (R / 'tests/cm_v37_vectors.h').write_text('\n'.join(out) + '\n')
    cases = c64_rows.read(trace)
    assert sorted(cases) == list(range(len(values)))
    missed = c64_rows.unexecuted_instructions(c64_rows.listing(ROPE.parent / 'assembly.lst'), OWNED,
                                              frozenset().union(*cases.values()))
    if missed:
        raise SystemExit(f'instructions of the milestone no case executes: {missed}')
    chosen = c64_rows.rows(cases, 32)
    (R / 'tests/cm_v37_c64_vectors.h').write_text(c64_rows.c64_header('cm_v37', 'cm_v37', values, chosen, 32))
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': 'GOP00FIX, V37, CANV37, ROC, V37XEQ, the basic code after R00 EXIT, VAC5STOR and the return point after every TC out of the file (36)',
             'boundary': 'entry to the first point outside bank 04 2000-2366, bank 20 2000-2063, bank 05 2342-3217, GOTOPOOH 4106-4111 and INTER-BANK_COMMUNICATION, or SWRETURN',
             'full_physical_words': 2048, **c64_rows.summary(cases, chosen, OWNED)}
    (B / 'cm-v37-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program; {len(chosen)} C64 rows cover every word the host cases execute')


if __name__ == '__main__':
    main()
