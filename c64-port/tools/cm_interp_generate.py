"""Comanche055 build of the compiled interpretive bodies.

src/lm_interp_orders.c and src/lm_interp_steps.c compile Luminary099's
INTERPRETER.agc paths. Comanche055 has the same INTERPRETER.agc text and the
same erasable assignments; only fixed addresses differ, which the sources
spell IF_(luminary,comanche) (include/interp_mission.h). src/cm_interp_*.c
compile the same bodies with INTERP_COMANCHE under cmi_ names.

This tool writes include/cm_interp.h (the cmi_ declarations, from the lmi_
headers) and src/cm_interp_names.h (the lmi_ -> cmi_ renames), and with
--check verifies both are current and that every IF_ pair names the same
instruction in both assembly listings (build/fixed-data/<mission>/): the
Comanche address holds the Luminary instruction under the same label at the
same offset, with the same three instructions on each side.

  python3 tools/cm_interp_generate.py          # rewrite the generated files
  python3 tools/cm_interp_generate.py --check  # exit 1 if stale or a pair is wrong
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
HEADERS = ['include/lm_interp_steps.h', 'include/lm_interp_orders.h']
SOURCES = ['src/lm_interp_steps.c', 'src/lm_interp_orders.c']
OUT_H = 'include/cm_interp.h'
OUT_NAMES = 'src/cm_interp_names.h'


def declarations():
    """The lmi_ declarations and enums of the two headers, in order."""
    lines = []
    for h in HEADERS:
        text = (ROOT / h).read_text()
        text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
        for line in text.splitlines():
            if line.startswith('#') or not line.strip():
                continue
            lines.append(line)
    return lines


def names(lines):
    found = []
    for line in lines:
        for n in re.findall(r'\b(lmi_\w+|LMI_\w+)\b', line):
            if n not in found:
                found.append(n)
    return found


def cm(n):
    return 'cmi_' + n[4:] if n.startswith('lmi_') else 'CMI_' + n[4:]


def header(lines):
    body = '\n'.join(re.sub(r'\b(lmi_\w+|LMI_\w+)\b', lambda m: cm(m.group(1)), l) for l in lines)
    return ('/* SPDX-License-Identifier: MIT */\n'
            '/* Generated by tools/cm_interp_generate.py: do not edit. */\n'
            '#ifndef CM_INTERP_H\n#define CM_INTERP_H\n'
            '#include "agc_multiword.h"\n#include "overlay_runtime.h"\n#include "p66_bias.h"\n'
            '/* Comanche055 builds of the compiled interpretive bodies\n'
            ' * (include/lm_interp_steps.h, include/lm_interp_orders.h): the same\n'
            ' * paths and arguments, with Comanche055 fixed addresses. */\n'
            + body + '\n#endif\n')


def renames(ns):
    return ('/* SPDX-License-Identifier: MIT */\n'
            '/* Generated by tools/cm_interp_generate.py: do not edit. Renames the\n'
            ' * lmi_ bodies for the Comanche055 build (src/cm_interp_*.c). */\n'
            + ''.join('#define %s %s\n' % (n, cm(n)) for n in ns))


LOC = re.compile(r'(\d\d,)?[0-7]{4}')


class Rope:
    """Instruction rows of a yaYUL listing: (bank, address, label, op, operand)."""

    def __init__(self, mission):
        self.rows, self.at, self.labels = [], {}, {}
        for raw in (ROOT / 'build/fixed-data' / mission / 'assembly.lst').read_text(errors='replace').splitlines():
            l = raw.split('\t')[0]
            if len(l) < 40 or not re.match(r'^\d+,\d+: ', l):
                continue
            loc, word = l[15:33].strip(), l[33:38]
            if not LOC.fullmatch(loc) or not re.fullmatch(r'[0-7]{5}', word):
                continue
            bank, addr = loc.split(',') if ',' in loc else (None, loc)
            row = (bank, int(addr, 8), l[46:65].strip(), l[65:74].strip(), re.sub(r'\s+', ' ', l[74:].strip()))
            i = len(self.rows)
            self.rows.append(row)
            self.at.setdefault((bank, row[1]), i)
            if row[2] and row[2][0] not in '+-':
                self.labels.setdefault(row[2], i)

    def owner(self, i):
        j = i
        while j >= 0 and not (self.rows[j][2] and self.rows[j][2][0] not in '+-' and self.rows[j][0] == self.rows[i][0]):
            j -= 1
        return j

    def window(self, i):
        return [r[3:] for r in self.rows[max(0, i - 3):i + 4]]


def comanche(lm, cm_, bank, addr):
    """The Comanche055 address of Luminary099's instruction at (bank, addr), or None."""
    i = lm.at.get((bank, addr))
    if i is None:
        return None
    j = lm.owner(i)
    k = cm_.labels.get(lm.rows[j][2])
    if k is None:
        return None
    c = k + (i - j)
    if c >= len(cm_.rows) or cm_.rows[c][0] != cm_.rows[k][0] or cm_.rows[c][1] - cm_.rows[k][1] != lm.rows[i][1] - lm.rows[j][1]:
        return None
    if lm.window(i) != cm_.window(c):
        return None
    return cm_.rows[c][1]


def check_pairs():
    lm, cm_ = Rope('Luminary099'), Rope('Comanche055')
    bad, n = [], 0
    for src in SOURCES:
        for no, line in enumerate((ROOT / src).read_text().splitlines(), 1):
            for a, b in re.findall(r'IF_\((0[0-7]+)u?,(0[0-7]+)u?\)', line):
                a, b = int(a, 8), int(b, 8)
                banks = [None] if a >= 0o4000 else ['00', '01']
                n += 1
                if not any(comanche(lm, cm_, k, a) == b for k in banks):
                    bad.append('%s:%d: IF_(0%o,0%o) does not name the same instruction' % (src, no, a, b))
    return n, bad


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true')
    a = p.parse_args()
    lines = declarations()
    want = {OUT_H: header(lines), OUT_NAMES: renames(names(lines))}
    if not a.check:
        for path, text in want.items():
            (ROOT / path).write_text(text)
        print('wrote', ', '.join(want))
        return 0
    fail = [path + ' is stale (run tools/cm_interp_generate.py)' for path, text in want.items()
            if not (ROOT / path).exists() or (ROOT / path).read_text() != text]
    n, bad = check_pairs()
    fail += bad
    for f in fail:
        print('FAIL:', f)
    if fail:
        return 1
    print('PASS: %d IF_ address pairs name the same Luminary099 and Comanche055 instructions; generated headers current' % n)
    return 0


if __name__ == '__main__':
    sys.exit(main())
