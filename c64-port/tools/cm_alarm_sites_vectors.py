"""Expected per-case digests for the cm-alarm-sites C64 diagnostic.

Taken from the host native run, which the differential proves byte-identical
to the original assembly. The C64 runs the same flight code on the same inputs
for contexts 0 and 63 of every site and kind, and compares digests."""
import pathlib, subprocess
R = pathlib.Path(__file__).resolve().parents[1]
RECORD, SITES, CONTEXTS = 4130, 62, (0, 63)
data = subprocess.run(['./build/cm-alarm-sites-native'], cwd=R, check=True, capture_output=True).stdout
def digest(b):
    # Two 16-bit running sums over little-endian words (cheap on a 6502).
    a = s = 0
    for i in range(0, len(b), 2):
        a = (a + int.from_bytes(b[i:i + 2], 'little')) & 0xffff
        s = (s + a) & 0xffff
    return s << 16 | a
cases = [ctx * 3 * SITES + k for ctx in CONTEXTS for k in range(3 * SITES)]
rows = []
for n in cases:
    rec = data[n * RECORD:(n + 1) * RECORD]
    assert int.from_bytes(rec[0:4], 'little') == n
    rows.append(f'{{{n}ul,0x{digest(rec[6:]):08x}ul}}')  # status + image + io
out = ['/* Generated by tools/cm_alarm_sites_vectors.py. */',
       f'#define CM_ALARM_SITES_TARGET_CASES {len(rows)}u',
       'static const struct {uint32_t n,digest;} cm_alarm_sites_expected[%d]={' % len(rows)]
out += [' ' + ','.join(rows[i:i + 6]) + ',' for i in range(0, len(rows), 6)]
out.append('};')
(R / 'build/cm-alarm-sites-vectors.h').write_text('\n'.join(out) + '\n')
print(f'wrote build/cm-alarm-sites-vectors.h: {len(rows)} cases')
