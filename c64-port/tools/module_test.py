"""C64 module-test harness (docs/MODULE-TEST.md): run a suite's cases on the
C64 through flight modules loaded from the flight store, and compare each
complete result with the host's.

  module_test.py --mission lm --modules lanec_pin_keys_num_routines,... \\
      --states STATES --oracle ORACLE --native NATIVE [--cases N,N,...] \\
      [--limit ROUTINES] --name NAME

STATES holds each case's entry state ("n LM|CM words... channels...
superbank irq", tools/lanec/native.c --states); ORACLE and NATIVE the host
results in the oracle's row format ("n words... channels... superbank irq
status"). A case the native code refused (status 1) is expected unchanged,
from its NATIVE row (as tools/lanec/freeze.py); every other case is expected
to equal its ORACLE row. Only the mission's cases run; --cases picks some.

Needs make flight-store (build/flight-store/<m>.reu, report.json and the
resolver). The modules are named by their flight stems (report.json's
module_list). The case records go in the store image's unused gap below the
rope, in batches when one gap does not hold them all; each batch is one VICE
run of build/module-test/<m>-module-test.prg (tools/module_test.c). Results:
build/module-test/<NAME>-<m>.json.
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import struct
import subprocess
import sys
import zlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from flight_store_build import BASE_IO, io_kind  # noqa: E402
from resident_flight_build import COMMON, MISSION, resident_sources  # noqa: E402

STORE = ROOT / 'build/flight-store'
OUT = ROOT / 'build/module-test'
WORDS, CHANNELS = 2048, 0o100
RECORD = WORDS * 2 + CHANNELS * 2 + 8 + 8
HEADER = 16
# The case blob's end: the Pinball trampoline save below the mission's rope
# (tools/flight_store_build.py REU_LIMIT).
ROPE = {'lm': 0x1df000, 'cm': 0x1df000}
NONE = 0xffff
IO_DEFINE = {'LM_DNTM': 'MT_IO_LM_DNTM', 'CM_DNTM': 'MT_IO_CM_DNTM'}


def rows(path, skip=1):
    """{case: [fields]} from a text file of rows."""
    out = {}
    with open(path) as f:
        for line in f:
            v = line.split()
            if v:
                out[int(v[0])] = v[skip:]
    return out


def expected(oracle, native, cells):
    v = [int(x) for x in (native if int(native[-1]) == 1 else oracle)]
    z = v[5]
    if cells is not None and v[-1] == 0 and (z < 8 or z in cells):
        # The trampoline executes a TC or TCF-to-fixed it ends at in a
        # register or return cell (src/lanec_pin_trampoline.c cell_return).
        w = v[z]
        if w <= 0o7777 and w not in (3, 4, 6, z):
            v[5], v[2] = w, z + 1
        elif 0o12000 <= w <= 0o17777:
            v[5] = w & 0o7777
    return zlib.crc32(b''.join(x.to_bytes(2, 'little') for x in v))


def record(n, state, crc, limit):
    words = [int(x) for x in state[:WORDS]]
    chans = [int(x) for x in state[WORDS:WORDS + CHANNELS]]
    sb, irq = int(state[WORDS + CHANNELS]), int(state[WORDS + CHANNELS + 1])
    return struct.pack(f'<{WORDS}H{CHANNELS}H4HII', *words, *chans, sb, irq, NONE, limit, crc, n)


def idle_z(m):
    held = {(r['bank'], r['loc']) for r in json.loads((STORE / f'{m}-boot-resolver.json').read_text())}
    return next(z for z in range(0o7777, 0o4000, -1) if (0o6000 if z >= 0o6000 else 0o4000, z) not in held)


def build(a, m, ids, io, blob):
    OUT.mkdir(parents=True, exist_ok=True)
    data = OUT / f'{m}-module-test.h'
    data.write_text('/* Generated by tools/module_test.py. */\n'
                    f'#define MT_MODULES {", ".join(f"0x{i:04x}u" for i in ids)}\n'
                    f'#define MT_IDLE_Z 0{idle_z(m):o}u\n#define MT_CASES 0x{blob:x}ul\n'
                    f'#define {IO_DEFINE[io]} 1\n')
    prg = OUT / f'{m}-module-test.prg'
    subprocess.run([str(c) for c in [
        a.cc, *COMMON, *MISSION[m], f'-DMT_DATA="{data}"', '-T', 'platform/c64/resident_flight.ld',
        f'-Wl,-Map,{prg}.map', 'tools/module_test.c', *resident_sources(m),
        STORE / 'overlay_v2_services.S', '-o', prg]], cwd=ROOT, check=True)
    return prg


def vice(a, m, prg, reu):
    rom = a.rom_dir.resolve()
    work = OUT / f'vice-{m}'
    work.mkdir(parents=True, exist_ok=True)
    sys_at = re.search(rb'\x9e\s*(\d+)\x00', prg.read_bytes()[:32])
    if sys_at is None:
        sys.exit(f'FAIL: {prg.name} has no BASIC SYS header')
    dump = work / 'results.bin'
    dump.unlink(missing_ok=True)
    # With a pinned module (slot class 3), boot's DMA of it to $C000 is the
    # first store there; the mailbox's done flag is the next.
    pinned = '#define FL_PINNED ' in (STORE / f'{m}-load-check.h').read_text()
    (work / 'vice.mon').write_text(f'load "{prg}" 0\nwatch store c000\n' + ('ignore 1 1\n' if pinned else '')
                                   + f'g {int(sys_at[1]):04x}\n'
                                   f'bsave "{dump}" 0 c000 c0ff\nquit\n')
    cmd = [a.vice, '-default', '-console', '-pal', '-warp', '+sound',
           '-kernal', str(rom / 'kernal-901227-03.bin'), '-basic', str(rom / 'basic-901226-01.bin'),
           '-chargen', str(rom / 'chargen-901225-01.bin'),
           '-directory', f'{a.data_dir.resolve()}:{rom.parent}',
           '-initbreak', 'ready', '-moncommands', str(work / 'vice.mon'),
           '-monlogname', str(work / 'monitor.log'), '-monlog', '-limitcycles', str(a.cycles),
           '-reu', '-reusize', str(len(reu.read_bytes()) // 1024), '-reuimage', str(reu)]
    env = dict(os.environ, XDG_CACHE_HOME=str(work / 'cache'), XDG_CONFIG_HOME=str(work / 'config'))
    for key in ('XDG_CACHE_HOME', 'XDG_CONFIG_HOME'):
        pathlib.Path(env[key]).mkdir(parents=True, exist_ok=True)
    with (work / 'vice.log').open('w') as log:
        subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT, timeout=a.timeout, env=env)
    if not dump.exists():
        return None
    d = dump.read_bytes()
    return dict(done=d[0] == 0xa5, failures=d[1] | d[2] << 8, checks=d[3] | d[4] << 8, first_failing_step=d[5],
                routines=d[6] | d[7] << 8, failing=list(struct.unpack_from(f'<{d[8]}I', d, 0x10)))


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--mission', choices=('lm', 'cm'), required=True)
    p.add_argument('--modules', required=True, help='flight stems under test, comma-separated')
    p.add_argument('--states', required=True)
    p.add_argument('--oracle', required=True)
    p.add_argument('--native', required=True)
    p.add_argument('--cases', help='case numbers, comma-separated (default: all of the mission)')
    p.add_argument('--limit', type=int, default=256, help='routines a case may run')
    p.add_argument('--tc-cells', default='',
                   help='octal erasable cells (with registers 0-7) where the modules\' routines take the TC or TCF '
                        'a result ends at, as the transfer ABI trampoline does; the host row is advanced the same way')
    p.add_argument('--flight-rows', action='store_true',
                   help='ORACLE/NATIVE are tools/lanec/native.c --flight rows (the one routine registered at the '
                        'entry, run on the host as here): compared as they are, no TC-cell step')
    p.add_argument('--name', required=True)
    p.add_argument('--cc', default=os.environ.get('MOS_CC', str(ROOT / 'deps/llvm-mos/bin/mos-c64-clang')))
    p.add_argument('--vice', default=os.environ.get('VICE', 'x64sc'))
    p.add_argument('--rom-dir', type=pathlib.Path,
                   default=pathlib.Path(os.environ.get('VICE_ROM_DIR', ROOT / 'deps/vice-data/C64')))
    p.add_argument('--data-dir', type=pathlib.Path,
                   default=pathlib.Path(os.environ.get('VICE_DATA_DIR', ROOT / 'deps/vice-data')))
    p.add_argument('--cycles', type=int, default=4_000_000_000)
    p.add_argument('--timeout', type=int, default=1800)
    a = p.parse_args()
    m = a.mission
    report = json.loads((STORE / 'report.json').read_text())[m]
    # A stem's module, or its chunks (each a module) when the builder split it.
    by_stem = {}
    for x in report['module_list']:
        if x.get('bytes'):
            by_stem.setdefault(x['stem'], []).append(x['id'])
    stems = a.modules.split(',')
    missing = [s for s in stems if s not in by_stem]
    if missing:
        sys.exit(f'FAIL: {m}: not linked in the flight store: {" ".join(missing)}')
    ids = [i for s in stems for i in by_stem[s]]
    if len(ids) > 255:
        sys.exit(f'FAIL: {m}: {len(ids)} modules under test; tools/module_test.c counts them in a byte')
    # A base-kind module (P66 / CM_NATIVE: the INTER-BANK routines) takes the
    # prefix of a DNTM record (lm_dntm_io opens with its p66_bias_io,
    # cm_dntm_io with its cm_native_io), so it runs on the same device.
    kinds = {io_kind(m, s) for s in stems} - ({BASE_IO[m]} if len({io_kind(m, s) for s in stems}) > 1 else set())
    if len(kinds) != 1 or next(iter(kinds)) not in IO_DEFINE:
        sys.exit(f'FAIL: {m}: the modules take {sorted(kinds)}; tools/module_test.c carries {sorted(IO_DEFINE)}')
    states, oracle, native = rows(a.states, 2), rows(a.oracle), rows(a.native)
    tag = m.upper()
    mine = sorted(n for n, v in rows(a.states, 1).items() if v[0] == tag)
    if a.cases:
        pick = {int(x) for x in a.cases.split(',')}
        mine = [n for n in mine if n in pick]
    cells = None if a.flight_rows else {int(x, 8) for x in a.tc_cells.split(',') if x}
    records = [record(n, states[n], expected(oracle[n], native[n], cells), a.limit) for n in mine]
    store = STORE / f'{m}.reu'
    image = bytearray(store.read_bytes())
    blob = (report['store_bytes'] + 0xff) & ~0xff
    room = (ROPE[m] - blob - HEADER) // RECORD
    if room < 1 or any(image[blob:ROPE[m]]):
        sys.exit(f'FAIL: {m}: no free gap below the rope in {store}')
    prg = build(a, m, ids, next(iter(kinds)), blob)
    named = OUT / f'{a.name}-{m}.prg'   # this run's program, kept for its hash
    named.write_bytes(prg.read_bytes())
    store_sha = hashlib.sha256(image).hexdigest()
    total = dict(failures=0, checks=0, routines=0, failing=[], batches=0)
    for first in range(0, len(records), room):
        part = records[first:first + room]
        reu = OUT / f'{m}-module-test.reu'
        body = b'MTC1' + struct.pack('<HH', len(part), RECORD) + bytes(HEADER - 8) + b''.join(part)
        reu.write_bytes(bytes(image[:blob]) + body + bytes(image[blob + len(body):]))
        got = vice(a, m, prg, reu)
        reu.unlink()
        if not got or not got['done'] or got['first_failing_step'] in (1, 2):
            sys.exit(f'FAIL: {m} {a.name}: batch {total["batches"]} did not finish: {got} (see {OUT}/vice-{m}/vice.log)')
        for k in ('failures', 'checks', 'routines'):
            total[k] += got[k]
        total['failing'] += got['failing']
        total['batches'] += 1
    result = dict(mission=m, name=a.name, modules=stems, module_ids=[f'0x{i:04x}' for i in ids], cases=len(records),
                  store_sha256=store_sha, prg_sha256=hashlib.sha256(named.read_bytes()).hexdigest(), **total)
    (OUT / f'{a.name}-{m}.json').write_text(json.dumps(result, indent=1) + '\n')
    if total['failures'] or total['checks'] != len(records):
        print(f"FAIL: VICE PAL {m} {a.name}: {total['failures']} of {len(records)} cases differ from the host "
              f"(first: {total['failing'][:8]})")
        return 1
    print(f"PASS: VICE PAL {named.relative_to(ROOT / 'build')}: {m} {a.name}: {len(records)} cases through flight "
          f"modules {' '.join(stems)} ({len(ids)} modules) loaded from the REU store (sha256 {store_sha[:16]}), "
          f"{total['routines']} routines, every complete result equal to the host's ({total['batches']} batches)")
    return 0


if __name__ == '__main__':
    sys.exit(main())
