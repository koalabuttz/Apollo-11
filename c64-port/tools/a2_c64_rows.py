"""Lane A2's C64 rows by native branch outcome (tools/c64_row_cover.py).

select() writes a one-case host runner (build/<name>-cover/runner.c) that
calls the milestone's digest function for the case number in argv[1] -- the
same call the C64 diagnostic makes per row -- builds it at -O0 --coverage over
every linked source of the milestone, traces every case's gcov branch arcs,
picks a greedy cover and checks that the chosen rows take every arc the host
corpus takes (host == C64), exiting otherwise. The cover starts from every
16th case (the earlier stride rows, which also exercise the C64 arithmetic
on more images). header() writes the C64 vector header: the explicit
case-number list and the 32-bit digests of those cases.
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import c64_row_cover  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
FLAGS = ('-std=c99', '-Iinclude', '-Itests', '-Isrc')


def select(name, sources, includes, call, cases, budget=None, stride=16):
    """(rows, proof fields): sources are the milestone's linked sources (port root
    relative), includes the headers the runner needs, call a C statement running
    case n (an unsigned) with apollo_overlay_state s and enum exec_status st in scope.
    The cover starts from every stride-th case (the earlier C64 rows; 0: none)."""
    d = B / f'{name}-cover'
    d.mkdir(parents=True, exist_ok=True)
    runner = d / 'runner.c'
    runner.write_text('/* Generated by tools/a2_c64_rows.py: run one case for gcov. */\n#include <stdlib.h>\n'
                      + ''.join(f'#include "{h}"\n' for h in includes)
                      + 'int main(int argc,char **argv){apollo_overlay_state s;enum exec_status st;'
                        'unsigned n=argc>1?(unsigned)strtoul(argv[1],0,10):0u;\n'
                      + f' {call}\n (void)st;return 0;}}\n')
    srcs = [*sources, str(runner.relative_to(R))]
    h = hashlib.sha256()
    for s in sorted(srcs) + sorted(str(p.relative_to(R)) for p in (*(R / 'src').glob('*.inc'),
                                                                 *(R / 'src').glob('*.h'),
                                                                 *(R / 'include').glob('*.h'),
                                                                 *(R / 'tests').glob('*_cases.h'))):
        h.update(s.encode() + b'\0' + (R / s).read_bytes())
    h.update(repr((call, cases)).encode())
    cache = d / f'trace-{h.hexdigest()[:16]}.json'
    if cache.exists():
        trace = c64_row_cover.load(cache)
    else:
        for old in d.glob('trace-*.json'):
            old.unlink()
        trace = c64_row_cover.host_trace(d / 'obj', srcs, FLAGS, range(cases))
        c64_row_cover.save(cache, trace)
    rows = c64_row_cover.cover(trace, budget=budget, seed=range(0, cases, stride) if stride else ())
    c64_row_cover.check(trace, rows, f'{name} C64 rows')
    proof = c64_row_cover.summary(trace, rows)
    proof['c64_row_seed_stride'] = stride
    proof['c64_missing_branch_arcs'] = c64_row_cover.missing(trace, rows)
    assert proof['c64_branch_arcs'] == proof['host_branch_arcs'] and not proof['c64_missing_branch_arcs']
    return rows, proof


def header(tool, prefix, values, rows, stride=16):
    """The C64 vector header: the chosen case numbers and their digests."""
    up = prefix.upper()
    nth = f'{stride}{"nd" if stride % 10 == 2 and stride % 100 != 12 else "th"}'
    seed = f'every {nth} case plus ' if stride else ''
    out = [f'/* SPDX-License-Identifier: MIT; generated by tools/{tool}: the C64 rows',
           f' * (tools/a2_c64_rows.py: {seed}a greedy cover of the gcov branch arcs every',
           ' * host case takes in every linked source; the rows take them all) and their',
           ' * digests from the vectors header. */',
           f'#define {up}_C64_COUNT {len(rows)}u', f'static const uint16_t {prefix}_c64_case[{len(rows)}]={{']
    for i in range(0, len(rows), 12):
        out.append(''.join(f'{n}u,' for n in rows[i:i + 12]))
    out += ['};', f'static const uint32_t {prefix}_c64[{len(rows)}]={{']
    for i in range(0, len(rows), 6):
        out.append(''.join(f'0x{values[n]:08x}ul,' for n in rows[i:i + 6]))
    out.append('};')
    return '\n'.join(out) + '\n'
