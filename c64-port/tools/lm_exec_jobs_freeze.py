"""Run the original-program oracle for lm-exec-jobs and freeze digests.

Builds the host-only yaAGC driver tools/lm_exec_jobs_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-exec-jobs-native) is byte-identical, and writes
tests/lm_exec_jobs_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words, SUPERBNK,
the interrupt-enable bit, channel 11 and InIsr) and
tests/lm_exec_jobs_c64_vectors.h (every sixteenth). Also writes
build/lm-exec-jobs-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_exec_jobs.c', 'src/lm_exec_tasks.c', 'src/lm_exec_routines.c', 'src/lm_admission_image.c', 'src/lm_waitlist_image.c',
          'src/lm_basic_sleep.c', 'src/lm_basic_wake.c', 'src/lm_basic_priority.c', 'src/lm_basic_finish.c',
          'src/lm_basic_change.c', 'src/lm_interpreter_change.c', 'src/lm_delay_image.c',
          'src/lm_taskover_resume.c', 'src/lm_waitlist_dispatch.c', 'src/lm_waitlist_irq_dispatch.c',
          'src/waitlist.c', 'src/executive.c', 'src/p66_native.c', 'src/agc_transfer.c', 'src/agc_multiword.c',
          'tests/lm_admission_image_cases.c', 'tests/lm_basic_change_cases.c', 'tests/lm_interpreter_change_cases.c',
          'tests/lm_sleep_cases.c', 'tests/lm_wake_cases.c', 'tests/lm_priority_cases.c', 'tests/lm_finish_cases.c',
          'tests/lm_delay_image_cases.c', 'tests/lm_waitlist_image_cases.c', 'tests/lm_taskover_resume_cases.c',
          'tests/lm_waitlist_dispatch_cases.c', 'tests/throttle_bridge_cases.c', 'tests/lm_exec_jobs_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_exec_jobs_reference.c', *CORE,
                    '-o', 'build/lm-exec-jobs-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-exec-jobs-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-exec-jobs-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-exec-jobs: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_jobs_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words, SUPERBNK, the interrupt-enable',
           ' * bit, channel 11 and InIsr. */',
           f'#define LM_EXJ_VECTORS {len(digests)}u', *table('lm_exj_expected', digests)]
    (R / 'tests/lm_exec_jobs_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_jobs_freeze.py: every',
           ' * sixteenth digest of tests/lm_exec_jobs_vectors.h, for the C64 diagnostic. */',
           f'#define LM_EXJ_C64_STRIDE {STRIDE}u', f'#define LM_EXJ_C64_COUNT {len(c64)}u',
           *table('lm_exj_c64', c64)]
    (R / 'tests/lm_exec_jobs_c64_vectors.h').write_text('\n'.join(out) + '\n')
    names = ['spvac', 'chang1', 'chang2', 'jobsleep', 'jobwake', 'priochng', 'endofjob', 'delay',
             'fixdelay-sites', 'taskover-resume', 't3-dispatch']
    first = [0, 1024, 1792, 2560, 3584, 4096, 5120, 6144, 7168, 7680, 8192, 9216]
    kinds = collections.Counter()
    for r in rows:
        cohort = names[next(i for i in range(len(names)) if r[0] < first[i + 1])]
        end = ('returned', 'alarm', 'refused')[r[1]]
        if end == 'returned' and cohort in ('jobsleep', 'priochng', 'endofjob', 'chang1', 'chang2'):
            z = r[2 + 5]
            end = 'idle' if z == 0o3214 else 'interpretive' if z == 0o6070 else 'returned'
        kinds[f'{cohort}:{end}'] += 1
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['04014 T3RUPT vector', '05112 SPVACIN', '05116 SPVAC', '05122 CHANG1', '05126 CHANG2',
                         '05133 JOBSLEEP', '05137 JOBWAKE', '05146 PRIOCHNG', '05155 ENDOFJOB', '05221 FIXDELAY',
                         '05224 VARDELAY', '05261 TASKOVER'],
             'boundary': 'job switches: the selected basic job entry, NEWOPS 06070 for an interpretive job, or '
                         'ADVAN 01,3214 idle; SPVAC/JOBWAKE/PRIOCHNG: the caller return; FIXDELAY/VARDELAY: '
                         'TASKOVER; TASKOVER RUPTAGN -0: the end of the interrupt (RESUME); T3 vector and '
                         'TASKOVER +1: the dispatched task; alarm: BAILOUT1/POODOO1 entry',
             'full_physical_words': 2048, 'extra_state': ['SUPERBNK', 'interrupt enable', 'channel 11', 'InIsr']}
    (B / 'lm-exec-jobs-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-exec-jobs cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
