"""Run the original-program oracle for lm-phase-table and freeze digests.

Builds the host-only yaAGC driver (tools/lm_phase_table_reference.c), runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-phase-table-native) is byte-identical, and writes
tests/lm_phase_table_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and every sixteenth digest to
tests/lm_phase_table_c64_vectors.h. Also writes build/lm-phase-table-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
CORE = ['tests/lm_phase_table_cases.c', 'src/lm_phase_table.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
        'src/lm_interbank_routines.c', 'src/lm_interbank_idle.c', 'src/lm_interbank.c', 'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/lm_phase_table_reference.c', *CORE, '-o', 'build/lm-phase-table-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/lm-phase-table-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-phase-table-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_phase_table_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, the NOVAC record and all 2048 erasable words. */',
           f'#define LM_PT_VECTORS {len(values)}u']
    table(out, 'lm_pt_expected', values)
    (R / 'tests/lm_phase_table_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_phase_table_freeze.py: every',
           ' * sixteenth digest of tests/lm_phase_table_vectors.h, for the C64 diagnostic. */',
           '#define LM_PT_C64_STRIDE 16u', f'#define LM_PT_C64_COUNT {len(values[::16])}u']
    table(c64, 'lm_pt_c64', values[::16])
    (R / 'tests/lm_phase_table_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': ['5311 NEWMODEX', '5314 NEWMODEA', '5315 MMDSPLAY', '5321 CHECKMM', '5327 2PHSCHNG',
                         '5353 PHASCHNG', '5357 PHSCHNGA', '10,2213 SETUPDSP', '10,2221 SETUPDSP NOVAC return',
                         '10,2224 PHSCHNG2', '10,2312 CON2'],
             'boundary': 'caller site to the caller return (or CHECKMM Q+1/Q+2), through BANKJUMP '
                         '(lm_interbank_routines); NOVAC recorded and returned to Q+2',
             'full_physical_words': 2048}
    (B / 'lm-phase-table-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program')


if __name__ == '__main__':
    main()
