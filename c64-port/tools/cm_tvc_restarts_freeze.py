"""Freeze oracle rows for the host check and the C64 diagnostic: for each
selected case, the oracle's status and every image word that differs from the
case input (tests/cm_tvc_restarts_vectors.h). Reads the delta stream that
tools/cm_tvc_restarts_differential.py keeps; never runs the native code."""
import pathlib,struct,hashlib,subprocess,lzma,sys
R=pathlib.Path(__file__).resolve().parents[1];sys.path.insert(0,str(R/'tools'))
from frozen_words import encode_rows,c_header
ROW=2053*2
cases={};path=R/'build/cm-tvc-restarts-reference.deltas.xz'
if not path.exists():path=R/'evidence/cm-tvc-restarts/cm-tvc-restarts-reference.deltas.xz'
with lzma.open(path,'rb') as f:
 h=hashlib.sha256()
 while head:=f.read(12):
  w=struct.unpack('<6H',head);body=f.read(4*w[5]);h.update(head+body);cases[w[0]|w[1]<<16]=(w,struct.unpack(f'<{2*w[5]}H',body))
# Every entry under each phase/counter class the case bits select.
chosen=sorted({k*517%65536 for k in range(128)})
rows=[]
for k,n in enumerate(chosen):
 w,pairs=cases[n];rows.append([n&65535,n>>16,w[2],w[3],w[4],w[5],*pairs])
width=max(map(len,rows));packed=encode_rows([r+[0]*(width-len(r)) for r in rows])
s=('/* SPDX-License-Identifier: MIT\n * Generated by tools/cm_tvc_restarts_freeze.py from the oracle delta stream SHA256:'+h.hexdigest()+' */\n'
   '#ifndef CM_TVC_RESTARTS_VECTORS_H\n#define CM_TVC_RESTARTS_VECTORS_H\n'+c_header(packed,'cm_tvc_restarts')+'#endif\n')
(R/'tests/cm_tvc_restarts_vectors.h').write_text(s)
print(len(rows),'rows',packed.storage_bytes,'bytes')
