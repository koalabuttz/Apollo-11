"""Run the original-program oracle for lm-stateup and freeze digests.

Builds the host-only yaAGC driver (tools/lm_stateup_reference.c), runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-stateup-native) is byte-identical, and writes
tests/lm_stateup_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and the C64 rows chosen by
native branch outcome (tools/a2_c64_rows.py: every 16th case plus a greedy
cover of the gcov arcs every host case takes in every linked source; the
freeze fails unless the rows take them all) to
tests/lm_stateup_c64_vectors.h. Also writes build/lm-stateup-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import a2_c64_rows  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
# The milestone's linked sources (tools/mk/lm-stateup.mk LM_STATEUP_SRC), for the row cover.
SRC = ['src/lm_stateup.c', 'src/lm_interp_orders.c', 'src/lm_interp_steps.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c', 'tests/lm_stateup_cases.c']
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
CORE = ['tests/lm_stateup_cases.c', 'src/lm_stateup.c', 'src/lm_interp_orders.c', 'src/lm_interp_steps.c',
        'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/lm_stateup_reference.c', *CORE, '-o', 'build/lm-stateup-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/lm-stateup-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-stateup-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_stateup_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, SUPERBNK and all 2048 erasable words. */',
           f'#define LM_STATEUP_VECTORS {len(values)}u']
    table(out, 'lm_stateup_expected', values)
    (R / 'tests/lm_stateup_vectors.h').write_text('\n'.join(out) + '\n')
    chosen, cover = a2_c64_rows.select('lm-stateup', SRC, ['lm_stateup_cases.h'], 'lm_stateup_digest(&s,(uint16_t)n,&st);', len(values),
                                       stride=16)
    (R / 'tests/lm_stateup_c64_vectors.h').write_text(a2_c64_rows.header('lm_stateup_freeze.py', 'lm_stateup', values, chosen, 16))
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': 'every order-pair word of STATEUP, DOINT, NO-INT, DOINT2, THISVINT (bank 13) and R00 (bank 04) (13), at NEWOPS',
             'boundary': 'NEWOPS with LOC on the pair to NEWOPS with LOC outside the file (CALL/STCALL/CLRGO/RVQ targets), R00 EXIT to basic code, or CHANG2',
             'full_physical_words': 2048, **cover}
    (B / 'lm-stateup-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program; {len(chosen)} C64 rows take all '
          f'{cover["host_branch_arcs"]} host branch arcs')


if __name__ == '__main__':
    main()
