"""Run the original-program oracle for lm-exec-idle and freeze digests.

Builds the host-only yaAGC driver tools/lm_exec_idle_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-exec-idle-native) is byte-identical, and writes
tests/lm_exec_idle_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit, channel 11 and InIsr) and
tests/lm_exec_idle_c64_vectors.h (every sixteenth). Also writes
build/lm-exec-idle-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_exec_idle.c',
          'src/lm_idle_dispatch.c',
          'src/lm_super_dispatch.c',
          'src/lm_svct3.c',
          'src/executive.c',
          'src/waitlist.c',
          'src/p66_native.c',
          'src/agc_transfer.c',
          'src/agc_multiword.c',
          'tests/lm_exec_idle_cases.c',
          'tests/lm_idle_dispatch_cases.c',
          'tests/lm_super_dispatch_cases.c',
          'tests/lm_svct3_cases.c',
          'tests/lm_context_lifecycle_cases.c',
          'tests/lm_admission_image_cases.c',
          'tests/lm_priority_cases.c',
          'tests/lm_sleep_cases.c',
          'tests/throttle_bridge_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
COHORTS = [(0, 'advan'), (1024, 'nuchang2'), (1792, 'dummyjob'), (2304, 'supdxchz'), (3328, 'svct3')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_exec_idle_reference.c', *CORE,
                    '-o', 'build/lm-exec-idle-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-exec-idle-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-exec-idle-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-exec-idle: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_idle_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable, channel 11 and InIsr. */',
           f'#define LM_EXI_VECTORS {len(digests)}u', *table('lm_exi_expected', digests)]
    (R / 'tests/lm_exec_idle_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_idle_freeze.py: every',
           ' * sixteenth digest of tests/lm_exec_idle_vectors.h, for the C64 diagnostic. */',
           f'#define LM_EXI_C64_STRIDE {STRIDE}u', f'#define LM_EXI_C64_COUNT {len(c64)}u',
           *table('lm_exi_c64', c64)]
    (R / 'tests/lm_exec_idle_c64_vectors.h').write_text('\n'.join(out) + '\n')
    kinds = collections.Counter()
    for r in rows:
        cohort = next(name for start, name in reversed(COHORTS) if r[0] >= start)
        kinds[f"{cohort}:{('returned', 'alarm', 'refused')[r[1]]}"] += 1
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['01,3011 NUCHANG2', '01,3206 DUMMYJOB', '01,3210 DUMMYJOB +2', '01,3214 ADVAN',
                         '05165 SUPDXCHZ', '05166 SUPDXCHZ +1', '05240 SVCT3', '05255 SVCT3 after NOVAC',
                         '05260 SVCT3X after FIXDELAY'],
             'boundary': 'one routine from its entry to the continuation it leaves in Z (the selected basic '
                         'job, NEWOPS for an interpretive job, the self-check at SELFRET, the SUPDXCHZ target, '
                         'or TASKOVER, NOVAC or FIXDELAY from SVCT3); the original runs to the first time it '
                         'reaches that Z (and FB in banked memory); alarm: BAILOUT1/POODOO1 entry',
             'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, channel 11, InIsr',
             'full_physical_words': 2048}
    (B / 'lm-exec-idle-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-exec-idle cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
