"""Run the original-program oracle for cm-exec-jobs and freeze digests.

Builds the host-only yaAGC driver tools/cm_exec_jobs_reference.c, runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-exec-jobs-native) is byte-identical, and writes
tests/cm_exec_jobs_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit and channel 11) and
tests/cm_exec_jobs_c64_vectors.h (every sixteenth). Also writes
build/cm-exec-jobs-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
NATIVE = ['src/cm_exec_jobs.c', 'src/cm_admission_zero.c', 'src/cm_context_change.c', 'src/cm_basic_sleep.c',
          'src/cm_wake_complete.c', 'src/cm_priority_complete.c', 'src/cm_basic_finish.c', 'src/cm_dispatch.c',
          'src/cm_executive.c', 'src/cm_native_image.c', 'src/agc_transfer.c', 'src/agc_multiword.c',
          'tests/cm_exec_jobs_cases.c', 'tests/cm_admission_zero_cases.c', 'tests/cm_admission_complete_cases.c',
          'tests/cm_context_change_cases.c', 'tests/cm_sleep_cases.c', 'tests/cm_basic_finish_cases.c',
          'tests/cm_wake_complete_cases.c', 'tests/cm_priority_complete_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
COHORTS = [(0, 'spvac'), (1024, 'change'), (2048, 'jobsleep'), (3072, 'jobwake'), (4096, 'priochng'),
           (5120, 'endofjob')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/cm_exec_jobs_reference.c', *CORE,
                    '-o', 'build/cm-exec-jobs-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/cm-exec-jobs-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-exec-jobs-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'cm-exec-jobs: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_exec_jobs_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable and channel 11. */',
           f'#define CM_EXJ_VECTORS {len(digests)}u', *table('cm_exj_expected', digests)]
    (R / 'tests/cm_exec_jobs_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_exec_jobs_freeze.py: every',
           ' * sixteenth digest of tests/cm_exec_jobs_vectors.h, for the C64 diagnostic. */',
           f'#define CM_EXJ_C64_STRIDE {STRIDE}u', f'#define CM_EXJ_C64_COUNT {len(c64)}u',
           *table('cm_exj_c64', c64)]
    (R / 'tests/cm_exec_jobs_c64_vectors.h').write_text('\n'.join(out) + '\n')
    kinds = collections.Counter()
    for r in rows:
        cohort = next(name for start, name in reversed(COHORTS) if r[0] >= start)
        kinds[f"{cohort}:{('returned', 'alarm', 'refused')[r[1]]}"] += 1
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['05154 SPVACIN', '05160 SPVAC', '05164 CHANG1', '05170 CHANG2', '05175 JOBSLEEP',
                         '05201 JOBWAKE', '05210 PRIOCHNG', '05217 ENDOFJOB'],
             'boundary': 'one routine from its entry to the continuation it leaves in Z (the caller, the '
                         'selected basic job, NEWOPS for an interpretive job, ADVAN when idle, TC 014 or '
                         'CCSHOLE from JOBWAKE); the original runs to the first time it reaches that Z (and '
                         'FB in banked memory); alarm: BAILOUT/POODOO entry',
             'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, channel 11',
             'full_physical_words': 2048}
    (B / 'cm-exec-jobs-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} cm-exec-jobs cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
