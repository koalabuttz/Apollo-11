"""Run the original-program oracle for cm-exec-services and freeze digests.

Builds the host-only yaAGC driver tools/cm_exec_services_reference.c, runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-exec-services-native) is byte-identical, and writes
tests/cm_exec_services_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit and InIsr) and
tests/cm_exec_services_c64_vectors.h (every sixteenth). Also writes
build/cm-exec-services-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
NATIVE = ['src/cm_exec_routines.c', 'src/cm_admission_zero.c', 'src/cm_waitlist_extended.c',
          'src/cm_waitlist_internal.c', 'src/cm_task_transfer.c', 'src/cm_native_image.c', 'src/cm_executive.c',
          'src/cm_waitlist.c', 'src/agc_transfer.c', 'src/agc_multiword.c', 'tests/cm_exec_services_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
COHORTS = [(0, 'site'), (4128, 'longtask'), (5152, 'fixdelay'), (5600, 'vardelay'), (6112, 'resume'),
           (6624, 'dispatch')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/cm_exec_services_reference.c', *CORE,
                    '-o', 'build/cm-exec-services-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/cm-exec-services-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-exec-services-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'cm-exec-services: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_exec_services_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable and InIsr. */',
           f'#define CM_EXS_VECTORS {len(digests)}u', *table('cm_exs_expected', digests)]
    (R / 'tests/cm_exec_services_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_exec_services_freeze.py: every',
           ' * sixteenth digest of tests/cm_exec_services_vectors.h, for the C64 diagnostic. */',
           f'#define CM_EXS_C64_STRIDE {STRIDE}u', f'#define CM_EXS_C64_COUNT {len(c64)}u',
           *table('cm_exs_c64', c64)]
    (R / 'tests/cm_exec_services_c64_vectors.h').write_text('\n'.join(out) + '\n')
    kinds = collections.Counter()
    for r in rows:
        cohort = next(name for start, name in reversed(COHORTS) if r[0] >= start)
        kinds[f"{cohort}:{('returned', 'alarm', 'refused')[r[1]]}"] += 1
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['04014 T3RUPT vector', '05134 NOVAC', '05147 FINDVAC', '05235 TWIDDLE', '05245 WAITLIST',
                         '05267 FIXDELAY', '05272 VARDELAY', '05324 TASKOVER', '05342 LONGCALL', '01,3461 LNGCALL2',
                         '01,3465 LONGCYCL', '01,3505 LONGRTRN', '01,3514 TCF LONGRTRN', '01,3515 GETCADR'],
             'boundary': 'site: every genuine call site to the caller return; longtask: LONGCYCL to TASKOVER, '
                         'GETCADR to the task; fixdelay/vardelay: to TASKOVER; resume: TASKOVER RUPTAGN -0 to the '
                         'end of the interrupt; dispatch: T3RUPT vector or TASKOVER RUPTAGN +1 to the next task; '
                         'alarm: BAILOUT/POODOO entry; refused: LONGCYCL reaching the constant DPBIT14',
             'compared': 'outcome kind; unless refused, all 2048 erasable words, SUPERBNK, interrupt enable, InIsr',
             'full_physical_words': 2048}
    (B / 'cm-exec-services-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} cm-exec-services cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
