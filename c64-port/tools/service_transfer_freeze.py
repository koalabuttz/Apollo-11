"""SERVICE_ROUTINES transfer tables (lane A): every genuine UPFLAG, DOWNFLAG
and GENTRAN site and every other entry of both missions, through
agc_transfer_run. Builds the native snapshot
(platform/host/service_transfer_snapshot.c) and the yaAGC oracle
(tools/service_transfer_reference.c), requires byte-identical output on every case
of tests/service_transfer_cases.c, and freezes one digest per case (the reach flag,
then the interrupt inhibit and the 2048 erasable words, Fletcher as svt_digest) into
tests/service_transfer_vectors.h. Writes build/service-transfer-proof.json.
"""
import hashlib, json, os, pathlib, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
NATIVE = ['tests/service_transfer_cases.c', 'src/service_transfer.c', 'src/service_routines.c', 'src/agc_transfer.c',
          'src/agc_word.c', 'src/agc_multiword.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c']
HEADERS = ['include/agc_transfer.h', 'include/service_transfer.h', 'include/service_routines.h',
           'include/service_routines_source.h', 'src/lm_service_sites.inc', 'src/cm_service_sites.inc',
           'tests/service_transfer_cases.h']
FLAGS = ['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Itools', '-Iplatform/host']


def digest(fields):
    a = b = 0
    for v in fields:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def main():
    subprocess.run(FLAGS + NATIVE + ['platform/host/service_transfer_snapshot.c', '-o', 'build/service-transfer-snapshot'],
                   cwd=R, check=True)
    subprocess.run(FLAGS + [f'-I{E}', 'tools/service_transfer_reference.c', 'src/cm_executive.c',
                            'tests/cm_executive_cases.c'] + [s for s in NATIVE if s != 'src/agc_word.c'] +
                   ['src/agc_word.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o'),
                    '-o', 'build/service-transfer-reference'], cwd=R, check=True)
    ropes = [R / 'build/fixed-data' / m / 'MAIN.agc.bin' for m in ('Luminary099', 'Comanche055')]
    native = subprocess.run(['./build/service-transfer-snapshot'], cwd=R, check=True, capture_output=True,
                            text=True).stdout
    oracle = subprocess.run(['./build/service-transfer-reference'] + [str(r) for r in ropes], cwd=R,
                            env={**os.environ, 'LANE_A_EXECUTED': 'build/service-transfer-executed.txt'}, check=True,
                            capture_output=True, text=True).stdout
    nl, ol = native.splitlines(), oracle.splitlines()
    assert len(nl) == len(ol), (len(nl), len(ol))
    cases = len(ol)
    differ = [i for i, (x, y) in enumerate(zip(nl, ol)) if x != y]
    assert not differ, f'native differs from yaAGC on cases {differ[:10]}'
    digests, reached = [], 0
    for i, line in enumerate(ol):
        v = list(map(int, line.split()))
        assert v[0] == i
        reached += v[1]
        digests.append(digest(v[1:] if v[1] else [0]))
    sites = {m: sum(1 for l in (R / f'src/{m}_service_sites.inc').read_text().splitlines() if l.startswith(' {'))
             for m in ('lm', 'cm')}
    proof = {'cases': cases, 'reached_continuation': reached, 'native_equals_yaagc': True,
             'operand_sites': sites, 'entry_cases_per_mission': 256, 'oracle': 'yaAGC agc_engine from the original ropes',
             'ropes': {r.parent.name: hashlib.sha256(r.read_bytes()).hexdigest() for r in ropes},
             'oracle_sha256': hashlib.sha256(oracle.encode()).hexdigest(),
             'dependencies': {f: hashlib.sha256((R / f).read_bytes()).hexdigest() for f in NATIVE + HEADERS},
             'boundary': ('from the SERVICE_ROUTINES entry (Q at the operand word for a genuine site, random otherwise; '
                          'any Q for TCGETCAD, WAKER, its finish and B5OFF) with a random erasable image to the first '
                          'continuation outside the file; yaAGC stops when Z and FB first equal the native ones')}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/service_transfer_freeze.py from the original',
            ' * Luminary099 and Comanche055 programs (yaAGC oracle): per case of tests/service_transfer_cases.c,',
            ' * the Fletcher digest of the reach flag, the inhibit flag and the 2048 erasable words. */',
            f'#define SVT_VECTORS {cases}u',
            f'static const uint32_t svt_digests[{cases}]={{']
    head += [','.join(f'0x{d:08x}u' for d in digests[i:i + 8]) + ',' for i in range(0, cases, 8)] + ['};']
    (R / 'tests/service_transfer_vectors.h').write_text('\n'.join(head) + '\n')
    # Every third case (both missions, sites and entries) for the C64 diagnostic.
    c64 = digests[::3]
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/service_transfer_freeze.py: every',
            ' * third digest of tests/service_transfer_vectors.h, for the C64 diagnostic. */',
            '#define SVT_C64_STRIDE 3u', f'#define SVT_C64_COUNT {len(c64)}u',
            f'static const uint32_t svt_c64[{len(c64)}]={{']
    head += [','.join(f'0x{d:08x}ul' for d in c64[i:i + 6]) + ',' for i in range(0, len(c64), 6)] + ['};']
    (R / 'tests/service_transfer_c64_vectors.h').write_text('\n'.join(head) + '\n')
    (R / 'build/service-transfer-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {cases} service-transfer cases identical to yaAGC, {reached} reach a continuation')


if __name__ == '__main__':
    main()
