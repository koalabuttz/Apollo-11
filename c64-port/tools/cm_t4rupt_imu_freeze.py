"""Run the original-program oracle for cm-t4rupt-imu and freeze digests.

Builds the host-only yaAGC driver tools/cm_t4rupt_imu_reference.c, runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-t4rupt-imu-native) is byte-identical, and writes
tests/cm_t4rupt_imu_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK and channels 11, 12, 14, 30 and 33) and
tests/cm_t4rupt_imu_c64_vectors.h (every sixteenth). Also writes
build/cm-t4rupt-imu-proof.json and build/cm-t4rupt-imu-executed.txt.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import c64_case_cover  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
NATIVE = ['src/cm_t4rupt_imu.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/cm_t4rupt_imu_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'src/cm_executive.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
IMUMON = 2048
PER = 128
ENTRIES = ['06,2174 IMUMON', '06,2260 ALARM 213 return', '06,2265 WAITLIST return (2CADR ENDTNON)',
           '06,2270 ENDTNON (task, and VARDELAY return)', '06,2315 UNZ2 (IBNKCALL NOATTOFF return)',
           '06,2316 ZEROICDU return', '06,2323 ISSUP (VARDELAY return)', '06,2341 WAITLIST return (2CADR PFAILOK)',
           '06,2356 ISSZERO IBNKCALL NOATTOFF return', '06,2362 ZEROICDU return', '06,2366 WAITLIST return (2CADR UNZ2)',
           '06,2451 IBNKCALL SETCOARS return', '06,2455 NOGIMRUN (WAITLIST return, 2CADR CA+ECE)',
           '06,2550 ALARM 207 return', '06,2573 IBNKCALL RNDREFDR return (IMUCAGE)',
           '06,2613 IBNKCALL RNDREFDR return (IMUOP)', '06,2624 ALARM 214 return', '06,2652 ALARM 212 return',
           '06,2657 ALARM 1105 return', '06,2664 ALARM 1106 return', '06,2665 SETISSW (IMUFAIL, ICDUFAIL)',
           '06,2713 VARALARM return (ISSWON)']


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/cm_t4rupt_imu_reference.c', *CORE,
                    '-o', 'build/cm-t4rupt-imu-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/cm-t4rupt-imu-reference', str(ROPE), 'build/cm-t4rupt-imu-executed.txt'],
                         cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-t4rupt-imu-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'cm-t4rupt-imu: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_t4rupt_imu_freeze.py from the',
            ' * original Comanche055 program (yaAGC oracle). Per-case digests of the outcome kind and,',
            ' * unless refused, all 2048 erasable words, SUPERBNK and channels 11, 12, 14, 30 and 33. */',
            f'#define CTI_VECTORS {len(digests)}u', *table('cti_expected', digests)]
    (R / 'tests/cm_t4rupt_imu_vectors.h').write_text('\n'.join(head) + '\n')
    c64rows, host_edges, row_edges = c64_case_cover.select('cm-t4rupt-imu', 'cti', 'src/cm_t4rupt_imu.c', 'tests/cm_t4rupt_imu_cases.c',
                                                         'cm_t4rupt_imu_cases.h', len(digests), STRIDE)
    assert row_edges == host_edges
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_t4rupt_imu_freeze.py: the',
            ' * C64 rows of tests/cm_t4rupt_imu_vectors.h, every sixteenth case plus the fewest',
            ' * further cases that run every branch outcome the host cases run',
            f' * (tools/c64_case_cover.py: {host_edges} edges). */',
            f'#define CTI_C64_COUNT {len(c64rows)}u',
            f'static const uint16_t cti_c64_case[{len(c64rows)}]={{' + ','.join(f'{r}u' for r in c64rows) + '};',
            *table('cti_c64', [digests[r] for r in c64rows])]
    (R / 'tests/cm_t4rupt_imu_c64_vectors.h').write_text('\n'.join(head) + '\n')
    entry = lambda n: ENTRIES[0 if n < IMUMON else 1 + (n - IMUMON) // PER]
    kinds = collections.Counter(f"{entry(r[0])}:{('returned', 'alarm', 'refused')[r[1]]}" for r in rows)
    ends = collections.Counter(f'{r[2 + 5]:05o}' for r in rows if r[1] != 2)
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())), 'continuations': dict(sorted(ends.items())), 'entries': ENTRIES,
             'boundary': 'one routine from its entry to the continuation it leaves in Z (RESUME, ALARM, VARALARM, '
                         'WAITLIST, VARDELAY, TASKOVER, IBNKCALL, POSTJUMP, ZEROICDU, or the SETISSW caller); the '
                         'original runs to the first time it reaches that Z (and FB in banked memory)',
             'c64_rows': {'cases': len(c64rows), 'host_edges': host_edges, 'row_edges': row_edges},
             'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, channels 11, 12, 14, 30, 33',
             'full_physical_words': 2048}
    (B / 'cm-t4rupt-imu-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {len(rows)} cm-t4rupt-imu cases equal the original program")


if __name__ == '__main__':
    main()
