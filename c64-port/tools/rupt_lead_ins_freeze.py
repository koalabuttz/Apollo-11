"""Run the original-program oracle for rupt-lead-ins and freeze digests.

Builds the host-only yaAGC driver tools/rupt_lead_ins_reference.c, runs it
on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/rupt-lead-ins-native lm|cm) is byte-identical, and writes
tests/rupt_lead_ins_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit and InIsr) and
tests/rupt_lead_ins_c64_vectors.h (every sixteenth). Also writes
build/rupt-lead-ins-proof.json and build/rupt-lead-ins-executed-{lm,cm}.txt.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = {'lm': B / 'fixed-data/Luminary099/MAIN.agc.bin', 'cm': B / 'fixed-data/Comanche055/MAIN.agc.bin'}
NATIVE = ['src/rupt_lead_ins.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/rupt_lead_ins_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
PER = 128
ENTRIES = {'lm': ['04000 GOPROG lead-in', '04010 T5RUPT', '04020 T4RUPT', '04024 KEYRUPT1', '04030 KEYRUPT2',
                  '04034 UPRUPT', '04040 DOWNRUPT', '04044 RADAR RUPT', '04050 RUPT10'],
           'cm': ['04000 GOPROG lead-in', '04004 T6RUPT', '04010 T5RUPT', '04020 T4RUPT', '04024 KEYRUPT1',
                  '04030 KEYRUPT2', '04034 UPRUPT', '04040 DOWNRUPT', '04044 RADAR RUPT', '04050 HAND CONTROL RUPT',
                  '04065 T5RUPT', '05333 RESUME', '05335 NOQRSM', '05336 NOQRSM +1', '05337 NOQBRSM']}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/rupt_lead_ins_reference.c', *CORE,
                    '-o', 'build/rupt-lead-ins-reference'], cwd=R, check=True)
    full, c64, proof = [], [], {}
    for m in ('lm', 'cm'):
        ref = subprocess.run(['./build/rupt-lead-ins-reference', str(ROPES[m]), m,
                              f'build/rupt-lead-ins-executed-{m}.txt'], cwd=R, check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/rupt-lead-ins-native', m], cwd=R, check=True, capture_output=True).stdout
        assert ref == nat, f'rupt-lead-ins {m}: native differs from the original program'
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        digests = [digest(r[1:]) for r in rows]
        name = m.upper()
        full += [f'#define RLI_{name}_VECTORS {len(digests)}u', *table(f'rli_{m}_expected', digests)]
        c64 += [f'#define RLI_{name}_C64_COUNT {len(digests[::STRIDE])}u', *table(f'rli_{m}_c64', digests[::STRIDE])]
        kinds = collections.Counter(f"{ENTRIES[m][r[0] // PER]}:{('returned', 'alarm', 'refused')[r[1]]}" for r in rows)
        proof[m] = {'mission': ROPES[m].parent.name, 'rope_sha256': hashlib.sha256(ROPES[m].read_bytes()).hexdigest(),
                    'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
                    'outcomes': dict(sorted(kinds.items())), 'entries': ENTRIES[m]}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/rupt_lead_ins_freeze.py from the',
            ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of the',
            ' * outcome kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable and InIsr. */']
    (R / 'tests/rupt_lead_ins_vectors.h').write_text('\n'.join(head + full) + '\n')
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/rupt_lead_ins_freeze.py: every',
            ' * sixteenth digest of tests/rupt_lead_ins_vectors.h, for the C64 diagnostic. */',
            f'#define RLI_C64_STRIDE {STRIDE}u']
    (R / 'tests/rupt_lead_ins_c64_vectors.h').write_text('\n'.join(head + c64) + '\n')
    proof.update({'boundary': 'one lead-in from its vector to the handler it leaves in Z (the GOPROG restart, '
                              'the banked handler, the 2CADR target, or NOQBRSM); the original runs to the first '
                              'time it reaches that Z (and FB in banked memory), or for the Comanche RESUME family '
                              'until the interrupt ends',
                  'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, InIsr',
                  'full_physical_words': 2048,
                  'oracle': 'yaAGC (agc_engine) running the original rope of each mission'})
    (B / 'rupt-lead-ins-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {proof['lm']['cases']} LM and {proof['cm']['cases']} CM rupt-lead-ins cases equal the original programs")


if __name__ == '__main__':
    main()
