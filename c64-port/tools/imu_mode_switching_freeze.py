"""Run the original-program oracle for imu-mode-switching and freeze digests.

Builds the host-only yaAGC driver tools/imu_mode_switching_reference.c
against build/agc_engine_no_imu_device.o (tools/prepare_no_imu_device_engine.py),
runs it on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/imu-mode-switching-native) is byte-identical, and writes
tests/imu_mode_switching_vectors.h (one digest per case: two 16-bit running
sums over the kind, all 2048 erasable words, the interrupt-enable state and
channels 11-14) and tests/imu_mode_switching_c64_vectors.h (C64 subsets).
Also writes build/imu-mode-switching-proof.json with the stops reached.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

import imu_mode_switching_cover

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = [B / 'fixed-data/Luminary099/MAIN.agc.bin', B / 'fixed-data/Comanche055/MAIN.agc.bin']
NATIVE = ['src/imu_mode_switching.c', 'src/agc_image_ops.c', 'src/lm_interbank_routines.c', 'src/lm_interbank.c',
          'src/cm_interbank_routines.c', 'src/cm_interbank_complete.c', 'src/agc_transfer.c', 'src/agc_word.c',
          'src/agc_multiword.c', 'src/agc_hardware_divide.c', 'tests/imu_mode_switching_cases.c']
CORE = NATIVE + ['tests/cm_executive_cases.c', str(B / 'agc_engine_no_imu_device.o'),
                 str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E)]
ROUTINES, LM_ROUTINES, ENTRY_CASES, LM_SITES, SITES = 144, 72, 55296, 74, 128
STRIDE, TRIP_STRIDE = 131, 17
STOPS = {
    0: {0o5567: 'ALARM', 0o5203: 'WAITLIST', 0o5224: 'VARDELAY', 0o5221: 'FIXDELAY', 0o5261: 'TASKOVER',
        0o4674: 'IBNKCALL', 0o4631: 'SWRETURN', 0o4707: 'ISWRETRN', 0o5133: 'JOBSLEEP', 0o5137: 'JOBWAKE',
        0o4645: 'MAKECADR', 0o5716: 'BAILOUT1', 0o5652: 'POODOO', 0o4635: 'POSTJUMP', 0o7257: 'TPAGREE',
        0o7307: 'SHORTMP', 0o4103: 'FINETIME +1', 0o5504: 'UPFLAG', 0o5516: 'DOWNFLAG', 0o5353: 'PHASCHNG',
        0o4616: 'BANKCALL', 0o6001: 'GOTOPOOH', 0o5744: 'VARALARM', 0o4000: 'caller return', 0o4001: 'caller return +1', 0o2703: 'SETISSW'},
    1: {0o5650: 'ALARM', 0o5245: 'WAITLIST', 0o5272: 'VARDELAY', 0o5267: 'FIXDELAY', 0o5324: 'TASKOVER',
        0o4740: 'IBNKCALL', 0o4675: 'SWRETURN', 0o4753: 'ISWRETRN', 0o5175: 'JOBSLEEP', 0o5201: 'JOBWAKE',
        0o4711: 'MAKECADR', 0o5721: 'POODOO', 0o4701: 'POSTJUMP', 0o7226: 'TPAGREE', 0o7256: 'SHORTMP',
        0o4554: 'FINETIME +1', 0o5546: 'UPFLAG', 0o5560: 'DOWNFLAG', 0o5412: 'PHASCHNG', 0o4662: 'BANKCALL',
        0o4106: 'GOTOPOOH', 0o5764: 'VARALARM', 0o4000: 'caller return', 0o4001: 'caller return +1', 0o2665: 'SETISSW'},
}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def rows_table(cases, digests):
    out = [f'static const uint16_t ims_c64_case[{len(cases)}]={{']
    for i in range(0, len(cases), 10):
        out.append(''.join(f'{n}u,' for n in cases[i:i + 10]))
    return out + ['};', *table('ims_c64', [digests[n] for n in cases])]


def main():
    subprocess.run(['cc', *FLAGS, '-w', 'tools/imu_mode_switching_reference.c', *CORE,
                    '-o', 'build/imu-mode-switching-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/imu-mode-switching-reference', *map(str, ROPES)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/imu-mode-switching-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'imu-mode-switching: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/imu_mode_switching_freeze.py from the',
           ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of the',
           ' * kind, all 2048 erasable words, the interrupt-enable state and channels 11-14. */',
           f'#define IMS_VECTORS {len(digests)}u', *table('ims_expected', digests)]
    (R / 'tests/imu_mode_switching_vectors.h').write_text('\n'.join(out) + '\n')
    # C64 rows: the cases that take, per mission, every edge, routine, site
    # and outcome kind of the host stream (tools/imu_mode_switching_cover.py),
    # and every 131st entry case and every 17th round trip of each mission.
    cover = set(imu_mode_switching_cover.select_rows())
    sample = set(range(0, ENTRY_CASES, STRIDE))
    for cm in (0, 1):
        trips = [ENTRY_CASES + i for i in range(len(digests) - ENTRY_CASES) if (i % SITES >= LM_SITES) == cm]
        sample |= set(trips[::TRIP_STRIDE])
    chosen = sorted(cover | sample)
    (B / 'imu-mode-switching-c64-rows.txt').write_text(''.join(f'{n}\n' for n in chosen))
    entry = [n for n in chosen if n < ENTRY_CASES]
    trips = {cm: [n for n in chosen if n >= ENTRY_CASES and ((n - ENTRY_CASES) % SITES >= LM_SITES) == cm]
             for cm in (0, 1)}
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/imu_mode_switching_freeze.py for the',
           f' * C64 diagnostics: {len(cover)} cases that take every edge, routine, site and outcome kind',
           ' * of the host stream in each mission, every 131st entry case and every 17th round trip of',
           ' * each mission. Case numbers and digests. */',
           f'#define IMS_C64_COUNT {len(entry)}u', f'#define IMS_C64_LM_TRIPS {len(trips[0])}u',
           f'#define IMS_C64_CM_TRIPS {len(trips[1])}u',
           '#if defined IMS_ENTRY_ONLY', *rows_table(entry, digests),
           '#elif defined IMS_TRIP_LM', *rows_table(trips[0], digests),
           '#else', *rows_table(trips[1], digests), '#endif']
    (R / 'tests/imu_mode_switching_c64_vectors.h').write_text('\n'.join(out) + '\n')
    stops = collections.defaultdict(collections.Counter)
    for r in rows:
        n, z = r[0], r[2 + 5]
        if n < ENTRY_CASES:
            k = n % ROUTINES
            cm = int(k >= LM_ROUTINES)
            key = f'{"CM" if cm else "LM"} routine {k % LM_ROUTINES}'
        else:
            k = (n - ENTRY_CASES) % SITES
            cm = int(k >= LM_SITES)
            key = f'{"CM" if cm else "LM"} round trip site {k - LM_SITES * cm}'
        name = STOPS[cm].get(z, f'Z {z:05o}' if z < 0o2000 else 'caller continuation')
        stops[key][name] += 1
    proof = {'missions': ['Luminary099', 'Comanche055'],
             'rope_sha256': [hashlib.sha256(p.read_bytes()).hexdigest() for p in ROPES],
             'oracle_engine': 'pinned yaAGC agc_engine.c without its gyro, IMU CDU drive and optics block '
                              '(build/no-imu-device.patch)',
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'stops': {k: dict(sorted(v.items())) for k, v in stops.items()},
             'boundary': 'entry cases: from the routine to the first external address, the subroutine '
                         'return at 04000, or an erasable TC target; round trips: TC BANKCALL or IBNKCALL '
                         'from every genuine site through native INTER-BANK to the caller continuation, an '
                         'external or SETISSW',
             'compared': '2048 erasable words (A, L 16-bit), the interrupt-enable state and channels 11-14'}
    (B / 'imu-mode-switching-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} imu-mode-switching cases equal the original programs')


if __name__ == '__main__':
    main()
