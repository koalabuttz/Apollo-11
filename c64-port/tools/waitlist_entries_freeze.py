"""WAITLIST entries reached from other files (lane A): T3RUPT of both missions,
DLY2 -1 of both, LM NOQBRSM +1. Picks the cases (platform/host/waitlist_entries_scan.c),
builds the native snapshot (platform/host/waitlist_entries_snapshot.c) and the
yaAGC oracle (tools/waitlist_entries_reference.c), requires byte-identical
output on every case, and freezes the case list and one digest per case
(reach flag, SUPERBNK, interrupt enable, InIsr, the 2048 erasable words) into
tests/waitlist_entries_vectors.h. Writes build/waitlist-entries-proof.json.
"""
import hashlib, json, pathlib, re, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
KINDS = ['LM T3RUPT 01,3407', 'CM T3RUPT 01,3416', 'LM DLY2 -1 05211', 'CM DLY2 -1 05255', 'LM NOQBRSM +1 05275']
FLAGS = ['cc', '-std=c99', '-O2', '-Wall', '-Wextra', '-Werror', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections',
         '-fdata-sections', '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Itools']
HEADERS = ['include/agc_transfer.h', 'include/lm_exec_routines.h', 'include/cm_exec_routines.h',
           'include/lm_t6rupt_routines.h', 'include/service_transfer.h', 'tests/waitlist_entries_cases.h']


def sources():
    mk = (R / 'tools/mk/waitlist-entries.mk').read_text()
    text = re.search(r'^WLE_SRC = ((?:.*\\\n)*.*)$', mk, re.M).group(1)
    return [f for f in text.replace('\\\n', ' ').split() if f != 'tests/waitlist_entries_check.c']


def digest(fields):
    a = b = 0
    for v in fields:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def header(cases, digests):
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/waitlist_entries_freeze.py from the original',
           ' * Luminary099 and Comanche055 programs (yaAGC oracle): the cases of tests/waitlist_entries_cases.c',
           ' * by kind (base case) and the Fletcher digest of each case\'s reach flag, SUPERBNK, interrupt',
           ' * enable, InIsr and 2048 erasable words. Cases are numbered kind 0 first. */',
           f'#define WLE_CASES {len(cases)}u']
    for k in range(len(KINDS)):
        rows = [(b, d) for (kk, b), d in zip(cases, digests) if kk == k]
        out += [f'#define WLE_COUNT_{k} {len(rows)}u', f'static const uint16_t wle_base_{k}[{len(rows)}]={{']
        out += [','.join(f'{b}u' for b, _ in rows[i:i + 16]) + ',' for i in range(0, len(rows), 16)] + ['};']
        out += [f'static const uint32_t wle_digest_{k}[{len(rows)}]={{']
        out += [','.join(f'0x{d:08x}u' for _, d in rows[i:i + 8]) + ',' for i in range(0, len(rows), 8)] + ['};']
    return '\n'.join(out) + '\n'


def main():
    src = sources()
    subprocess.run(FLAGS + ['-DWLE_SCAN'] + src + ['platform/host/waitlist_entries_scan.c', '-o', 'build/wle-scan'],
                   cwd=R, check=True)
    cases = sorted((tuple(map(int, l.split())) for l in subprocess.run(['./build/wle-scan'], cwd=R, check=True,
                   capture_output=True, text=True).stdout.splitlines()), key=lambda c: c[0])
    vectors = R / 'tests/waitlist_entries_vectors.h'
    vectors.write_text(header(cases, [0] * len(cases)))
    subprocess.run(FLAGS + src + ['platform/host/waitlist_entries_snapshot.c', '-o', 'build/waitlist-entries-snapshot'],
                   cwd=R, check=True)
    subprocess.run([f for f in FLAGS if f not in ('-Wall', '-Wextra', '-Werror')] + [f'-I{E}',
                    'tools/waitlist_entries_reference.c', 'tests/cm_executive_cases.c'] +
                   [s for s in src if s != 'src/cm_executive.c'] + ['src/cm_executive.c', str(E / 'agc_engine.o'),
                   str(E / 'agc_engine_init.o'), str(E / 'rfopen.o'), '-o', 'build/waitlist-entries-reference'],
                   cwd=R, check=True)
    ropes = [R / 'build/fixed-data' / m / 'MAIN.agc.bin' for m in ('Luminary099', 'Comanche055')]
    native = subprocess.run(['./build/waitlist-entries-snapshot'], cwd=R, check=True, capture_output=True,
                            text=True).stdout.splitlines()
    oracle = subprocess.run(['./build/waitlist-entries-reference'] + [str(r) for r in ropes], cwd=R, check=True,
                            capture_output=True, text=True).stdout.splitlines()
    assert len(native) == len(oracle) == len(cases), (len(native), len(oracle), len(cases))
    differ = [i for i, (x, y) in enumerate(zip(native, oracle)) if x != y]
    assert not differ, f'native differs from yaAGC on cases {differ[:10]}'
    digests, by_kind = [], {k: [0, 0] for k in KINDS}
    for i, line in enumerate(oracle):
        v = list(map(int, line.split()))
        by_kind[KINDS[cases[i][0]]][0] += 1
        by_kind[KINDS[cases[i][0]]][1] += v[1]
        digests.append(digest(v[1:] if v[1] else [0]))
    vectors.write_text(header(cases, digests))
    reached = sum(r for _, r in by_kind.values())
    proof = {'cases': len(cases), 'reached': reached, 'native_equals_yaagc': True,
             'by_kind': {k: {'cases': c, 'reached': r} for k, (c, r) in by_kind.items()},
             'ropes': {r.parent.name: hashlib.sha256(r.read_bytes()).hexdigest() for r in ropes},
             'oracle': 'yaAGC (agc_engine) running the original rope of each mission',
             'oracle_sha256': hashlib.sha256('\n'.join(oracle).encode()).hexdigest(),
             'dependencies': {f: hashlib.sha256((R / f).read_bytes()).hexdigest() for f in src + HEADERS},
             'boundary': ('T3RUPT: from the T3RUPT word after the vector\'s DXCH ARUPT; CAF T3RPTBB; XCH BBANK to the '
                          'dispatched task; DLY2 -1: from DELAYJOB through DLY2 -1, WAIT2 and TCGETCAD to JOBSLEEP or '
                          'BAILOUT; NOQBRSM +1: to the end of the interrupt. yaAGC stops at the native Z (and FB when '
                          'banked) or when InIsr clears')}
    (R / 'build/waitlist-entries-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(cases)} waitlist-entries cases identical to yaAGC, {reached} reach the continuation')


if __name__ == '__main__':
    main()
