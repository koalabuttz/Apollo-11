/* argv: Luminary rope, Comanche rope [, --data]. With --data, prints the rope
 * words of the SUPDACAL data slots (tests/interbank_oracle_data.h). Otherwise,
 * for every case the native run reached (a refusal prints "n 0"), runs the
 * original from the same image, entry, inhibit and SUPERBNK until Z first
 * equals the native Z with the native FB, and prints the inhibit flag,
 * channel 7 and the 2048 erasable words (A, L, Q 16-bit). */
int main(int argc,char **argv){static agc_t rope[2];static apollo_overlay_state s,native;uint16_t n,superbank,inhint,i,p;unsigned cycles;uint8_t m;
 if(argc!=3&&argc!=4)return 2;
 for(i=0;i<2u;++i){memset(&machine,0,sizeof machine);if(agc_load_binfile(&machine,argv[1+i]))return 2;rope[i]=machine;}
 if(argc==4){
  printf("/* SPDX-License-Identifier: MIT; generated by tools/interbank_oracle_freeze.py from the original ropes:\n * the fixed words of the SUPDACAL data slots (ibo_data_physical), Luminary099 then Comanche055. */\n");
  printf("static const uint16_t ibo_data[2][IBO_DATA]={\n");
  for(m=0;m<2u;++m){printf(" {");for(i=0;i<IBO_DATA;++i){p=ibo_data_physical(m,i);printf("0%ou%s",(unsigned)(rope[m].Fixed[p/1024u][p%1024u]&077777),i+1u<IBO_DATA?",":"");}printf("}%s\n",m?"":",");}
  printf("};\n");return 0;}
 InhibitAlarms=1;
 for(n=0;n<ibo_cases();++n){
  if(!ibo_run(&native,&superbank,&inhint,n)){printf("%u 0\n",(unsigned)n);continue;}
  machine=rope[ibo_mission(n)];ibo_input(&s,&superbank,&inhint,n);for(i=0;i<2048u;++i)*memory(i)=(int16_t)s.words[i];
  machine.InputChannel[7]=machine.OutputChannel7=(int16_t)superbank;machine.AllowInterrupt=!inhint;
  for(cycles=0;cycles<20000u;++cycles){
   lane_a_mark(ibo_mission(n));
   if(cycles&&!machine.PendFlag&&!machine.ExtraDelay&&!machine.IndexValue&&!machine.ExtraCode&&get(5)==native.words[5]&&get(4)==native.words[4])break;
   machine.ScalerCounter=0;if(agc_engine(&machine))return 2;}
  if(cycles==20000u){fprintf(stderr,"interbank-oracle case %u timeout\n",(unsigned)n);return 2;}
  printf("%u 1 %u %u",(unsigned)n,(unsigned)!machine.AllowInterrupt,(unsigned)machine.OutputChannel7&0160u);for(i=0;i<2048u;++i)printf(" %u",(unsigned)*memory(i)&(i<3u?0177777u:077777u));printf("\n");
 }
 return lane_a_write_executed();}
