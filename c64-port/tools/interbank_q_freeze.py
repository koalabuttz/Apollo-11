"""INTER-BANK unusual-Q entries (lane A): SWCALL -1 and BANKJUMP with Q below
0100, in both missions. Builds the native snapshot
(platform/host/interbank_q_snapshot.c) and the yaAGC oracle
(tools/interbank_q_reference.c), requires byte-identical output on every case
of tests/interbank_q_cases.c, and freezes one digest per case (the reach flag,
then the 2048 erasable words, Fletcher as ibq_digest) into
tests/interbank_q_vectors.h. Writes build/interbank-q-proof.json.
"""
import hashlib, json, pathlib, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
NATIVE = ['tests/interbank_q_cases.c', 'src/lm_interbank_routines.c', 'src/lm_interbank.c',
          'src/cm_interbank_routines.c', 'src/cm_interbank_complete.c', 'src/agc_transfer.c', 'src/agc_word.c',
          'src/agc_multiword.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c']
HEADERS = ['include/agc_transfer.h', 'include/lm_interbank_routines.h', 'include/cm_interbank_routines.h',
           'include/lm_interbank.h', 'include/cm_interbank_complete.h', 'tests/interbank_q_cases.h']
FLAGS = ['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Itools', '-Iplatform/host']


def digest(fields):
    a = b = 0
    for v in fields:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def main():
    subprocess.run(FLAGS + NATIVE + ['platform/host/interbank_q_snapshot.c', '-o', 'build/interbank-q-snapshot'],
                   cwd=R, check=True)
    subprocess.run(FLAGS + [f'-I{E}', 'tools/interbank_q_reference.c', 'src/cm_executive.c',
                            'tests/cm_executive_cases.c'] + [s for s in NATIVE if s != 'src/agc_word.c'] +
                   ['src/agc_word.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o'),
                    '-o', 'build/interbank-q-reference'], cwd=R, check=True)
    ropes = [R / 'build/fixed-data' / m / 'MAIN.agc.bin' for m in ('Luminary099', 'Comanche055')]
    native = subprocess.run(['./build/interbank-q-snapshot'], cwd=R, check=True, capture_output=True,
                            text=True).stdout
    oracle = subprocess.run(['./build/interbank-q-reference'] + [str(r) for r in ropes], cwd=R, check=True,
                            capture_output=True, text=True).stdout
    nl, ol = native.splitlines(), oracle.splitlines()
    assert len(nl) == len(ol) == 1024, (len(nl), len(ol))
    differ = [i for i, (x, y) in enumerate(zip(nl, ol)) if x != y]
    assert not differ, f'native differs from yaAGC on cases {differ[:10]}'
    digests, reached = [], 0
    for i, line in enumerate(ol):
        v = list(map(int, line.split()))
        assert v[0] == i
        reached += v[1]
        digests.append(digest(v[1:] if v[1] else [0]))
    kinds = ['LM SWCALL -1', 'CM SWCALL -1', 'LM BANKJUMP', 'CM BANKJUMP']
    proof = {'cases': 1024, 'reached_callee': reached, 'native_equals_yaagc': True,
             'by_kind': {k: sum(1 for i, l in enumerate(ol) if i % 4 == j and l.split()[1] == '1')
                         for j, k in enumerate(kinds)},
             'bankjump_q_below_0100': sum(1 for i in range(1024) if i % 4 >= 2 and (i // 4) % 2),
             'ropes': {r.parent.name: hashlib.sha256(r.read_bytes()).hexdigest() for r in ropes},
             'oracle_sha256': hashlib.sha256(oracle.encode()).hexdigest(),
             'dependencies': {f: hashlib.sha256((R / f).read_bytes()).hexdigest() for f in NATIVE + HEADERS},
             'boundary': ('from the INTER-BANK entry (SWCALL -1 or BANKJUMP) with a random erasable image to the '
                          'first instruction of the callee; yaAGC stops when Z and FB first equal the native ones')}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/interbank_q_freeze.py from the original',
            ' * Luminary099 and Comanche055 programs (yaAGC oracle): per case of tests/interbank_q_cases.c,',
            ' * the Fletcher digest of the reach flag and the 2048 erasable words at the callee. */',
            '#define IBQ_VECTORS 1024u',
            'static const uint32_t ibq_digests[1024]={']
    head += [','.join(f'0x{d:08x}u' for d in digests[i:i + 8]) + ',' for i in range(0, 1024, 8)] + ['};']
    (R / 'tests/interbank_q_vectors.h').write_text('\n'.join(head) + '\n')
    (R / 'build/interbank-q-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: 1024 interbank-q cases identical to yaAGC, {reached} reach the callee')


if __name__ == '__main__':
    main()
