"""Run the original-program oracle for cm-t4rupt-chain and freeze digests.

Builds the host-only yaAGC driver tools/cm_t4rupt_chain_reference.c, runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-t4rupt-chain-native) is byte-identical, and writes
tests/cm_t4rupt_chain_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, IRQ enable, InIsr and channels 10-14 and 30-33) and
tests/cm_t4rupt_chain_c64_vectors.h (every sixteenth). Also writes
build/cm-t4rupt-chain-proof.json and build/cm-t4rupt-chain-executed.txt.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
NATIVE = ['src/t4rupt_core.c', 'src/cm_t4rupt_imu.c', 'src/cm_t4rupt_optics.c', 'src/cm_interp_orders.c', 'src/cm_interp_steps.c',
          'src/lm_interp_orders.c', 'src/lm_interp_steps.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
          'src/agc_transfer.c', 'src/agc_multiword.c', 'tests/cm_t4rupt_chain_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'src/cm_executive.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/cm_t4rupt_chain_reference.c', *CORE,
                    '-o', 'build/cm-t4rupt-chain-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/cm-t4rupt-chain-reference', str(ROPE), 'build/cm-t4rupt-chain-executed.txt'],
                         cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-t4rupt-chain-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'cm-t4rupt-chain: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_t4rupt_chain_freeze.py from the',
            ' * original Comanche055 program (yaAGC oracle). Per-case digests of the outcome kind and,',
            ' * unless refused, all 2048 erasable words, SUPERBNK, IRQ enable, InIsr and channels 10-14, 30-33. */',
            f'#define CCH_VECTORS {len(digests)}u', *table('cch_expected', digests)]
    (R / 'tests/cm_t4rupt_chain_vectors.h').write_text('\n'.join(head) + '\n')
    c64rows = list(range(0, len(digests), STRIDE))
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_t4rupt_chain_freeze.py: every',
            ' * sixteenth digest of tests/cm_t4rupt_chain_vectors.h, for the C64 diagnostic (with the',
            ' * cover rows of tests/cm_t4rupt_chain_c64_rows.h, tools/lane_a_c64_cover.py). */',
            f'#define CCH_C64_STRIDE {STRIDE}u',
            f'#define CCH_C64_COUNT {len(c64rows)}u',
            *table('cch_c64', [digests[r] for r in c64rows])]
    (R / 'tests/cm_t4rupt_chain_c64_vectors.h').write_text('\n'.join(head) + '\n')
    kinds = collections.Counter(('returned', 'alarm', 'refused')[r[1]] for r in rows)
    ends = collections.Counter(f'{r[2 + 5]:05o}' for r in rows if r[1] != 2)
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())), 'continuations': dict(sorted(ends.items())),
             'tables': ['cm_t4rupt_core_routines', 'cm_t4rupt_imu_routines', 'cm_t4rupt_optics_basic'],
             'boundary': 'one T4RUPT interrupt from 06,2000 through agc_transfer_run over the three routine tables of the '
                         'file until the first continuation outside them; the original runs from T4RUPT to the first '
                         'time it reaches that Z (and FB in banked memory)',
             'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, InIsr, channels 10, 11, 12, 13, 14, 30, 31, 32, 33',
             'full_physical_words': 2048}
    (B / 'cm-t4rupt-chain-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {len(rows)} cm-t4rupt-chain cases equal the original program")


if __name__ == '__main__':
    main()
