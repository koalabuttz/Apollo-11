"""SYSTEM_TEST_STANDARD_LEAD_INS of both missions (lane A, milestone
standard-lead-oracle): every registered entry and interpretive word, through
agc_transfer_run. Builds the native snapshot
(platform/host/standard_lead_oracle_snapshot.c) and the yaAGC oracle
(tools/standard_lead_oracle_reference.c), requires byte-identical output on
every case of tests/standard_lead_oracle_cases.c, and freezes one digest per
case (the reach flag, then the interrupt inhibit, SUPERBNK and the 2048
erasable words, Fletcher as slo_digest) into
tests/standard_lead_oracle_vectors.h. Writes build/standard-lead-oracle-proof.json.
"""
import collections, hashlib, json, pathlib, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
NATIVE = ['tests/standard_lead_oracle_cases.c', 'src/agc_transfer.c', 'src/standard_lead_routines.c',
          'src/standard_lead.c', 'src/standard_lead_interp.c', 'src/standard_lead_wake.c', 'src/lm_basic_wake.c',
          'src/executive.c', 'src/cm_basic_wake.c', 'src/cm_native_image.c', 'src/cm_dispatch.c',
          'src/lm_interbank_routines.c', 'src/lm_interbank.c', 'src/cm_interbank_routines.c',
          'src/cm_interbank_complete.c', 'src/agc_word.c', 'tests/standard_lead_cases.c']
HEADERS = ['include/agc_transfer.h', 'include/standard_lead_routines.h', 'include/standard_lead.h',
           'include/standard_lead_wake.h', 'include/lm_interbank_routines.h', 'include/cm_interbank_routines.h',
           'tests/standard_lead_oracle_cases.h', 'tests/standard_lead_cases.h', 'tests/standard_lead_fixed_inputs.h']
FLAGS = ['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Itools', '-Iplatform/host']
KINDS = ['E/BKCALL', 'RETURN0', 'RETURN1', 'RETURN2', 'E/CALL', 'E/CALL resume', 'E/JOBWAK', 'INTPRET',
         'INTPRET+2', 'EXIT word', 'CALL word']


def digest(fields):
    a = b = 0
    for v in fields:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def main():
    subprocess.run(FLAGS + NATIVE + ['src/cm_executive.c', 'platform/host/standard_lead_oracle_snapshot.c',
                                     '-o', 'build/standard-lead-oracle-snapshot'], cwd=R, check=True)
    subprocess.run(FLAGS + [f'-I{E}', 'tools/standard_lead_oracle_reference.c', 'src/cm_executive.c',
                            'tests/cm_executive_cases.c'] + [s for s in NATIVE if s != 'src/agc_word.c'] +
                   ['src/agc_word.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o'),
                    '-o', 'build/standard-lead-oracle-reference'], cwd=R, check=True)
    ropes = [R / 'build/fixed-data' / m / 'MAIN.agc.bin' for m in ('Luminary099', 'Comanche055')]
    native = subprocess.run(['./build/standard-lead-oracle-snapshot'], cwd=R, check=True, capture_output=True,
                            text=True).stdout
    oracle = subprocess.run(['./build/standard-lead-oracle-reference'] + [str(r) for r in ropes], cwd=R,
                            check=True, capture_output=True, text=True).stdout
    nl, ol = native.splitlines(), oracle.splitlines()
    assert len(nl) == len(ol), (len(nl), len(ol))
    cases = len(ol)
    differ = [i for i, (x, y) in enumerate(zip(nl, ol)) if x != y]
    assert not differ, f'native differs from yaAGC on cases {differ[:10]}'
    digests, reached, per_kind = [], 0, collections.Counter()
    for i, line in enumerate(ol):
        v = list(map(int, line.split()))
        assert v[0] == i
        reached += v[1]
        per_kind[('LM', 'CM')[i % 2] + ' ' + KINDS[(i // 2) % len(KINDS)]] += v[1]
        digests.append(digest(v[1:] if v[1] else [0]))
    proof = {'cases': cases, 'reached_continuation': reached, 'native_equals_yaagc': True,
             'reached_by_entry': dict(sorted(per_kind.items())), 'cases_per_entry': 64,
             'ropes': {r.parent.name: hashlib.sha256(r.read_bytes()).hexdigest() for r in ropes},
             'oracle': 'yaAGC agc_engine from the original ropes',
             'oracle_sha256': hashlib.sha256(oracle.encode()).hexdigest(),
             'dependencies': {f: hashlib.sha256((R / f).read_bytes()).hexdigest() for f in NATIVE + HEADERS},
             'boundary': ('from each registered entry of SYSTEM_TEST_STANDARD_LEAD_INS, the INTERPRETER points its '
                          'paths reach and its CALL and EXIT words at the fetch point, with a deterministic image, '
                          'to the first continuation outside the file; yaAGC stops when Z and FB first equal the '
                          'native ones')}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/standard_lead_oracle_freeze.py from the original',
            ' * Luminary099 and Comanche055 programs (yaAGC oracle): per case of tests/standard_lead_oracle_cases.c,',
            ' * the Fletcher digest of the reach flag, the inhibit flag, SUPERBNK and the 2048 erasable words. */',
            f'#define SLO_VECTORS {cases}u',
            f'static const uint32_t slo_digests[{cases}]={{']
    head += [','.join(f'0x{d:08x}u' for d in digests[i:i + 8]) + ',' for i in range(0, cases, 8)] + ['};']
    (R / 'tests/standard_lead_oracle_vectors.h').write_text('\n'.join(head) + '\n')
    # Every third case (both missions, every entry) for the C64 diagnostic.
    c64 = digests[::3]
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/standard_lead_oracle_freeze.py: every',
            ' * third digest of tests/standard_lead_oracle_vectors.h, for the C64 diagnostic. */',
            '#define SLO_C64_STRIDE 3u', f'#define SLO_C64_COUNT {len(c64)}u',
            f'static const uint32_t slo_c64[{len(c64)}]={{']
    head += [','.join(f'0x{d:08x}ul' for d in c64[i:i + 6]) + ',' for i in range(0, len(c64), 6)] + ['};']
    (R / 'tests/standard_lead_oracle_c64_vectors.h').write_text('\n'.join(head) + '\n')
    (R / 'build/standard-lead-oracle-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {cases} standard-lead-oracle cases identical to yaAGC, {reached} reach a continuation')


if __name__ == '__main__':
    main()
