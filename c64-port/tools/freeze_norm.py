#!/usr/bin/env python3
"""Freeze lossless bounded complete arithmetic states after oracle equality."""
import hashlib,pathlib
from frozen_words import encode_rows,c_header
root=pathlib.Path(__file__).resolve().parents[1]
data=(root/'build/norm-reference.snapshots').read_bytes()
assert data==(root/'build/norm-native.snapshots').read_bytes()
rows=[list(map(int,l.split())) for l in data.decode().splitlines()]
assert len(rows)==132096 and all(len(r)==22 for r in rows)
indices=sorted(set(list(range(128))+[61*i for i in range(256)]+[1024+511*i for i in range(256)]))
packed=encode_rows([rows[i][1:] for i in indices])
s='/* SPDX-License-Identifier: MIT\n * Generated by tools/freeze_norm.py from unchanged historical assembly\n * with pinned hardware DV. Full snapshot SHA256: '+hashlib.sha256(data).hexdigest()+'\n */\n'
s+='#ifndef NORM_VECTORS_H\n#define NORM_VECTORS_H\n'+c_header(packed,'norm')
s+='\n#ifdef NORM_FROZEN_IMPLEMENTATION\nconst uint32_t norm_reference_cases[NORM_FROZEN_ROWS]={\n'
for i in range(0,len(indices),16): s+='    '+','.join(str(n)+'u' for n in indices[i:i+16])+',\n'
s+='};\n#else\nextern const uint32_t norm_reference_cases[NORM_FROZEN_ROWS];\n#endif\n#endif\n'
(root/'tests/norm_vectors.h').write_text(s)
print(f'Frozen {len(indices)} SQRT/SQRTSUB states, 21 words including path; {packed.storage_bytes} packed bytes + {len(indices)*4} case-index bytes')
