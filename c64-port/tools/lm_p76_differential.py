"""Run unchanged Luminary099 in the pinned yaAGC oracle from every lm-p76
case (tests/lm_p76_cases.c) to its first stop, check the native trampoline
run of the P76 routines against every row, pin the stream identity, and
freeze per-case digests: tests/lm_p76_vectors.h (all cases, and the C64 sample). Archives the oracle stream as
build/lm-p76-reference.snapshots.bin.xz and writes build/lm-p76-proof.json
with the stops per routine. --record rewrites the pinned identity."""
import argparse,collections,hashlib,json,lzma,pathlib,struct,subprocess,sys
R=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(R/'tools'))
from lm_p76_core import CORE,CASES
ROW=4106;ROUTINES=28;STATES=ROUTINES*512
PIN=R/'evidence/lm-p76/lm-p76-source-stream.json'
NAMES=['DELVOV save (2212)','TIG (2233)','COMPMAT (2237)','after INTSTALL (2261)','after P76SUB1 (2263)','after INTEGRVS (2302)','after INTSTALL (2304)','after MINIRECT (2315)','after INTPRET (2323)','after ATOPOTH (2325)','OUT (2332)','P76SUB1 (2340)',
 'P76 (2207)','after UPFLAG (2211)','V06N84 flash (2216)','terminate (2221)','proceed (2222)','recycle (2223)','V06N33 flash (2224)','terminate (2227)','proceed (2230)','recycle (2231)','INTPRET (2232)','PHASCHNG (2316)','after PHASCHNG (2320)','after UPFLAG (2322)','INTWAKE1 (2330)','ENDP76 (2333)']
def digest(vals):
 a=b=0
 for v in vals:a=(a+v)&0xffff;b=(b+a)&0xffff
 return b<<16|a
def table(name,values):
 out=[f'static const uint32_t {name}[{len(values)}]={{']
 for i in range(0,len(values),6):out.append(''.join(f'0x{v:08x}ul,'for v in values[i:i+6]))
 return out+['};']
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--record',action='store_true');a=p.parse_args()
(R/'build').mkdir(exist_ok=True)
# CI runs a spec's test- and sanitize- targets at once; both rebuild these build/ outputs, so one waits.
import fcntl;LOCK=open(R/'build'/(pathlib.Path(__file__).stem+'.lock'),'w');fcntl.flock(LOCK,fcntl.LOCK_EX)
if not (R/'build/agc_engine_hardware_dv.o').exists():subprocess.run([sys.executable,'tools/prepare_hardware_dv.py'],cwd=R,check=True)
subprocess.run(['gcc','-std=c99','-O2','-DLM_P76_NO_TRAMPOLINE','-Iinclude','-Itests','-Ideps/virtualagc/yaAGC','-Itools','tools/lm_p76_reference.c',*CASES,'tests/cm_executive_cases.c','src/agc_word.c','build/agc_engine_hardware_dv.o','deps/virtualagc/yaAGC/agc_engine_init.o','deps/virtualagc/yaAGC/rfopen.o','-lm','-o','build/lm-p76-reference'],cwd=R,check=True)
subprocess.run(['cc','-std=c99','-O2','-Wall','-Wextra','-Werror','-Wconversion','-pedantic','-Iinclude','-Itests','tools/lm_p76_snapshot.c',*CORE,'-lm','-o','build/lm-p76-native'],cwd=R,check=True)
ref=subprocess.Popen(['build/lm-p76-reference','deps/lm-rtb-fixture/MAIN.agc.bin',str(STATES)],cwd=R,stdout=subprocess.PIPE)
nat=subprocess.Popen(['build/lm-p76-native',str(STATES)],cwd=R,stdout=subprocess.PIPE)
out_path=R/'build/lm-p76-reference.snapshots.bin.xz';tmp=out_path.with_suffix('.xz.part');archive=lzma.open(tmp,'wb',preset=6)
h=hashlib.sha256();size=0;tags=collections.Counter();digests=[];stops=collections.defaultdict(collections.Counter)
for n in range(STATES):
 x=ref.stdout.read(ROW);y=nat.stdout.read(ROW)
 if len(x)!=ROW or x!=y:
  ref.kill();nat.kill()
  if len(x)==ROW==len(y):
   X=struct.unpack('<2053H',x);Y=struct.unpack('<2053H',y)
   print('FAIL case',n,[(f'{i-5:04o}',f'{v:06o}',f'{Y[i]:06o}')for i,v in enumerate(X)if v!=Y[i]][:25])
  else:print('FAIL case',n,'short row')
  raise SystemExit(1)
 X=struct.unpack('<2053H',x);h.update(x);archive.write(x);size+=len(x);tags[X[4]]+=1
 digests.append(digest([X[4],*X[5:],X[2]]))
 w=X[5:];z=w[5];fb=w[4]&0o76000
 if z==0o6070:name=f'NEWOPS {fb>>10:02o},{w[0o164]:04o}' if fb in(0o26000,0o20000,0o22000,0o24000) else 'NEWOPS of a CADR in another bank'
 else:name={0o5504:'UPFLAG',0o5353:'PHASCHNG',0o4616:'BANKCALL',0o6001:'GOTOPOOH',0o6037:'INTPRET',0o5726:'POODOO1 (1302)'}.get(z,f'Z {z:04o}')
 stops[NAMES[n%ROUTINES]][name]+=1
if ref.stdout.read(1)or nat.stdout.read(1)or ref.wait()or nat.wait():raise SystemExit('FAIL producer exit or trailing bytes')
archive.close();tmp.replace(out_path)
identity=dict(archive='build/lm-p76-reference.snapshots.bin.xz',decoded_sha256=h.hexdigest(),decoded_bytes=size,cases=STATES,tag_counts={str(k):v for k,v in sorted(tags.items())},oracle='pinned yaAGC hardware-DV variant, deps/lm-rtb-fixture/MAIN.agc.bin (unchanged Luminary099)')
if a.record:PIN.parent.mkdir(parents=True,exist_ok=True);PIN.write_text(json.dumps(identity,indent=2)+'\n')
pin=json.loads(PIN.read_text())
if (pin['decoded_sha256'],pin['decoded_bytes'])!=(identity['decoded_sha256'],size):raise SystemExit('FAIL oracle stream differs from the pinned identity')
head=['/* SPDX-License-Identifier: MIT; generated by tools/lm_p76_differential.py: digests of the',' * original Luminary099 run of every lm-p76 case (see tests/lm_p76_cases.h). */']
# C64 samples: each group's cases spread over the 512 variants, cycling
# through the group's entries (case k: variant k*512/count, entry k%len).
# Group 1 holds COMPMAT (UNIT, VXV, VXM); group 2 every other entry (C64
# RAM).
GROUPS={1:(2,),2:tuple(r for r in range(ROUTINES)if r!=2)};COUNT={1:128,2:520}
c64={g:[k*512//COUNT[g]*ROUTINES+r[k%len(r)]for k in range(COUNT[g])]for g,r in GROUPS.items()}
lines=[*head,f'#define LM_P76_VECTORS {len(digests)}u','#ifndef LM_P76_C64_GROUP',*table('lm_p76_expected',digests)]
for g,r in GROUPS.items():lines+=[f'#elif LM_P76_C64_GROUP=={g}',f'#define LM_P76_C64_CASES {len(c64[g])}u','static const uint8_t lm_p76_c64_routine[%d]={%s};'%(len(r),','.join(map(str,r))),*table('lm_p76_expected',[digests[n]for n in c64[g]])]
(R/'tests/lm_p76_vectors.h').write_text('\n'.join([*lines,'#endif'])+'\n')
proof=dict(cases=STATES,c64_groups={str(g):len(v)for g,v in c64.items()},stream_sha256=h.hexdigest(),stops={k:dict(sorted(v.items()))for k,v in stops.items()},boundary='each case runs from its entry (NEWOPS or Z) through the trampoline (this file\'s routines) to the first point outside them; the oracle stops at the same point (tests/lm_p76_cases.c lm_p76_stop: a NEWOPS outside 13,2212-2350, UPFLAG, PHASCHNG, BANKCALL, GOTOPOOH, INTPRET, POODOO1)',compared='2048 erasable words (A, L 16-bit), the interrupt-enable state and SUPERBNK')
(R/'build/lm-p76-proof.json').write_text(json.dumps(proof,indent=1)+'\n')
print(f'PASS {STATES} original P76 entries equal native trampoline runs',h.hexdigest(),flush=True)
