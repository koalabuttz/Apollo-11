"""Run the original-program oracle for keyrupt-uprupt and freeze digests.

Builds the host-only yaAGC driver tools/keyrupt_uprupt_reference.c, runs it
on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/keyrupt-uprupt-native lm|cm) is byte-identical, and writes
tests/keyrupt_uprupt_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit, InIsr and channel 11) and
tests/keyrupt_uprupt_c64_vectors.h (every sixteenth). Also writes
build/keyrupt-uprupt-proof.json and build/keyrupt-uprupt-executed-{lm,cm}.txt.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = {'lm': B / 'fixed-data/Luminary099/MAIN.agc.bin', 'cm': B / 'fixed-data/Comanche055/MAIN.agc.bin'}
NATIVE = ['src/keyrupt_uprupt.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/keyrupt_uprupt_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
PER = 256
ENTRIES = {'lm': ['04,3274 KEYRUPT1', '04,3300 KEYRUPT1 +4 (LODSAMPT return)', '04,3303 KEYCOM',
                  '04,3313 ACCEPTUP +4 (NOVAC return)', '04,3317 UPRUPT', '04,3323 UPRUPT +4 (LODSAMPT return)'],
           'cm': ['07,3673 KEYRUPT1', '07,3677 KEYRUPT1 +4 (LODSAMPT return)', '07,3702 KEYCOM',
                  '07,3712 ACCEPTUP +4 (NOVAC return)', '07,3716 UPRUPT', '07,3722 UPRUPT +4 (LODSAMPT return)']}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/keyrupt_uprupt_reference.c', *CORE,
                    '-o', 'build/keyrupt-uprupt-reference'], cwd=R, check=True)
    full, c64, proof = [], [], {}
    for m in ('lm', 'cm'):
        ref = subprocess.run(['./build/keyrupt-uprupt-reference', str(ROPES[m]), m,
                              f'build/keyrupt-uprupt-executed-{m}.txt'], cwd=R, check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/keyrupt-uprupt-native', m], cwd=R, check=True, capture_output=True).stdout
        assert ref == nat, f'keyrupt-uprupt {m}: native differs from the original program'
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        digests = [digest(r[1:]) for r in rows]
        name = m.upper()
        full += [f'#define KU_{name}_VECTORS {len(digests)}u', *table(f'ku_{m}_expected', digests)]
        c64 += [f'#define KU_{name}_C64_COUNT {len(digests[::STRIDE])}u', *table(f'ku_{m}_c64', digests[::STRIDE])]
        kinds = collections.Counter(f"{ENTRIES[m][r[0] // PER]}:{('returned', 'alarm', 'refused')[r[1]]}" for r in rows)
        proof[m] = {'mission': ROPES[m].parent.name, 'rope_sha256': hashlib.sha256(ROPES[m].read_bytes()).hexdigest(),
                    'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
                    'outcomes': dict(sorted(kinds.items())), 'entries': ENTRIES[m]}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/keyrupt_uprupt_freeze.py from the',
            ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of the',
            ' * outcome kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable, InIsr and channel 11. */']
    (R / 'tests/keyrupt_uprupt_vectors.h').write_text('\n'.join(head + full) + '\n')
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/keyrupt_uprupt_freeze.py: every',
            ' * sixteenth digest of tests/keyrupt_uprupt_vectors.h, for the C64 diagnostic. */',
            f'#define KU_C64_STRIDE {STRIDE}u']
    (R / 'tests/keyrupt_uprupt_c64_vectors.h').write_text('\n'.join(head + c64) + '\n')
    proof.update({'boundary': 'one routine from its entry to the continuation it leaves in Z (LODSAMPT, NOVAC '
                              'or RESUME, all in fixed-fixed memory); the original runs to the first time it '
                              'reaches that Z',
                  'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, InIsr, channel 11',
                  'full_physical_words': 2048,
                  'oracle': 'yaAGC (agc_engine) running the original rope of each mission'})
    (B / 'keyrupt-uprupt-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {proof['lm']['cases']} LM and {proof['cm']['cases']} CM keyrupt-uprupt cases equal the original programs")


if __name__ == '__main__':
    main()
