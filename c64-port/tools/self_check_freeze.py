"""Run the original-program oracle for self-check and freeze digests.

Builds the host-only yaAGC driver (tools/self_check_reference.c, with the
per-case trace of tools/case_trace.h) and, for each mission, runs it on the
unmodified rope (Luminary099, Comanche055), checks the native snapshot
(build/self-check-native) is byte-identical, fails if an instruction of
AGC_BLOCK_TWO_SELF-CHECK (bank 43) but FXADRS is never executed, and writes
tests/{lm,cm}_self_check_vectors.h (one digest per case: two 16-bit running
sums over the printed values) and the C64 rows chosen by outcome
(tools/c64_rows.py; every STRIDEth case) to tests/{lm,cm}_self_check_c64_vectors.h.
Also writes build/self-check-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import c64_rows  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
STRIDE = 64
# mission index, name, prefix, offset of its words below Comanche055's
MISSIONS = [(0, 'Luminary099', 'lm_self_check', 2), (1, 'Comanche055', 'cm_self_check', 0)]
CORE = ['tests/self_check_cases.c', 'src/lm_self_check.c', 'src/cm_self_check.c', 'src/agc_image_ops.c',
        'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c',
        'tests/cm_executive_cases.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


# Words no state can reach (Comanche055 addresses): the +0 outcome of a CCS
# on a ones'-complement sum whose last addend is never +0, which the adder
# cannot make +0 (x + -x is -0). -1CHK's TCF PRERRORS at 3277: every TC -1CHK
# follows an AD of a nonzero word (an ERASCHK address, S+1, S-1, CONC+S2, or
# the complemented address); CCS L's TC CONTINU at 3612: L is ADSUM's result
# plus SBIT11.
UNREACHABLE = {0o3277: 'CCS A +0 at -1CHK', 0o3612: 'CCS L +0 at ADRSCHK'}


def owned(d):
    """The file's words in bank 43 (Comanche055 3234-3725, shifted by d) but FXADRS (3561-3564) and UNREACHABLE, physical."""
    return [0o43 * 1024 + w - d - 0o2000 for w in range(0o3234, 0o3726)
            if not 0o3561 <= w <= 0o3564 and w not in UNREACHABLE]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    trace = B / 'self-check.trace'
    subprocess.run(['cc', '-std=c99', '-O2', f'-DCASE_TRACE={trace}', '-Iinclude', '-Itests', '-Isrc', '-Itools', '-I' + str(E),
                    'tools/self_check_reference.c', *CORE, '-o', 'build/self-check-reference'],
                   cwd=R, check=True)
    proof = {'oracle': 'yaAGC (deps/virtualagc), host only', 'missions': {}}
    for mission, name, prefix, d in MISSIONS:
        rope = B / f'fixed-data/{name}/MAIN.agc.bin'
        ref = subprocess.run(['./build/self-check-reference', str(mission), str(rope)], cwd=R, check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/self-check-native', str(mission)], cwd=R, check=True, capture_output=True).stdout
        if ref != nat:
            for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
                if a != b:
                    x, y = a.split(), b.split()
                    diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                    raise SystemExit(f'{name} case {i}: native differs from the original program at {diff}')
            raise SystemExit(f'{name}: native output length differs')
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        values = [digest(r[1:]) for r in rows]
        out = [f'/* SPDX-License-Identifier: MIT; generated by tools/self_check_freeze.py from the',
               f' * original {name} program (yaAGC oracle). Per-case digests of the interrupt-enable',
               ' * state, SUPERBNK and all 2048 erasable words. */',
               f'#define {prefix.upper()}_VECTORS {len(values)}u']
        table(out, f'{prefix}_expected', values)
        (R / f'tests/{prefix}_vectors.h').write_text('\n'.join(out) + '\n')
        cases = c64_rows.read(trace)
        assert sorted(cases) == list(range(len(values)))
        own = owned(d)
        missed = c64_rows.unexecuted_instructions(c64_rows.listing(rope.parent / 'assembly.lst'), own,
                                                  frozenset().union(*cases.values()))
        if missed:
            raise SystemExit(f'{name}: instructions of the milestone no case executes: {missed}')
        chosen = c64_rows.rows(cases, STRIDE)
        (R / f'tests/{prefix}_c64_vectors.h').write_text(c64_rows.c64_header('self_check', prefix, values, chosen, STRIDE))
        proof['missions'][name] = {'rope_sha256': hashlib.sha256(rope.read_bytes()).hexdigest(), 'cases': len(values),
                                   'snapshot_sha256': hashlib.sha256(ref).hexdigest(), **c64_rows.summary(cases, chosen, own)}
        print(f'PASS: {name}: {len(values)} cases equal the original program; {len(chosen)} C64 rows cover every word the host cases execute')
    proof.update({'entries': 'SELFCHK, STSHOSUM, NXTBNK and the return point after every TC out of the file (11)',
                  'boundary': 'entry to the first point outside bank 43 3234-3725 (Comanche055 addresses; Luminary099 two lower): ALARM2, POSTJUMP, SUPDACAL, CHANG1, LEFT5, SDISPLAY, ENDSUMS, a TC SFAIL/SKEEP1 target outside the file, or FXADRS (3561, not translated)',
                  'not_executed': {'FXADRS (3561-3564)': 'not translated: ROPECHK reads the whole rope there; a run stops',
                                   **{f'{w:04o}': why for w, why in UNREACHABLE.items()}},
                  'full_physical_words': 2048})
    (B / 'self-check-proof.json').write_text(json.dumps(proof, indent=1) + '\n')


if __name__ == '__main__':
    main()
