"""Generate include/interp_runtime_tables.h: the INTERPRETER.agc addresses
and dispatch tables the runtime interpreter (src/lm_interp_runtime.c) needs,
for Luminary099 (default) and Comanche055 (INTERP_COMANCHE), from the
yaYUL listings.

The jump tables are the TCF targets of INDJUMP (32 address orders),
MISCJUMP (16 index, branch and miscellaneous orders) and UNAJUMP (15 unary
orders, UNAJUMP +0 being order code 01): the body PCs the dispatch paths
leave in Z, as tools/interp_compile.py passes them.

  interp_runtime_generate.py [--check]"""
import os
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import interp_listing as IL

R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(R, 'include/interp_runtime_tables.h')
# Basic points of INTERPRETER.agc the interpreter runs from, as logical Z.
POINTS = ('NEWOPS', 'DANZIG', 'NOIBNKSW', 'DIRADRES', 'DODLOAD', 'DODLOAD*', 'DOVLOAD', 'DOVLOAD*', '15BITADR', 'GOTO',
          'SWRETURN', 'INTPRET', 'CHANG2', 'SHORTT', 'SHORTV')


def logical(phys):
    bank, off = divmod(phys, 1024)
    if bank in (2, 3):
        return 0o4000 + (bank - 2) * 1024 + off
    return 0o2000 + off


def table(L, label, count):
    base = L.labels[label]
    out = []
    for i in range(count):
        ln = L.by_phys.get(base + i)
        out.append(ln.words[0] & 0o7777 if ln is not None and ln.op == 'TCF' and ln.operand else 0)
    return out


def mission(m):
    L = IL.load(m)
    lab = L.labels
    pre = 'IRT_'
    lines = []
    for p in POINTS:
        name = p.replace('*', 'X').replace('15', 'B15')
        lines.append('#define %s%s 0%05ou' % (pre, name, logical(lab[p])))
    lines.append('#define %sDLOADX_WORD 0%05ou /* DLOAD* (the CYR code DODLOAD* loads) */' % (pre, L.word(lab['DLOAD*'])))
    for lbl, n in (('INDJUMP', 32), ('MISCJUMP', 16), ('UNAJUMP', 15)):
        t = table(L, lbl, n)
        lines.append('#define %s%s {%s}' % (pre, lbl, ','.join('0%05o' % x for x in t)))
    return lines


def render():
    out = ['/* SPDX-License-Identifier: MIT */',
           '/* Generated by tools/interp_runtime_generate.py from the yaYUL listings: do',
           ' * not edit. INTERPRETER.agc addresses (logical Z) and the INDJUMP, MISCJUMP',
           ' * and UNAJUMP body PCs for the runtime interpreter. */',
           '#ifndef INTERP_RUNTIME_TABLES_H', '#define INTERP_RUNTIME_TABLES_H', '#ifdef INTERP_COMANCHE']
    out += mission('cm')
    out.append('#else')
    out += mission('lm')
    out += ['#endif', '#endif', '']
    return '\n'.join(out)


def main(argv):
    text = render()
    if '--check' in argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ''
        if cur != text:
            print('%s is stale: run tools/interp_runtime_generate.py' % OUT)
            return 1
        return 0
    open(OUT, 'w').write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
