"""Run the original-program oracle for lm-t6rupt and freeze digests.

Builds the host-only yaAGC driver tools/lm_t6rupt_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-t6rupt-native) is byte-identical, and writes
tests/lm_t6rupt_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit, InIsr and channels 5, 6 and 13) and
tests/lm_t6rupt_c64_vectors.h (every sixteenth). Also writes
build/lm-t6rupt-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_t6rupt.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_t6rupt_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
COHORTS = [(0, 'vector'), (256, 'dot6rupt'), (1792, 't6jobchk'), (2304, 'write'), (3072, 'resume')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_t6rupt_reference.c', *CORE,
                    '-o', 'build/lm-t6rupt-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-t6rupt-reference', str(ROPE), 'build/lm-t6rupt-executed.txt'], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-t6rupt-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-t6rupt: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_t6rupt_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable, InIsr and channels 5, 6, 13. */',
           f'#define LM_T6_VECTORS {len(digests)}u', *table('lm_t6_expected', digests)]
    (R / 'tests/lm_t6rupt_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_t6rupt_freeze.py: every',
           ' * sixteenth digest of tests/lm_t6rupt_vectors.h, for the C64 diagnostic. */',
           f'#define LM_T6_C64_STRIDE {STRIDE}u', f'#define LM_T6_C64_COUNT {len(c64)}u',
           *table('lm_t6_c64', c64)]
    (R / 'tests/lm_t6rupt_c64_vectors.h').write_text('\n'.join(out) + '\n')
    kinds = collections.Counter()
    for r in rows:
        cohort = next(name for start, name in reversed(COHORTS) if r[0] >= start)
        kinds[f"{cohort}:{('returned', 'alarm', 'refused')[r[1]]}"] += 1
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['04004 T6RUPT vector', '17,2065 DOT6RUPT', '17,2027 T6JOBCHK', '05753 WRITEP -1', '05754 WRITEP',
                         '05757 WRITEU -1', '05760 WRITEU', '05770 WRITEV -1', '05771 WRITEV', '05270 RESUME',
                         '05272 NOQRSM', '05274 NOQBRSM'],
             'boundary': 'one routine from its entry to the continuation it leaves in Z (DOT6RUPT from the '
                         'vector; RESUME or CCSHOLE from DOT6RUPT; the caller, or CCSHOLE, from T6JOBCHK; '
                         'the caller from the jet writers); the original runs to the first time it reaches '
                         'that Z (and FB in banked memory), or for RESUME, NOQRSM and NOQBRSM until the '
                         'interrupt ends',
             'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, InIsr, channels 5, 6, 13',
             'full_physical_words': 2048}
    (B / 'lm-t6rupt-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-t6rupt cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
