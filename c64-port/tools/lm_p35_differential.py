"""Run unchanged Luminary099 in the pinned yaAGC oracle from every lm-p35
case (tests/lm_p35_cases.c) to its first stop, check the native trampoline
run of the P35/P75 routines against every row, pin the stream identity, and
freeze per-case digests: tests/lm_p35_vectors.h (all cases, and the C64 sample). Archives the oracle stream as
build/lm-p35-reference.snapshots.bin.xz and writes build/lm-p35-proof.json
with the stops per routine. --record rewrites the pinned identity."""
import argparse,collections,hashlib,json,lzma,pathlib,struct,subprocess,sys
R=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(R/'tools'))
from lm_p35_core import CORE,CASES
ROW=4106;ROUTINES=13;STATES=ROUTINES*1024
PIN=R/'evidence/lm-p35/lm-p35-source-stream.json'
NAMES=['CALL SELECTMU after INTPRET (2737)','P35/P75B (2741)','after LOADTIME (2743)','after PRECSET (2752)','after S34/35.1 (2754)','after S34/35.2 (2756)','after S34/35.5 (2760)','after VN1645 (2762)',
 'P35 (2725)','after AVFLAGA (2726)','P75 (2731)','after AVFLAGP (2732)','after P20FLGON (2736)']
def digest(vals):
 a=b=0
 for v in vals:a=(a+v)&0xffff;b=(b+a)&0xffff
 return b<<16|a
def table(name,values):
 out=[f'static const uint32_t {name}[{len(values)}]={{']
 for i in range(0,len(values),6):out.append(''.join(f'0x{v:08x}ul,'for v in values[i:i+6]))
 return out+['};']
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--record',action='store_true');a=p.parse_args()
(R/'build').mkdir(exist_ok=True)
if not (R/'build/agc_engine_hardware_dv.o').exists():subprocess.run([sys.executable,'tools/prepare_hardware_dv.py'],cwd=R,check=True)
subprocess.run(['gcc','-std=c99','-O2','-DLM_P35_NO_TRAMPOLINE','-Iinclude','-Itests','-Ideps/virtualagc/yaAGC','-Itools','tools/lm_p35_reference.c',*CASES,'tests/cm_executive_cases.c','src/agc_word.c','build/agc_engine_hardware_dv.o','deps/virtualagc/yaAGC/agc_engine_init.o','deps/virtualagc/yaAGC/rfopen.o','-lm','-o','build/lm-p35-reference'],cwd=R,check=True)
subprocess.run(['cc','-std=c99','-O2','-Wall','-Wextra','-Werror','-Wconversion','-pedantic','-Iinclude','-Itests','tools/lm_p35_snapshot.c',*CORE,'-lm','-o','build/lm-p35-native'],cwd=R,check=True)
ref=subprocess.Popen(['build/lm-p35-reference','deps/lm-rtb-fixture/MAIN.agc.bin',str(STATES)],cwd=R,stdout=subprocess.PIPE)
nat=subprocess.Popen(['build/lm-p35-native',str(STATES)],cwd=R,stdout=subprocess.PIPE)
out_path=R/'build/lm-p35-reference.snapshots.bin.xz';tmp=out_path.with_suffix('.xz.part');archive=lzma.open(tmp,'wb',preset=6)
h=hashlib.sha256();size=0;tags=collections.Counter();digests=[];stops=collections.defaultdict(collections.Counter)
for n in range(STATES):
 x=ref.stdout.read(ROW);y=nat.stdout.read(ROW)
 if len(x)!=ROW or x!=y:
  ref.kill();nat.kill()
  if len(x)==ROW==len(y):
   X=struct.unpack('<2053H',x);Y=struct.unpack('<2053H',y)
   print('FAIL case',n,[(f'{i-5:04o}',f'{v:06o}',f'{Y[i]:06o}')for i,v in enumerate(X)if v!=Y[i]][:25])
  else:print('FAIL case',n,'short row')
  raise SystemExit(1)
 X=struct.unpack('<2053H',x);h.update(x);archive.write(x);size+=len(x);tags[X[4]]+=1
 digests.append(digest([X[4],*X[5:],X[2]]))
 w=X[5:];z=w[5];fb=w[4]&0o76000
 if z==0o6070:name=f'NEWOPS {fb>>10:02o},{w[0o164]:04o}'
 else:name={0o2347:'AVFLAGA',0o2354:'AVFLAGP',0o2361:'P20FLGON',0o6037:'INTPRET',0o3573:'LOADTIME'}.get(z,f'Z {z:04o}')
 stops[NAMES[n%ROUTINES]][name]+=1
if ref.stdout.read(1)or nat.stdout.read(1)or ref.wait()or nat.wait():raise SystemExit('FAIL producer exit or trailing bytes')
archive.close();tmp.replace(out_path)
identity=dict(archive='build/lm-p35-reference.snapshots.bin.xz',decoded_sha256=h.hexdigest(),decoded_bytes=size,cases=STATES,tag_counts={str(k):v for k,v in sorted(tags.items())},oracle='pinned yaAGC hardware-DV variant, deps/lm-rtb-fixture/MAIN.agc.bin (unchanged Luminary099)')
if a.record:PIN.parent.mkdir(parents=True,exist_ok=True);PIN.write_text(json.dumps(identity,indent=2)+'\n')
pin=json.loads(PIN.read_text())
if (pin['decoded_sha256'],pin['decoded_bytes'])!=(identity['decoded_sha256'],size):raise SystemExit('FAIL oracle stream differs from the pinned identity')
head=['/* SPDX-License-Identifier: MIT; generated by tools/lm_p35_differential.py: digests of the',' * original Luminary099 run of every lm-p35 case (see tests/lm_p35_cases.h). */']
# C64 sample: 520 cases spread over the 1024 variants, cycling through all
# thirteen entries (case k: variant k*1024/520, entry k%13); every routine
# fits one PRG.
GROUPS={1:tuple(range(ROUTINES))};COUNT={1:520}
c64={g:[k*1024//COUNT[g]*ROUTINES+r[k%len(r)]for k in range(COUNT[g])]for g,r in GROUPS.items()}
lines=[*head,f'#define LM_P35_VECTORS {len(digests)}u','#ifndef LM_P35_C64_GROUP',*table('lm_p35_expected',digests)]
for g,r in GROUPS.items():lines+=[f'#elif LM_P35_C64_GROUP=={g}',f'#define LM_P35_C64_CASES {len(c64[g])}u','static const uint8_t lm_p35_c64_routine[%d]={%s};'%(len(r),','.join(map(str,r))),*table('lm_p35_expected',[digests[n]for n in c64[g]])]
(R/'tests/lm_p35_vectors.h').write_text('\n'.join([*lines,'#endif'])+'\n')
proof=dict(cases=STATES,c64_groups={str(g):len(v)for g,v in c64.items()},stream_sha256=h.hexdigest(),stops={k:dict(sorted(v.items()))for k,v in stops.items()},boundary='each case runs from its entry (NEWOPS or Z) through the trampoline (this file\'s routines) to the first point outside them; the oracle stops at the same point (tests/lm_p35_cases.c lm_p35_stop: a NEWOPS outside 35,2737-2763, AVFLAGA, AVFLAGP, P20FLGON, INTPRET, LOADTIME)',compared='2048 erasable words (A, L 16-bit), the interrupt-enable state and SUPERBNK')
(R/'build/lm-p35-proof.json').write_text(json.dumps(proof,indent=1)+'\n')
print(f'PASS {STATES} original P35/P75 entries equal native trampoline runs',h.hexdigest(),flush=True)
