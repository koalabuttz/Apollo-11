"""Run the original-program oracle for cm-fresh-start and freeze digests.

Builds the host-only yaAGC driver (tools/cm_fresh_start_reference.c), runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-fresh-start-native) is byte-identical, and writes
tests/cm_fresh_start_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and every 16th digest (16 is prime to the 17 entries, so all are reached) to
tests/cm_fresh_start_c64_vectors.h. Also writes build/cm-fresh-start-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
CORE = ['tests/cm_fresh_start_cases.c', 'src/cm_fresh_start.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
        'src/cm_interbank_routines.c', 'src/cm_interbank_complete.c', 'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/cm_fresh_start_reference.c', *CORE, '-o', 'build/cm-fresh-start-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/cm-fresh-start-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-fresh-start-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_fresh_start_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, SUPERBNK, channels 11, 5, 6, 12, 13, 14 and 33, the trap latches and all 2048',
           ' * erasable words. */',
           f'#define CM_FS_VECTORS {len(values)}u']
    table(out, 'cm_fresh_start_expected', values)
    (R / 'tests/cm_fresh_start_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_fresh_start_freeze.py: every',
           ' * 16th digest of tests/cm_fresh_start_vectors.h, for the C64 diagnostic. */',
           '#define CM_FS_C64_STRIDE 16u', f'#define CM_FS_C64_COUNT {len(values[::16])}u']
    table(c64, 'cm_fresh_start_c64', values[::16])
    (R / 'tests/cm_fresh_start_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': 'SLAP1, MR.KLEAN, P00KLEAN, V37KLEAN, GOPROG, ENEMA, GOPROG3, T5IDLOC, GOTOPOOH and the return points after BANKCALL VAC5STOR, IBNKCALL SETCOARS, WAITLIST, MMDSPLAY, STOPRATE, SWCALL, ALARM and PHASCHNG (17)',
             'boundary': 'entry to the first point outside bank 05 2342-3217, GOTOPOOH 4106-4111 and INTER-BANK_COMMUNICATION, or SWRETURN',
             'full_physical_words': 2048}
    (B / 'cm-fresh-start-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program')


if __name__ == '__main__':
    main()
