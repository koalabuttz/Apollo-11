"""Run the original-program oracle for lm-dapidler and freeze digests.

Builds the host-only yaAGC driver tools/lm_dapidler_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-dapidler-native) is byte-identical, and writes
tests/lm_dapidler_vectors.h (one digest per case: two 16-bit running sums
over the outcome, channels 5, 6, 12, 14 and all 2048 erasable words) and
tests/lm_dapidler_c64_vectors.h (the C64
rows, chosen by outcome by tools/lane_f_c64_rows.py). Also writes
build/lm-dapidler-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_dapidler.c', 'src/agc_fast_ops.c', 'src/agc_fast_window.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
          'src/lm_interbank_routines.c', 'src/lm_interbank_idle.c', 'src/lm_interbank.c', 'src/lm_exec_routines.c', 'src/lm_admission_image.c',
          'src/lm_waitlist_image.c', 'src/waitlist.c', 'src/executive.c', 'src/p66_native.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_dapidler_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(B / 'agc_engine_hardware_dv.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    if not (B / 'agc_engine_hardware_dv.o').exists():
        subprocess.run([sys.executable, 'tools/prepare_hardware_dv.py'], cwd=R, check=True)
    subprocess.run(['cc', *FLAGS, 'tools/lm_dapidler_reference.c', *CORE,
                    '-o', 'build/lm-dapidler-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-dapidler-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-dapidler-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-dapidler: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_dapidler_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channels 5, 6, 12, 14 and all 2048 erasable words. */',
           f'#define LM_DI_VECTORS {len(digests)}u', *table('lm_di_expected', digests)]
    (R / 'tests/lm_dapidler_vectors.h').write_text('\n'.join(out) + '\n')
    subprocess.run([sys.executable, 'tools/lane_f_c64_rows.py', 'lm-dapidler'], cwd=R, check=True)
    names = ['CHEKBITS', 'CHEKMORE', 'DAPIDLER', 'CHECKUP', '16,2042', '16,2050', '16,2161', 'SHUTDOWN', 'ALTDSPLY']
    outcome = ['returned', 'alarm', 'resume', 'qerrcalc', 'calcperr', 'zatteror']
    kinds = collections.Counter(f"{names[r[0] % 9]}:{outcome[r[1]]}" for r in rows)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['16,2000 CHEKBITS', '16,2016 CHEKMORE', '16,2024 DAPIDLER', '16,2041 CHECKUP', '16,2042',
                         '16,2050', '16,2161', '16,2163 SHUTDOWN', '20,2226 ALTDSPLY'],
             'boundary': "each entry from a random image (FB bank 16 or 20, EB 6, random channels 5, 6, 12, 30, 31, "
                         "channel 14 bits 1-5, canonical Executive) to TCF RESUME, IBNKCALL QERRCALC, CALCPERR or ZATTEROR, the "
                         "1202 alarm or CHEKBITS's return; compared: outcome, channels 5, 6, 12, 14 and all 2048 "
                         "erasable words (CDU command counters as left at CAF 13,14,15)",
             'full_physical_words': 2048}
    (B / 'lm-dapidler-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-dapidler cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
