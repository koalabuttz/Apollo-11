"""Run unchanged Luminary099 in the pinned yaAGC oracle from every lm-p21
case (tests/lm_p21_cases.c) to its first stop, check the native trampoline
run of the P21 routines against every row, pin the stream identity, and
freeze per-case digests: tests/lm_p21_vectors.h (all cases, and the C64 sample). Archives the oracle stream as
build/lm-p21-reference.snapshots.bin.xz and writes build/lm-p21-proof.json
with the stops per routine. --record rewrites the pinned identity."""
import argparse,collections,hashlib,json,lzma,pathlib,struct,subprocess,sys
R=pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0,str(R/'tools'))
from lm_p21_core import CORE,CASES
ROW=4106;ROUTINES=24;STATES=ROUTINES*512
PIN=R/'evidence/lm-p21/lm-p21-source-stream.json'
NAMES=['after INTPRET (3524)', 'after INTSTALL (3530)', '+2 (3541)', 'after INTEGRV (3546)', 'P21CONT (3550)', 'P21VSAVE (3571)', 'after ARCSIN (3610)', 'P21DSP (3625)', 'after LAT-LONG (3642)', 'after INTPRET (3654)', 'PROG21 (3505)', 'GOPERF4 (3507)', 'terminate (3512)', 'proceed (3513)', 'enter (3514)', 'P21PROG1 (3515)', 'terminate (3520)', 'proceed (3521)', 'recycle (3522)', 'INTPRET (3523)', 'V06N43 (3646)', 'terminate (3651)', 'proceed (3652)', 'recycle (3653)']
def digest(vals):
 a=b=0
 for v in vals:a=(a+v)&0xffff;b=(b+a)&0xffff
 return b<<16|a
def table(name,values):
 out=[f'static const uint32_t {name}[{len(values)}]={{']
 for i in range(0,len(values),6):out.append(''.join(f'0x{v:08x}ul,'for v in values[i:i+6]))
 return out+['};']
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--record',action='store_true');a=p.parse_args()
(R/'build').mkdir(exist_ok=True)
if not (R/'build/agc_engine_hardware_dv.o').exists():subprocess.run([sys.executable,'tools/prepare_hardware_dv.py'],cwd=R,check=True)
subprocess.run(['gcc','-std=c99','-O2','-DLM_P21_NO_TRAMPOLINE','-Iinclude','-Itests','-Ideps/virtualagc/yaAGC','-Itools','tools/lm_p21_reference.c',*CASES,'tests/cm_executive_cases.c','src/agc_word.c','build/agc_engine_hardware_dv.o','deps/virtualagc/yaAGC/agc_engine_init.o','deps/virtualagc/yaAGC/rfopen.o','-lm','-o','build/lm-p21-reference'],cwd=R,check=True)
subprocess.run(['cc','-std=c99','-O2','-Wall','-Wextra','-Werror','-Wconversion','-pedantic','-Iinclude','-Itests','tools/lm_p21_snapshot.c',*CORE,'-lm','-o','build/lm-p21-native'],cwd=R,check=True)
ref=subprocess.Popen(['build/lm-p21-reference','deps/lm-rtb-fixture/MAIN.agc.bin',str(STATES)],cwd=R,stdout=subprocess.PIPE)
nat=subprocess.Popen(['build/lm-p21-native',str(STATES)],cwd=R,stdout=subprocess.PIPE)
out_path=R/'build/lm-p21-reference.snapshots.bin.xz';tmp=out_path.with_suffix('.xz.part');archive=lzma.open(tmp,'wb',preset=6)
h=hashlib.sha256();size=0;tags=collections.Counter();digests=[];stops=collections.defaultdict(collections.Counter)
for n in range(STATES):
 x=ref.stdout.read(ROW);y=nat.stdout.read(ROW)
 if len(x)!=ROW or x!=y:
  ref.kill();nat.kill()
  if len(x)==ROW==len(y):
   X=struct.unpack('<2053H',x);Y=struct.unpack('<2053H',y)
   print('FAIL case',n,[(f'{i-5:04o}',f'{v:06o}',f'{Y[i]:06o}')for i,v in enumerate(X)if v!=Y[i]][:25])
  else:print('FAIL case',n,'short row')
  raise SystemExit(1)
 X=struct.unpack('<2053H',x);h.update(x);archive.write(x);size+=len(x);tags[X[4]]+=1
 digests.append(digest([X[4],*X[5:],X[2]]))
 w=X[5:];z=w[5];fb=w[4]&0o76000
 if z==0o6070:name=f'NEWOPS {fb>>10:02o},{w[0o164]:04o}'
 else:name={0o3610:'ARCSIN',0o4616:'BANKCALL',0o6001:'GOTOPOOH',0o6037:'INTPRET',0o5726:'POODOO1 (1302)'}.get(z,f'Z {z:04o}')
 stops[NAMES[n%ROUTINES]][name]+=1
if ref.stdout.read(1)or nat.stdout.read(1)or ref.wait()or nat.wait():raise SystemExit('FAIL producer exit or trailing bytes')
archive.close();tmp.replace(out_path)
identity=dict(archive='build/lm-p21-reference.snapshots.bin.xz',decoded_sha256=h.hexdigest(),decoded_bytes=size,cases=STATES,tag_counts={str(k):v for k,v in sorted(tags.items())},oracle='pinned yaAGC hardware-DV variant, deps/lm-rtb-fixture/MAIN.agc.bin (unchanged Luminary099)')
if a.record:PIN.parent.mkdir(parents=True,exist_ok=True);PIN.write_text(json.dumps(identity,indent=2)+'\n')
pin=json.loads(PIN.read_text())
if (pin['decoded_sha256'],pin['decoded_bytes'])!=(identity['decoded_sha256'],size):raise SystemExit('FAIL oracle stream differs from the pinned identity')
head=['/* SPDX-License-Identifier: MIT; generated by tools/lm_p21_differential.py: digests of the',' * original Luminary099 run of every lm-p21 case (see tests/lm_p21_cases.h). */']
# C64 samples: each group's cases spread over the 512 variants, cycling
# through the group's entries (case k: variant k*512/count, entry k%len).
# One group holds every entry.
GROUPS={1:tuple(range(6)),2:tuple(range(6,ROUTINES))};COUNT={1:516,2:518}
c64={g:[k*512//COUNT[g]*ROUTINES+r[k%len(r)]for k in range(COUNT[g])]for g,r in GROUPS.items()}
lines=[*head,f'#define LM_P21_VECTORS {len(digests)}u','#ifndef LM_P21_C64_GROUP',*table('lm_p21_expected',digests)]
for g,r in GROUPS.items():lines+=[f'#elif LM_P21_C64_GROUP=={g}',f'#define LM_P21_C64_CASES {len(c64[g])}u','static const uint8_t lm_p21_c64_routine[%d]={%s};'%(len(r),','.join(map(str,r))),*table('lm_p21_expected',[digests[n]for n in c64[g]])]
(R/'tests/lm_p21_vectors.h').write_text('\n'.join([*lines,'#endif'])+'\n')
proof=dict(cases=STATES,c64_groups={str(g):len(v)for g,v in c64.items()},stream_sha256=h.hexdigest(),stops={k:dict(sorted(v.items()))for k,v in stops.items()},boundary='each case runs from its entry (NEWOPS or Z) through the trampoline (this file\'s routines) to the first point outside them; the oracle stops at the same point (tests/lm_p21_cases.c lm_p21_stop: a NEWOPS outside 24,3524-3645 and 3654-3661, ARCSIN, BANKCALL, GOTOPOOH, INTPRET, POODOO1)',compared='2048 erasable words (A, L 16-bit), the interrupt-enable state and SUPERBNK')
(R/'build/lm-p21-proof.json').write_text(json.dumps(proof,indent=1)+'\n')
print(f'PASS {STATES} original P21 entries equal native trampoline runs',h.hexdigest(),flush=True)
