"""Run the original-program oracle for lm-q-r-axis and freeze digests.

Builds the host-only yaAGC driver tools/lm_q_r_axis_reference.c, runs it on the
unmodified Luminary099 rope, checks the native snapshot (build/lm-q-r-axis-native)
is byte-identical on every case the native routines accept, and writes
tests/lm_q_r_axis_vectors.h (one digest per case: two 16-bit running sums over
the outcome, channel 13, the interrupt-enable and interrupt-in-progress bits
and all 2048 erasable words) and tests/lm_q_r_axis_c64_vectors.h (the C64
rows, chosen by outcome by tools/lane_f_c64_rows.py). Cases the native routines refuse are left out of the
comparison; their digest is of the unchanged input image, which the host test
checks. Writes build/lm-q-r-axis-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_q_r_axis.c', 'src/agc_fast_ops.c', 'src/agc_fast_window.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_q_r_axis_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Itools', '-I' + str(E)]
REFUSED = 1
NAMES = ['CALLQERR', '17,2172', '17,2214', '17,2454', '17,2620', 'QERRCALC', '17,2714', '17,2724', '17,2775',
         '17,3004', '17,3042', '17,3074', '17,3103', 'JTLST', 'ROT-TOUV', '17,3224', 'CLOSEOUT'] + ['CALLQERR'] * 15

# Destinations of the file's exits: (FB bank, Z) in switched fixed memory.
EXITS = {(0o21, 0o3077): 'GTS', (0o17, 0o3252): 'TJETLAW', (0o17, 0o2002): 'TC 02002 (OCT 02002 run as TC)', 0o4674: 'IBNKCALL', 0o5272: 'NOQRSM', 0o5567: 'ALARM',
         0o5757: 'WRITEU -1 (= WRITEP -1 +4)', 0o5760: 'WRITEP +4',
         0o5770: 'WRITEV -1 (= WRITEP -1 +13)', 0o5771: 'WRITEP +13'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_q_r_axis_reference.c', *CORE,
                    '-o', 'build/lm-q-r-axis-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-q-r-axis-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-q-r-axis-native'], cwd=R, check=True, capture_output=True).stdout
    rrows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    nrows = [list(map(int, line.split())) for line in nat.decode().splitlines()]
    assert [r[0] for r in rrows] == [r[0] for r in nrows] == list(range(len(nrows)))
    compared = [n for n in nrows if n[1] != REFUSED]
    for n in compared:
        assert n == rrows[n[0]], f'lm-q-r-axis case {n[0]}: native differs from the original program'
    refused = [n[0] for n in nrows if n[1] == REFUSED]
    digests = [digest(r[1:]) for r in nrows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_q_r_axis_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channel 13, the interrupt-enable and interrupt-in-progress bits and all',
           ' * 2048 erasable words',
           ' * (a refused case: its unchanged input image). */',
           f'#define LM_QR_VECTORS {len(digests)}u', *table('lm_qr_expected', digests)]
    (R / 'tests/lm_q_r_axis_vectors.h').write_text('\n'.join(out) + '\n')
    subprocess.run([sys.executable, 'tools/lane_f_c64_rows.py', 'lm-q-r-axis'], cwd=R, check=True)
    outcome = ['left the file', 'refused', 'none']
    kinds = collections.Counter(f"{NAMES[r[0] % 32]}:{outcome[r[1]]}" for r in nrows)
    oracle_refused = collections.Counter(outcome[rrows[n][1]] for n in refused)
    # Where each compared case left the file (rows are case, kind, channel
    # 13, interrupt enable, interrupt in progress, then the image: FB is word 4, Z 5).
    exits = collections.Counter(EXITS.get((r[5 + 4] >> 10, r[5 + 5]) if r[5 + 5] < 0o4000 else r[5 + 5],
                                          "the subroutine's return in Q") for r in compared)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(nrows), 'compared_cases': len(compared),
             'compared_sha256': hashlib.sha256('\n'.join(' '.join(map(str, n)) for n in compared).encode()).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'exits': dict(sorted(exits.items())),
             'refused_cases': len(refused), 'refused_oracle_outcomes': dict(sorted(oracle_refused.items())),
             'entries': ['17,2072 CALLQERR', '17,2172', '17,2214', '17,2454', '17,2620', '17,2626 QERRCALC', '17,2714',
                         '17,2724', '17,2775', '17,3004', '17,3042', '17,3074', '17,3103', '17,3114 JTLST',
                         '17,3146 ROT-TOUV', '17,3224', '17,3236 CLOSEOUT'],
             'boundary': 'each entry from a random image (FB bank 17, EB 6, random channels 4, 13 and 31, an eight-bit '
                         'channel 5, a random interrupt-enable bit, erasable words of random widths with +-0 frequent) '
                         'until the original leaves 17,2072-3251 and MAKERUPT (TC, TCF, DTCB or TC Q to a destination '
                         'outside; LOOPER\'s TC RETJADR to a word other than the file\'s three return addresses, '
                         'which the native routines refuse at the entry); '
                         'compared: outcome, channel 13, the interrupt-enable and interrupt-in-progress bits and all '
                         '2048 erasable words',
             'full_physical_words': 2048}
    (B / 'lm-q-r-axis-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(compared)} lm-q-r-axis cases equal the original program '
          f'({len(refused)} refused): {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
