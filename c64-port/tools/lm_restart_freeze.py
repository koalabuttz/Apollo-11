"""Run the original-program oracles for lm-restart-select and freeze digests.

Builds the host-only yaAGC drivers (tools/lm_restart_select_reference.c and
tools/lm_restart_routines_reference.c), runs them on the unmodified
Luminary099 rope, checks the native snapshots are byte-identical, and writes
tests/lm_restart_vectors.h: one digest per case (two 16-bit running sums over
the printed values), which the host test and the C64 diagnostic compare.
Also writes build/lm-restart-select-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
CORE = ['tests/lm_restart_select_cases.c', 'src/agc_word.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def run(name):
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-I' + str(E),
                    f'tools/{name}_reference.c', *CORE, '-o', f'build/{name.replace("_", "-")}-reference'],
                   cwd=R, check=True)
    ref = subprocess.run([f'./build/{name.replace("_", "-")}-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run([f'./build/{name.replace("_", "-")}-native'], cwd=R,
                         check=True, capture_output=True).stdout
    assert ref == nat, f'{name}: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    return ref, [digest(r[1:]) for r in rows]


def main():
    sel, sel_d = run('lm_restart_select')
    com, com_d = run('lm_restart_routines')
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_restart_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the status',
           ' * (or service calls) and all 2048 erasable words. */',
           f'#define LM_RS_SELECT_VECTORS {len(sel_d)}u',
           f'#define LM_RS_COMPOSE_VECTORS {len(com_d)}u']
    for name, values in (('lm_rs_select_expected', sel_d), ('lm_rs_compose_expected', com_d)):
        out.append(f'static const uint32_t {name}[{len(values)}]={{')
        for i in range(0, len(values), 6):
            out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
        out.append('};')
    (R / 'tests/lm_restart_vectors.h').write_text('\n'.join(out) + '\n')
    # The C64 diagnostic checks every sixteenth case of each kind.
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_restart_freeze.py: every',
           ' * sixteenth digest of tests/lm_restart_vectors.h, for the C64 diagnostic. */',
           '#define LM_RS_C64_STRIDE 16u']
    for name, values in (('lm_rs_select_c64', sel_d[::16]), ('lm_rs_compose_c64', com_d[::16])):
        c64.append(f'#define {name.upper()}_COUNT {len(values)}u')
        c64.append(f'static const uint32_t {name}[{len(values)}]={{')
        for i in range(0, len(values), 6):
            c64.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
        c64.append('};')
    (R / 'tests/lm_restart_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'select_cases': len(sel_d), 'compose_cases': len(com_d),
             'select_snapshot_sha256': hashlib.sha256(sel).hexdigest(),
             'compose_snapshot_sha256': hashlib.sha256(com).hexdigest(),
             'entries': ['01,3526 RESTARTS', '01,3541 GETPART2', '01,3763 PHSPART2'],
             'boundary': 'select: TC GOLOC-1 (Z 0704) or X.1 TC FINDVAC; compose: RESTARTS to SWRETURN '
                         'with each selected service recorded and returned to Q+2',
             'full_physical_words': 2048}
    (B / 'lm-restart-select-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(sel_d)} selection and {len(com_d)} composition cases equal the original program')


if __name__ == '__main__':
    main()
