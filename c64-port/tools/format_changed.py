#!/usr/bin/env python3
"""Format the C lines a change touches, with the pinned clang-format.

  python3 tools/format_changed.py              # fix: changes since HEAD (staged and not)
  python3 tools/format_changed.py --staged     # fix: staged changes only (pre-commit hook)
  python3 tools/format_changed.py --check --base origin/main
                                                # report: what a PR left unformatted

Only lines the change touches are reformatted (git-clang-format), so an edit
never reflows a whole file. That matters here: cover records key branches
by file:line, and a whole-file reflow would stale every certificate citing
the file. A repo-wide pass is a separate, coordinated step.

Scope: .c and .h under src/, include/ and platform/. Generated files (a
"Generated by" or "do not edit" note in their first lines) are left to the
tool that writes them; regenerate those instead.

The formatter is deps/llvm-mos/bin/clang-format (tools/setup_cloud.sh), so
every container and CI runner formats the same way; style is .clang-format.
Formatting changes no compiled byte.
"""
import argparse
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRS = ('src/', 'include/', 'platform/')
BINARY = ROOT / 'deps/llvm-mos/bin/clang-format'
DRIVER = ROOT / 'deps/llvm-mos/bin/git-clang-format'


def generated(path):
    try:
        with open(path, errors='replace') as f:
            head = ''.join(f.readline() for _ in range(5)).lower()
    except OSError:
        return True
    return 'generated by' in head or 'do not edit' in head


def changed(base, staged):
    """Port C files the change touches, relative to the repository root."""
    top = subprocess.run(['git', 'rev-parse', '--show-toplevel'], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout.strip()
    cmd = ['git', 'diff', '--name-only', '--diff-filter=ACMR']
    cmd += ['--cached'] if staged else []
    cmd += [base] if base else []
    names = subprocess.run(cmd, cwd=top, check=True, capture_output=True, text=True).stdout.split()
    out = []
    for name in names:
        rel = os.path.relpath(os.path.join(top, name), ROOT)
        if rel.startswith(DIRS) and rel.endswith(('.c', '.h')) and not generated(ROOT / rel):
            out.append(os.path.join(top, name))
    return top, out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--base', help='commit to diff against (default HEAD)')
    ap.add_argument('--staged', action='store_true', help='staged changes only')
    ap.add_argument('--check', action='store_true', help='print the diff and exit 1; change nothing')
    a = ap.parse_args()
    if not BINARY.exists() or not DRIVER.exists():
        print(f'format_changed: {BINARY} missing; run tools/setup_cloud.sh', file=sys.stderr)
        return 0 if not a.check else 2
    top, files = changed(a.base, a.staged)
    if not files:
        return 0
    cmd = [sys.executable, str(DRIVER), '--binary', str(BINARY), '--style', 'file', '--quiet']
    cmd += ['--diff'] if a.check else ['-f']
    cmd += ['--staged'] if a.staged else []
    cmd += [a.base or 'HEAD', '--'] + files
    r = subprocess.run(cmd, cwd=top, capture_output=True, text=True)
    if a.check:
        diff = r.stdout.strip()
        if not diff or diff.startswith('no modified files') or 'did not modify any files' in diff:
            return 0
        print(diff)
        print('format_changed: run `make format` (or install the hook: tools/setup_cloud.sh) '
              'to format these lines', file=sys.stderr)
        return 1
    if r.returncode not in (0, 1):
        sys.stderr.write(r.stdout + r.stderr)
        return r.returncode
    return 0


if __name__ == '__main__':
    sys.exit(main())
