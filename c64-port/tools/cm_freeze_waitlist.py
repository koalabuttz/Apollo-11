#!/usr/bin/env python3
"""Freeze all queue words only after native/original CM assembly agreement."""
import hashlib,pathlib
R=pathlib.Path(__file__).resolve().parents[1]; p=R/'build/cm-waitlist-reference.snapshots'
assert p.read_bytes()==(R/'build/cm-waitlist-native.snapshots').read_bytes()
rows=[list(map(int,r.split())) for r in p.read_text().splitlines()]
assert len(rows)==306 and all(len(r)==34 for r in rows)
s='/* SPDX-License-Identifier: MIT\n * GENERATED by tools/cm_freeze_waitlist.py from original CM assembly.\n * Snapshot SHA256: '+hashlib.sha256(p.read_bytes()).hexdigest()+'\n */\n#ifndef CM_WAITLIST_VECTORS_H\n#define CM_WAITLIST_VECTORS_H\n#include <stdint.h>\nstatic const uint16_t cm_waitlist_reference[306][32]={\n'
for r in rows: s+=' {'+','.join(str(w) for w in r[2:])+'}, /* case %u step %u */\n'%(r[0],r[1])
(R/'tests/cm_waitlist_vectors.h').write_text(s+'};\n#endif\n')
print('Frozen all 32 result/state/transfer words for each of 306 checkpoints')
