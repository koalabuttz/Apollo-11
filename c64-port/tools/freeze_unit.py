#!/usr/bin/env python3
"""Freeze complete bounded original ABS/ABVAL/UNIT states losslessly."""
import hashlib,pathlib
from collections import Counter
from frozen_words import encode_rows,c_header
root=pathlib.Path(__file__).resolve().parents[1];data=(root/'build/unit-reference.snapshots').read_bytes()
assert data==(root/'build/unit-native.snapshots').read_bytes()
rows=[list(map(int,l.split()))for l in data.decode().splitlines()]
assert len(rows)==50736 and all(len(r)==106 for r in rows)
ks=list(range(8))+list(range(512,516))+[8192+v-1 for v in [127,128,129,256,512,1024,2048]]+[16384+(1<<i)-1 for i in range(10)]+[1024,1025,3072,3073,12288]
indices=sorted({3*k+op for k in ks for op in range(3)}|{3*k+2 for k in range(16896,16912)});assert len(indices)==118
packed=encode_rows([rows[i][1:]for i in indices])
s='/* SPDX-License-Identifier: MIT\n * Generated by tools/freeze_unit.py from unchanged original assembly with\n * pinned hardware DV; snapshot SHA256: '+hashlib.sha256(data).hexdigest()+'\n */\n#ifndef UNIT_VECTORS_H\n#define UNIT_VECTORS_H\n'+c_header(packed,'unit')
s+='\n#ifdef UNIT_FROZEN_IMPLEMENTATION\nconst uint32_t unit_reference_cases[UNIT_FROZEN_ROWS]={\n'
for i in range(0,len(indices),16):s+='    '+','.join(str(v)+'u'for v in indices[i:i+16])+',\n'
s+='};\n#else\nextern const uint32_t unit_reference_cases[UNIT_FROZEN_ROWS];\n#endif\n#endif\n';(root/'tests/unit_vectors.h').write_text(s)
print('Frozen118 complete105-word ABS/ABVAL/UNIT states; packed',packed.storage_bytes,'bytes +472 case-index bytes')
print('Operation/path counts:',dict(sorted(Counter((i%3,rows[i][1])for i in indices).items())))
