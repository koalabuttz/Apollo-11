"""Freeze independently emitted source expectations and pure constructor inputs."""
import pathlib,subprocess,hashlib
root=pathlib.Path(__file__).resolve().parents[1]
rows=[list(map(int,s.split())) for s in (root/'build/p66-native-reference.snapshots').read_text().splitlines()]
mixed=[list(map(int,s.split())) for s in (root/'build/p66-native-mixed-reference.snapshots').read_text().splitlines()]
assert len(rows)==5775 and len(mixed)==112
numbers=list(range(26))+[64,80,96,112,128,1154]
def fingerprint(words):
 h=2166136261
 for w in words:
  for b in (w&255,w>>8):h=((h^b)*16777619)&0xffffffff
 return 'UINT32_C(%u)'%h
def emit(name,guard,count,expected,extra=''):
 out=f'/* SPDX-License-Identifier: GPL-2.0-or-later\n * Frozen unchanged-assembly states; FNV over complete explicit LE words. */\n#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n'+extra+f'static const uint32_t {name}[{len(expected)}][{count}]={{\n'
 out+=''.join('{'+','.join(fingerprint(w) for w in group)+'},\n' for group in expected)+'};\n#endif\n'
 return out
extra='#ifdef P66_NATIVE_C64_INPUT\n#define PN_TARGET_CASES 8u\n#else\n#define PN_TARGET_CASES 32u\n#endif\nstatic const uint16_t pn_target_numbers[32]={'+','.join(map(str,numbers))+'};\n'
(root/'tests/p66_native_vectors.h').write_text(emit('pn_fingerprints','P66_NATIVE_VECTORS_H',5,[[rows[n*5+s][2:] for s in range(5)] for n in numbers],extra))
(root/'tests/p66_native_mixed_vectors.h').write_text(emit('pn_mixed_fingerprints','P66_NATIVE_MIXED_VECTORS_H',7,[[mixed[n*7+s][2:] for s in range(7)] for n in range(8)]))
inputs=['tests/'+n+'_cases.c' for n in ('prepare','scale','push','elapsed','store','divide','gravity','velocity','p66_native')]
flags=['-D'+n+'_INPUT_ONLY' for n in ('VELOCITY','GRAVITY','DIVIDE','STORE','ELAPSED','PUSH','SCALE','PREPARE')]
subprocess.run(['gcc','-std=c99','-O2','-DP66_NATIVE_REFERENCE_INPUT']+flags+['-Iinclude','-Itests','tools/p66_native_input_snapshot.c']+inputs+['-o','build/p66-native-inputs'],cwd=root,check=True)
run=subprocess.run(['./build/p66-native-inputs'],cwd=root,capture_output=True,text=True,check=True)
(root/'build/p66-native-inputs.snapshots').write_text(run.stdout)
initial=[list(map(int,line.split())) for line in run.stdout.splitlines()];assert len(initial)==8 and all(len(r)==118 for r in initial)
header='/* SPDX-License-Identifier: MIT\n * Pure constructor inputs; generated by freeze_p66_native.py. */\n#ifndef P66_NATIVE_INPUTS_H\n#define P66_NATIVE_INPUTS_H\nstatic const uint16_t pn_frozen_inputs[8][117]={\n'+''.join('{'+','.join(map(str,r[1:]))+'},\n' for r in initial)+'};\n#endif\n'
(root/'tests/p66_native_inputs.h').write_text(header)
for f in ('p66-native-reference.snapshots','p66-native-mixed-reference.snapshots','p66-native-inputs.snapshots'):
 print(f,hashlib.sha256((root/'build'/f).read_bytes()).hexdigest())
