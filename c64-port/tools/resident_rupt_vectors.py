"""Freeze the yaAGC results of tests/resident_rupt_cases.c.

Builds tools/resident_rupt_reference.c against Virtual AGC
(deps/virtualagc/yaAGC), runs it on each mission's unmodified rope
(evidence/fixed-data-<m>-original.rope.bin) and writes
tests/resident_rupt_vectors.h: one digest per block of 64 cases. Also
writes tests/resident_rupt_c64_rows.h: the digests of every 32nd T3RUPT
case, which the C64 flight check (platform/c64/resident_flight_check.c,
part 4) runs. Host only; needs the yaAGC objects.
"""
import hashlib
from pathlib import Path
import subprocess

BLOCK = 64
STRIDE = 32


def mix(h, v):
    h = ((h ^ (v & 0xff)) * 16777619) & 0xffffffff
    return ((h ^ (v >> 8)) * 16777619) & 0xffffffff


def fold(digests):
    """tests/resident_rupt_cases.c rr_fold over each block of BLOCK digests."""
    out = []
    for i in range(0, len(digests), BLOCK):
        h = 2166136261
        for d in digests[i:i + BLOCK]:
            h = mix(mix(h, d & 0xffff), d >> 16)
        out.append(f'{h:08x}')
    return out

ROOT = Path(__file__).resolve().parents[1]
E = ROOT / 'deps/virtualagc/yaAGC'
EXE = ROOT / 'build/resident-rupt-reference'


def main():
    EXE.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', f'-I{E}', 'tools/resident_rupt_reference.c',
                    'tests/resident_rupt_cases.c', 'src/agc_word.c', 'src/agc_transfer.c', E / 'agc_engine.o',
                    E / 'agc_engine_init.o', E / 'rfopen.o', '-o', EXE], cwd=ROOT, check=True)
    out = ['/* SPDX-License-Identifier: MIT\n * GENERATED by tools/resident_rupt_vectors.py from yaAGC'
           ' (tools/resident_rupt_reference.c). */\n',
           '#ifndef RESIDENT_RUPT_VECTORS_H\n#define RESIDENT_RUPT_VECTORS_H\n#include <stdint.h>\n'
           '#include "resident_rupt_cases.h"\n',
           'typedef struct { uint32_t entry[RR_ENTRY_CASES / RR_BLOCK], t3[RR_T3_CASES / RR_BLOCK],'
           ' timer[RR_TIMER_CASES / RR_BLOCK]; } rr_vectors;\n']
    c64 = ['/* SPDX-License-Identifier: MIT\n * GENERATED by tools/resident_rupt_vectors.py from yaAGC'
           ' (tools/resident_rupt_reference.c). */\n',
           '#ifndef RESIDENT_RUPT_C64_ROWS_H\n#define RESIDENT_RUPT_C64_ROWS_H\n#include <stdint.h>\n',
           f'/* The T3RUPT cases n = {STRIDE} * row (tests/resident_rupt_cases.c). */\n',
           f'#define RR_C64_STRIDE {STRIDE}u\n#define RR_C64_ROWS (RR_T3_CASES / RR_C64_STRIDE)\n']
    for m in ('lm', 'cm'):
        rope = ROOT / f'evidence/fixed-data-{m}-original.rope.bin'
        text = subprocess.run([EXE, m, rope], cwd=ROOT, check=True, capture_output=True, text=True).stdout
        rows = {'E': [], 'R': [], 'T': []}
        for line in text.splitlines():
            kind, n, digest = line.split()
            assert int(n) == len(rows[kind])
            rows[kind].append(int(digest, 16))
        out.append(f'/* {m}: rope SHA256 {hashlib.sha256(rope.read_bytes()).hexdigest()} */\n')
        out.append(f'static const rr_vectors rr_{m}_vectors = {{\n {{')
        for kind in ('E', 'R', 'T'):
            if kind != 'E':
                out.append(' {')
            for i, d in enumerate(fold(rows[kind])):
                out.append(('\n  ' if i % 8 == 0 else ' ') + f'0x{d}u,')
            out.append('\n },\n' if kind != 'T' else '\n }\n};\n')
        rows_c64 = rows['R'][::STRIDE]
        c64.append(f'static const uint32_t rr_{m}_c64_rows[RR_C64_ROWS] = {{')
        for i, d in enumerate(rows_c64):
            c64.append(('\n ' if i % 8 == 0 else ' ') + f'0x{d:08x}u,')
        c64.append('\n};\n')
    out.append('#endif\n')
    (ROOT / 'tests/resident_rupt_vectors.h').write_text(''.join(out))
    c64.append('#endif\n')
    (ROOT / 'tests/resident_rupt_c64_rows.h').write_text(''.join(c64))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
