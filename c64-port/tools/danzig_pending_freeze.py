"""Pending-DANZIG transfer point (lane A): every RTB-left order pair of both
missions, from the unmodified listings, run in yaAGC from NEWOPS to the
first DANZIG with EDOP nonzero (tools/danzig_pending_reference.c). Freezes
the resulting LOC, BANKSET, EDOP and FB into tests/danzig_pending_vectors.h,
which tests/test_danzig_pending.c and the C64 diagnostic feed through
agc_transfer_point and agc_transfer_run. Writes build/danzig-pending-proof.json.
"""
import hashlib, json, pathlib, re, subprocess

R = pathlib.Path(__file__).resolve().parents[1]
E = R / 'deps/virtualagc/yaAGC'
MISSIONS = [('Luminary099', 0o6070, 0o6061), ('Comanche055', 0o6037, 0o6030)]
OPCODE_COLUMN = 65   # listing column of the opcode field (labels start at 46)
LINE = re.compile(r'^\d+,\d+: (\d\d),(\d{4}) +(\d{5}) ')


def sites(listing):
    out = []
    for n, line in enumerate(listing.read_text(errors='replace').splitlines(), 1):
        m = LINE.match(line)
        if not m or line[OPCODE_COLUMN:OPCODE_COLUMN + 4] != 'RTB ':
            continue
        right = line[OPCODE_COLUMN + 4:].split('#')[0].split()
        if not right:
            continue
        bank, off = int(m.group(1), 8), int(m.group(2), 8)
        out.append({'physical': bank * 1024 + off - 0o2000, 'address': f'{m.group(1)},{m.group(2)}',
                    'word': m.group(3), 'right': right[0], 'listing_line': n})
    return out


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Itools', f'-I{E}',
                    'tools/danzig_pending_reference.c', 'src/agc_word.c', 'src/cm_executive.c',
                    'tests/cm_executive_cases.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'),
                    str(E / 'rfopen.o'), '-o', 'build/danzig-pending-reference'], cwd=R, check=True)
    rows, proof = [], {'missions': {}}
    for m, (mission, newops, danzig) in enumerate(MISSIONS):
        fixed = R / 'build/fixed-data' / mission
        found = sites(fixed / 'assembly.lst')
        rope = fixed / 'MAIN.agc.bin'
        out = subprocess.run(['./build/danzig-pending-reference', str(rope), f'{newops:o}', f'{danzig:o}'],
                             cwd=R, check=True, capture_output=True, text=True,
                             input=''.join(f'{s["physical"]}\n' for s in found)).stdout.splitlines()
        assert len(out) == len(found)
        reached = []
        for s, line in zip(found, out):
            v = list(map(int, line.split()))
            assert v[0] == s['physical']
            s['reached'] = bool(v[1])
            if v[1]:
                loc, bankset, edop, fb = v[2:]
                bank = (bankset >> 10) & 0o37
                bank += 8 if bank >= 0o30 and bankset & 0o100 else 0
                key = bank * 1024 + loc - 0o2000
                assert key == s['physical'] + 1, (mission, s)
                s.update(loc=f'{loc:05o}', bankset=f'{bankset:05o}', edop=f'{edop:05o}', key=key)
                rows.append((m, s['physical'], loc, bankset, edop, fb))
                reached.append(s)
        proof['missions'][mission] = {
            'rope_sha256': hashlib.sha256(rope.read_bytes()).hexdigest(),
            'rtb_left_pairs': len(found), 'reached_pending_danzig': len(reached),
            'not_reached_from_zero_state': [s['address'] for s in found if not s['reached']],
            'sites': found}
    proof['boundary'] = ('from NEWOPS at each RTB-left pair word, with an otherwise zero image, to the first '
                         'DANZIG with EDOP nonzero; every reached point has LOC under BANKSET at the pair word +1 '
                         '(the RTB operand word)')
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/danzig_pending_freeze.py from the',
            ' * original Luminary099 and Comanche055 programs (yaAGC oracle): the state at the pending',
            ' * DANZIG after each RTB-left order pair (mission, pair word, LOC, BANKSET, EDOP, FB). */',
            f'#define DZP_ROWS {len(rows)}u',
            'typedef struct { uint8_t cm; uint16_t pair; uint16_t loc, bankset, edop, fb; } dzp_row;',
            f'static const dzp_row dzp_rows[{len(rows)}]={{']
    head += [f'{{{r[0]},{r[1]}u,0{r[2]:o},0{r[3]:o},0{r[4]:o},0{r[5]:o}}},' for r in rows] + ['};']
    (R / 'tests/danzig_pending_vectors.h').write_text('\n'.join(head) + '\n')
    (R / 'build/danzig-pending-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} RTB-left pairs reach DANZIG with EDOP pending and LOC at the RTB operand word')


if __name__ == '__main__':
    main()
