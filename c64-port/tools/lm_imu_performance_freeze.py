#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Run the original-program oracle for lm-imu-performance and freeze digests.

Builds the host-only yaAGC driver tools/lm_imu_performance_reference.c
against build/agc_engine_no_imu_device.o (tools/prepare_no_imu_device_engine.py),
runs it on the unmodified Luminary099 rope, and checks every case the native
snapshot (build/lm-imu-performance-native) runs is byte-identical to it; a
case the native routine refuses must leave its image unchanged. Writes
tests/lm_imu_performance_vectors.h (one digest per case: two 16-bit running
sums over the kind and, unless refused, all 2048 erasable words and the
interrupt-enable state) and build/lm-imu-performance-proof.json.

C64 parts (IPT_C64_PART in tests/lm_imu_performance_cases.h): each part is
built for the host too and run on every case; a row it runs (kind other
than 3) must equal the oracle run with the same chained-step stops (the
keys the part leaves out), and the part-0 replay of the part. The C64 rows
(tests/lm_imu_performance_c64_vectors.h) are the rows covering every edge
the host stream takes and every key (tools/lm_imu_performance_cover.c) and
every STRIDE-th case in the first part that runs it, and the EXTRA_ROWS
of tools/lm_imu_performance_cover.py;
tools/lm_imu_performance_cover.py checks their gcov against the host's.
"""
import collections
import hashlib
import json
import pathlib
import re
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
import sys
sys.path.insert(0, str(R / 'tools'))
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_imu_performance.c', 'src/sband_trig.c', 'src/guidance_trig.c', 'src/guidance_product.c',
          'src/lm_interp_orders.c', 'src/lm_interp_steps.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
          'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c', 'tests/lm_imu_performance_cases.c']
CORE = NATIVE + ['tests/cm_executive_cases.c', str(B / 'agc_engine_no_imu_device.o'),
                 str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E)]
STRIDE = 149
REFUSED = 2
PARTS = 8
STOPS = {0o2335: 'CHECKG1 idle', 0o4103: 'FINETIME +1 idle', 0o5567: 'ALARM', 0o5744: 'VARALARM', 0o5516: 'DOWNFLAG', 0o5504: 'UPFLAG', 0o5126: 'CHANG2',
         0o5122: 'CHANG1', 0o4616: 'BANKCALL', 0o5261: 'TASKOVER', 0o5173: 'TWIDDLE', 0o5105: 'FINDVAC',
         0o5133: 'JOBSLEEP', 0o5137: 'JOBWAKE', 0o4000: 'caller return', 0o6070: 'NEWOPS outside the file'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def keys():
    src = (R / 'src/lm_imu_performance.c').read_text()
    body = re.search(r'ipt_routine_keys\[IPT_ROUTINES\]=\{(.*?)\};', src, re.S).group(1)
    return [('FF ' if k == 'FFK' else '37,') + a[1:] for k, a in re.findall(r'(FFK|B37)\((0[0-7]+)\)', body)]


def capture(cmd, name):
    """Runs cmd with its rows to build/<name> (the rows are too many to hold)."""
    path = B / name
    with open(path, 'w') as f:
        subprocess.run(cmd, cwd=R, check=True, stdout=f)
    return path


def row_digest(line):
    r = list(map(int, line.split()))
    return digest(r[1:2] if r[1] == REFUSED else r[1:])


def main():
    subprocess.run(['cc', *FLAGS, '-w', 'tools/lm_imu_performance_reference.c', *CORE,
                    '-o', 'build/lm-imu-performance-reference'], cwd=R, check=True)
    ref = capture(['./build/lm-imu-performance-reference', str(ROPE)], 'ipt-oracle.txt')
    nat = capture(['./build/lm-imu-performance-native'], 'ipt-native.txt')
    names = keys()
    digests, kinds, refused = [], [], collections.Counter()
    stops = collections.defaultdict(collections.Counter)
    sha = hashlib.sha256()
    with open(nat) as fn, open(ref) as fr:
        for i, (a, b) in enumerate(zip(fn, fr)):
            a, b = a.rstrip('\n'), b.rstrip('\n')
            sha.update((('\n' if i else '') + a).encode())
            r = a.split(maxsplit=8)
            assert int(r[0]) == i
            key = names[i % len(names)]
            kinds.append(int(r[1]))
            if int(r[1]) == REFUSED:
                refused[key] += 1
            else:
                assert a == b, f'lm-imu-performance case {i} ({key}): native differs from the original program'
                z = int(r[7])
                stops[key][STOPS.get(z, f'Z {z:05o}')] += 1
            digests.append(row_digest(a))
    assert len(digests) % len(names) == 0
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_imu_performance_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the kind and, unless',
           ' * refused, all 2048 erasable words and the interrupt-enable state. */',
           f'#define IPT_VECTORS {len(digests)}u', *table('ipt_expected', digests)]
    (R / 'tests/lm_imu_performance_vectors.h').write_text('\n'.join(out) + '\n')
    # C64 parts: each part's host build against the oracle stopped at the
    # keys the part leaves out, and against the part-0 replay of the part.
    part_kinds, part_digests, part_summary = {}, {}, {}
    subprocess.run(['cc', *FLAGS, '-Wall', '-Wextra', '-Werror', '-DIPT_C64_PART=0', *NATIVE,
                    'platform/host/lm_imu_performance_snapshot.c', '-o', 'build/lm-imu-performance-part0'], cwd=R, check=True)
    for part in range(1, PARTS + 1):
        exe = f'build/lm-imu-performance-part{part}'
        subprocess.run(['cc', *FLAGS, '-Wall', '-Wextra', '-Werror', f'-DIPT_C64_PART={part}', *NATIVE,
                        'platform/host/lm_imu_performance_snapshot.c', '-o', exe], cwd=R, check=True)
        rows_p = capture(['./' + exe], f'ipt-part{part}.txt')
        replay = capture(['./build/lm-imu-performance-part0', str(part)], f'ipt-part{part}-replay.txt')
        oracle = capture(['./build/lm-imu-performance-reference', str(ROPE), str(part)], f'ipt-part{part}-oracle.txt')
        count, ks, ds = collections.Counter(), [], []
        with open(rows_p) as fa, open(replay) as fb, open(oracle) as fc:
            for i, (line, again, orig) in enumerate(zip(fa, fb, fc)):
                assert line == again, f'lm-imu-performance part {part}: case {i}: the part-0 replay differs from the part build'
                k = int(line.split(maxsplit=2)[1])
                count[k] += 1
                ks.append(k)
                ds.append(row_digest(line) if k != 3 else 0)
                if k == REFUSED:
                    assert kinds[i] == REFUSED, f'lm-imu-performance part {part}: case {i} refused, native runs it'
                elif k != 3:
                    assert line == orig, f'lm-imu-performance part {part}: case {i} differs from the original program'
        for path in (rows_p, replay, oracle):
            path.unlink()
        part_kinds[part], part_digests[part] = ks, ds
        part_summary[part] = {'runs': count[0], 'refused': count[REFUSED], 'left out (kind 3)': count[3]}
    # Rows the C64 runs: tools/lm_imu_performance_cover.c's cover of every
    # edge the host stream takes and every key, and every STRIDE-th case in
    # the first part that runs it.
    subprocess.run(['gcc', '-std=c99', '-O0', '-Iinclude', '-Itests', '-DP66_NATIVE_DISPATCH_ONLY',
                    '-DIPT_C64_PART=0', '-fsanitize-coverage=trace-pc', '-c', 'src/lm_imu_performance.c',
                    '-o', 'build/lm-imu-performance-select.o'], cwd=R, check=True)
    subprocess.run(['gcc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-DP66_NATIVE_DISPATCH_ONLY', '-DIPT_C64_PART=0',
                    'build/lm-imu-performance-select.o', *[n for n in NATIVE if n != 'src/lm_imu_performance.c'],
                    'tools/lm_imu_performance_cover.c', '-o', 'build/lm-imu-performance-select'], cwd=R, check=True)
    sel = subprocess.run(['./build/lm-imu-performance-select', 'select'], cwd=R, check=True, capture_output=True)
    assert sel.stderr.decode().splitlines()[-1].endswith(' 0 items left'), sel.stderr.decode()[-2000:]
    chosen = {tuple(map(int, l.split())) for l in sel.stdout.decode().splitlines()}
    covering = len(chosen)
    for i in range(0, len(digests), STRIDE):
        part = next((p for p in range(1, PARTS + 1) if part_kinds[p][i] != 3), None)
        if part:
            chosen.add((part, i))
    from lm_imu_performance_cover import EXTRA_ROWS
    chosen |= set(EXTRA_ROWS)
    chosen = sorted(chosen)
    assert all(part_kinds[p][i] != 3 for p, i in chosen)
    (B / 'lm-imu-performance-c64-rows.txt').write_text(''.join(f'{p} {i}\n' for p, i in chosen))
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_imu_performance_freeze.py for the',
           ' * C64 diagnostics: per part, the rows covering every edge and key of the host stream',
           f' * and every {STRIDE}th case; digests of the part\'s run (a chained step ends at a key',
           ' * the part leaves out). */']
    for part in range(1, PARTS + 1):
        mine = [i for p, i in chosen if p == part]
        out += [f'#{"if" if part == 1 else "elif"} IPT_C64_PART=={part}', f'#define IPT_C64_COUNT {len(mine)}u',
                f'static const uint16_t ipt_c64_case[{len(mine)}]={{']
        out += [''.join(f'{i}u,' for i in mine[j:j + 12]) for j in range(0, len(mine), 12)]
        out += ['};', *table('ipt_c64', [part_digests[part][i] for i in mine])]
    out.append('#endif')
    (R / 'tests/lm_imu_performance_c64_vectors.h').write_text('\n'.join(out) + '\n')
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle_engine': 'pinned yaAGC agc_engine.c without its gyro, IMU CDU drive and optics block '
                              '(build/no-imu-device.patch); scalers frozen',
             'cases': len(digests), 'compared': len(digests) - sum(refused.values()),
             'refused': dict(sorted(refused.items())),
             'c64_parts': {str(p): sum(1 for q, _ in chosen if q == p) for p in range(1, PARTS + 1)},
             'c64_covering_rows': covering,
             'c64_part_rows': {str(p): v for p, v in part_summary.items()},
             'snapshot_sha256': sha.hexdigest(),
             'stops': {k: dict(sorted(v.items())) for k, v in sorted(stops.items())},
             'boundary': 'from each routine key to the first instruction outside IMU_PERFORMANCE_TEST_2/'
                         'IMU_PERFORMANCE_TESTS_4, the interpreter, SWCALL and FINETIME (ipt_leaves), or an idle point '
                         '(ipt_idle: CHECKG1 after PIPAX was unchanged, FINETIME +1 after LOSCALAR 37777)',
             'compared_words': '2048 erasable words (A, L 16-bit) and the interrupt-enable state'}
    (B / 'lm-imu-performance-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {proof["compared"]} of {len(digests)} lm-imu-performance cases equal the original program '
          f'({len(digests) - proof["compared"]} refused); C64 parts run {len(chosen)} rows ({covering} covering every edge and key)')


if __name__ == '__main__':
    main()
