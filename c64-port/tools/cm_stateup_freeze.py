"""Run the original-program oracle for cm-stateup and freeze digests.

Builds the host-only yaAGC driver (tools/cm_stateup_reference.c), runs it
on the unmodified Comanche055 rope, checks the native snapshot
(build/cm-stateup-native) is byte-identical, and writes
tests/cm_stateup_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and every 17th digest (17 is prime to the 12 entries, so all are reached) to
tests/cm_stateup_c64_vectors.h. Also writes build/cm-stateup-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
CORE = ['tests/cm_stateup_cases.c', 'src/cm_stateup.c', 'src/cm_interp_orders.c', 'src/cm_interp_steps.c',
        'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/cm_stateup_reference.c', *CORE, '-o', 'build/cm-stateup-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/cm-stateup-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/cm-stateup-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_stateup_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, SUPERBNK and all 2048 erasable words. */',
           f'#define CM_STATEUP_VECTORS {len(values)}u']
    table(out, 'cm_stateup_expected', values)
    (R / 'tests/cm_stateup_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_stateup_freeze.py: every',
           ' * 17th digest of tests/cm_stateup_vectors.h, for the C64 diagnostic. */',
           '#define CM_STATEUP_C64_STRIDE 17u', f'#define CM_STATEUP_C64_COUNT {len(values[::17])}u']
    table(c64, 'cm_stateup_c64', values[::17])
    (R / 'tests/cm_stateup_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': 'every order-pair word of STATEUP, STATEND, THISVINT (bank 13) and R00 (bank 04) (12), at NEWOPS',
             'boundary': 'NEWOPS with LOC on the pair to NEWOPS with LOC outside the file (CALL/STCALL/CLRGO/RVQ targets), R00 EXIT to basic code, or CHANG2',
             'full_physical_words': 2048}
    (B / 'cm-stateup-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program')


if __name__ == '__main__':
    main()
