"""Compile the fixed words Comanche055 ALARM_AND_ABORT reads.

ALARM and ALARM2 read the alarm code their caller placed after its `TC`
(`INDEX Q; CA 0`); BAILOUT (= ABORT) and POODOO read it after VAC5STOR
through the caller's Q saved in ALMCADR (`INDEX ALMCADR; CAF 0`). This
tool emits that word for every genuine TC site (tools/agc_sites_generate.py
sites()), the CADRs after this file's own `TC BANKCALL` and `TC POSTJUMP`
(read by cm_interbank_routines), and the
fixed constants the file reads with CA/CAF/CS/AD/MASK, each checked against
the listing and the rope; native code never reads the rope.

  python3 tools/cm_alarm_generate.py           # write src/cm_alarm_operands.inc
  python3 tools/cm_alarm_generate.py --check   # fail if stale
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from agc_sites_generate import listing_lines, sites  # noqa: E402
from fixed_data_generate import fixed_address, rope_word  # noqa: E402

MISSION = 'Comanche055'
PROGRAM = 'ALARM_AND_ABORT'
OUTPUT = 'src/cm_alarm_operands.inc'
CALLEES = ('ALARM', 'ALARM2', 'BAILOUT', 'POODOO')
DATA_OPS = ('CA', 'CAF', 'CS', 'AD', 'MASK')


def build():
    base = ROOT / 'build/fixed-data' / MISSION
    listing = (base / 'assembly.lst').read_text(errors='replace')
    rope = (base / 'MAIN.agc.bin').read_bytes()
    rows = list(listing_lines(listing))
    calls, rope_sha = sites(MISSION, CALLEES)
    own, _ = sites(MISSION, ('BANKCALL', 'POSTJUMP'))
    own = [r for r in own if r['caller'].startswith(PROGRAM)]
    listed = {}
    for path, line, address, words, label, op, opnd in rows:
        at = fixed_address(address) if words else None
        if at is not None:
            for k, w in enumerate(words):
                listed[at + k] = (w, f'{path}:{line}', f'{label} {op} {opnd}'.strip())
    constants = {}
    for path, line, address, words, label, op, opnd in rows:
        if not path.startswith(PROGRAM) or op not in DATA_OPS or len(words) != 1 or opnd == '0':
            continue
        address12, here = words[0] & 0o7777, fixed_address(address)
        if address12 < 0o2000:
            continue
        phys = address12 if address12 >= 0o4000 else here // 1024 * 1024 + address12 - 0o2000
        word = listed[phys][0]
        assert rope_word(rope, phys) == word, (path, line)
        name = re.sub(r'\W', '_', opnd.split()[0])
        assert constants.get(name, (phys, word)) == (phys, word), name
        constants[name] = (phys, word)
    table = [{'physical': r['physical'], 'word': r['word'], 'kind': f"{r['callee']} {r['operand']}", 'source': r['caller']}
             for r in calls + own]
    table += [{'physical': p, 'word': w, 'kind': f'constant {n}', 'source': listed[p][1]} for n, (p, w) in constants.items()]
    table.sort(key=lambda r: r['physical'])
    assert len({r['physical'] for r in table}) == len(table)
    return calls, own, constants, table, rope_sha


def render(calls, own, constants, table, rope_sha):
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_alarm_generate.py. */',
           f'/* {MISSION} ALARM_AND_ABORT: the alarm code after every genuine TC ' + ', '.join(CALLEES) + ',',
           ' * the CADRs after its own TC BANKCALL/POSTJUMP, and the fixed constants it reads;',
           f' * keyed by physical fixed word. Oracle rope sha256 {rope_sha}. */']
    for name, (phys, word) in sorted(constants.items()):
        bank, offset = divmod(phys, 1024)
        out.append(f'#define CM_ALARM_K_{name} 0{word:05o}u /* {bank:02o},{offset + 0o2000:04o} */')
    out.append(f'#define CM_ALARM_OPERAND_COUNT {len(table)}u')
    out.append(f'static const agc_site_operand cm_alarm_operands[{len(table)}]={{')
    for row in table:
        bank, offset = divmod(row['physical'], 1024)
        out.append(f" {{{row['physical']}u,0{row['word']:05o}}}, /* {bank:02o},{offset + 0o2000:04o} "
                   f"{row['kind'][:40]} <- {row['source']} */")
    out.append('};')
    out.append('#ifdef CM_ALARM_SITE_LIST /* tests: operand word and callee of each TC site */')
    out.append(f'#define CM_ALARM_SITE_COUNT {len(calls)}u')
    out.append('enum { ' + ','.join(f'CM_AS_{c}={i}' for i, c in enumerate(CALLEES)) + ' };')
    out.append(f'static const struct {{ uint16_t physical; uint8_t callee; }} cm_alarm_site_list[{len(calls)}]={{')
    for i in range(0, len(calls), 8):
        out.append(' ' + ''.join(f"{{{s['physical']}u,{CALLEES.index(s['callee'])}}}," for s in calls[i:i + 8]))
    out.append('};')
    out.append('#endif')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--json', help='also write the table as JSON (evidence)')
    args = parser.parse_args()
    calls, own, constants, table, rope_sha = build()
    text = render(calls, own, constants, table, rope_sha)
    if args.json:
        pathlib.Path(args.json).write_text(json.dumps(
            {'mission': MISSION, 'rope_sha256': rope_sha, 'sites': calls, 'own_cadrs': own,
             'constants': {n: {'physical': p, 'word': w} for n, (p, w) in constants.items()}}, indent=1) + '\n')
    path = ROOT / OUTPUT
    if args.check:
        if not path.exists() or path.read_text() != text:
            sys.exit(f'{OUTPUT} is stale; run tools/cm_alarm_generate.py')
        print(f'PASS: {OUTPUT} matches {len(calls)} {MISSION} sites, {len(table)} words')
        return
    path.write_text(text)
    print(f'wrote {OUTPUT}: {len(calls)} sites, {len(table)} words')


if __name__ == '__main__':
    main()
