"""Run the original-program oracle for t4rupt-core and freeze digests.

Builds the host-only yaAGC driver tools/t4rupt_core_reference.c, runs it
on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/t4rupt-core-native lm|cm) is byte-identical, and writes
tests/t4rupt_core_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK, the interrupt-enable bit, InIsr and channel 10) and
tests/t4rupt_core_c64_vectors.h (every sixteenth). Also writes
build/t4rupt-core-proof.json and build/t4rupt-core-executed-{lm,cm}.txt.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = {'lm': B / 'fixed-data/Luminary099/MAIN.agc.bin', 'cm': B / 'fixed-data/Comanche055/MAIN.agc.bin'}
NATIVE = ['src/t4rupt_core.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/t4rupt_core_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
T4 = 2048
RET = 64
ENTRIES = {'lm': ['06,2000 T4RUPT', '06,2116 T4JUMP (NOVAC return)', '06,2121 RCSMONIT return', '06,2125 RCSMONIT return'],
           'cm': ['06,2000 T4RUPT', '06,2116 T4JUMP (NOVAC return)', '06,2130 OPTTEST']}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/t4rupt_core_reference.c', *CORE,
                    '-o', 'build/t4rupt-core-reference'], cwd=R, check=True)
    full, c64, proof = [], [], {}
    for m in ('lm', 'cm'):
        ref = subprocess.run(['./build/t4rupt-core-reference', str(ROPES[m]), m,
                              f'build/t4rupt-core-executed-{m}.txt'], cwd=R, check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/t4rupt-core-native', m], cwd=R, check=True, capture_output=True).stdout
        assert ref == nat, f't4rupt-core {m}: native differs from the original program'
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        digests = [digest(r[1:]) for r in rows]
        name = m.upper()
        full += [f'#define T4_{name}_VECTORS {len(digests)}u', *table(f't4_{m}_expected', digests)]
        c64 += [f'#define T4_{name}_C64_COUNT {len(digests[::STRIDE])}u', *table(f't4_{m}_c64', digests[::STRIDE])]
        kinds = collections.Counter(f"{ENTRIES[m][0 if r[0] < T4 else 1 + (r[0] - T4) // RET]}:{('returned', 'alarm', 'refused')[r[1]]}" for r in rows)
        proof[m] = {'mission': ROPES[m].parent.name, 'rope_sha256': hashlib.sha256(ROPES[m].read_bytes()).hexdigest(),
                    'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
                    'outcomes': dict(sorted(kinds.items())), 'entries': ENTRIES[m]}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/t4rupt_core_freeze.py from the',
            ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of the',
            ' * outcome kind and, unless refused, all 2048 erasable words, SUPERBNK, IRQ enable, InIsr and channel 10. */']
    (R / 'tests/t4rupt_core_vectors.h').write_text('\n'.join(head + full) + '\n')
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/t4rupt_core_freeze.py: every',
            ' * sixteenth digest of tests/t4rupt_core_vectors.h, for the C64 diagnostic. */',
            f'#define T4_C64_STRIDE {STRIDE}u']
    (R / 'tests/t4rupt_core_c64_vectors.h').write_text('\n'.join(head + c64) + '\n')
    proof.update({'boundary': 'one routine from its entry to the continuation it leaves in Z (RESUME, NOVAC, '
                              'or a T4JUMP target); the original runs to the first time it reaches that Z (and '
                              'FB in banked memory)',
                  'compared': 'outcome kind; all 2048 erasable words, SUPERBNK, interrupt enable, InIsr, channel 10',
                  'full_physical_words': 2048})
    (B / 't4rupt-core-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {proof['lm']['cases']} LM and {proof['cm']['cases']} CM t4rupt-core cases equal the original programs")


if __name__ == '__main__':
    main()
