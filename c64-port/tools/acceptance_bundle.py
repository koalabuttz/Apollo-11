"""Build one program's whole-program acceptance evidence from one commit
(docs/PORT_SCOPE.md, integrated_applications; acceptance bar item 1).

  acceptance_bundle.py lm|cm [--check-only] [--only CATEGORY,...]

At HEAD, with no changes to the port's sources, it:

  1. builds the flight store and the resident once (make flight-store,
     tools/resident_flight_build.py);
  2. runs each category's generator, `tools/<name>_acceptance.py <m>`: the
     tools/*_acceptance.py whose docstring says "Write one program's
     <category>". Each lane owns its generator; this tool only calls it. A
     category with no generator is listed as FAIL (missing);
  3. reads each doc, docs/acceptance/<Program>-<category>.md: the
     "Generated by ... at commit `C`. Result: **PASS**" line (C is HEAD,
     or a commit whose port sources, src include platform tools tests
     Makefile, are HEAD's: the commit that adds the docs), and every
     evidence/<id>/<file> it cites, whose file must exist and match the
     sha256 the doc gives for it (tools/evidence.py verify on each id);
  4. prints one table (category, generator, result, commit, evidence) and
     writes it to build/acceptance-bundle-<m>.json.

It exits 0 only when all six categories PASS, each doc cites HEAD's sources, and
all their evidence resolves. --check-only skips steps 1 and 2 (a dry run
on what is already in the tree).
"""
import argparse
import hashlib
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from port_coverage import APPLICATION_EVIDENCE  # noqa: E402

PROGRAM = {'lm': 'Luminary099', 'cm': 'Comanche055'}
# The port's sources: a change here between generators would mix commits.
SOURCES = ['src', 'include', 'platform', 'tools', 'tests', 'Makefile']
HEADER = re.compile(r'Generated by `([^`]*)` at commit `([0-9a-f]{7,40})( \(dirty\))?`\. Result: \*\*(PASS|FAIL)\*\*')
CITE = re.compile(r'evidence/([a-z0-9][a-z0-9-]*)/([A-Za-z0-9][A-Za-z0-9._-]*)(?:`? \(sha256 `([0-9a-f]{8,64})(?:\.\.\.)?`\))?')


def git(*args):
    return subprocess.run(['git', *args], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def same_sources(commit, head):
    """The doc's commit is HEAD, or the port's sources are the same at both
    (a commit that only adds docs and evidence keeps the docs current)."""
    if head.startswith(commit):
        return True
    if subprocess.run(['git', 'cat-file', '-e', f'{commit}^{{commit}}'], cwd=ROOT, capture_output=True).returncode:
        return False
    return subprocess.run(['git', 'diff', '--quiet', commit, head, '--', *SOURCES], cwd=ROOT).returncode == 0


def generators():
    """{category: tools/<x>_acceptance.py}, from each generator's docstring."""
    found = {}
    for path in sorted((ROOT / 'tools').glob('*_acceptance.py')):
        text = path.read_text(errors='replace')[:2000]
        for cat in APPLICATION_EVIDENCE:
            if re.search(rf"Write one program's\s+{cat}\b", text):
                found.setdefault(cat, path.relative_to(ROOT).as_posix())
    return found


def run(cmd, log):
    print('+', ' '.join(cmd), flush=True)
    with log.open('w') as f:
        return subprocess.run(cmd, cwd=ROOT, stdout=f, stderr=subprocess.STDOUT).returncode


def check_doc(m, cat, head):
    """(result, commit, evidence note, problems) for one category's doc."""
    doc = ROOT / 'docs/acceptance' / f'{PROGRAM[m]}-{cat}.md'
    if not doc.exists():
        return 'FAIL', '', '', [f'no {doc.relative_to(ROOT)}']
    text = doc.read_text()
    h = HEADER.search(text)
    if not h:
        return 'FAIL', '', '', ['no "Generated by ... at commit `C`. Result: **PASS|FAIL**" line']
    problems = []
    commit = h[2] + (' (dirty)' if h[3] else '')
    if h[3]:
        problems.append(f'generated from a tree with uncommitted source changes ({commit})')
    elif not same_sources(h[2], head):
        problems.append(f'cites {commit}: not HEAD {head[:12]}, and the sources differ (or the commit is unknown)')
    if h[4] != 'PASS':
        problems.append('the doc says FAIL')
    ids, files, bad = set(), set(), []
    for c in CITE.finditer(text):
        ids.add(c[1])
        f = ROOT / 'evidence' / c[1] / c[2]
        files.add(f)
        if not f.exists():
            bad.append(f'{c[1]}/{c[2]} missing')
        elif c[3] and not sha(f).startswith(c[3]):
            bad.append(f'{c[1]}/{c[2]} sha256 is not {c[3]}')
    for i in sorted(ids):
        v = subprocess.run([sys.executable, 'tools/evidence.py', 'verify', i], cwd=ROOT, capture_output=True, text=True)
        if v.returncode:
            bad.append(f'evidence.py verify {i} failed')
    problems += sorted(set(bad))
    note = f'{len(files)} files in {len(ids)} ids' + (', all resolve' if not bad else '')
    return ('PASS' if not problems else 'FAIL'), commit, note, problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('mission', choices=sorted(PROGRAM))
    ap.add_argument('--check-only', action='store_true', help='only check the docs and evidence in the tree')
    ap.add_argument('--only', default='', help='comma-separated categories to generate (all are still checked)')
    a = ap.parse_args(argv)
    m, head = a.mission, git('rev-parse', 'HEAD')
    gens = generators()
    only = set(filter(None, a.only.split(','))) or set(APPLICATION_EVIDENCE)
    logs = ROOT / 'build/acceptance-bundle' / m
    logs.mkdir(parents=True, exist_ok=True)
    ran = {}
    if not a.check_only:
        if git('status', '--porcelain', '--untracked-files=no', '--', *SOURCES):
            raise SystemExit('the port has uncommitted source changes: commit them first, so every doc cites one commit')
        for step, cmd in (('store', ['make', 'flight-store', 'build/agc_engine_hardware_dv.o']),
                          ('resident', [sys.executable, 'tools/resident_flight_build.py'])):
            if run(cmd, logs / f'{step}.log'):
                raise SystemExit(f'{step} build failed: {logs / f"{step}.log"}')
        for cat in APPLICATION_EVIDENCE:
            if cat in only and cat in gens:
                ran[cat] = run([sys.executable, gens[cat], m], logs / f'{cat}.log')
    rows = []
    for cat in APPLICATION_EVIDENCE:
        gen = gens.get(cat)
        if not gen:
            rows.append(dict(category=cat, generator='missing', result='FAIL', commit='', evidence='',
                             problems=['no tools/*_acceptance.py says "Write one program\'s ' + cat + '"']))
            continue
        result, commit, note, problems = check_doc(m, cat, head)
        if cat in ran and ran[cat]:
            problems.insert(0, f'generator exited {ran[cat]} ({logs.relative_to(ROOT)}/{cat}.log)')
            result = 'FAIL'
        rows.append(dict(category=cat, generator=gen, result=result, commit=commit, evidence=note, problems=problems))
    print(f'\n{PROGRAM[m]} at {head[:12]}: whole-program acceptance\n')
    print(f"{'Category':32} {'Result':6} {'Commit':14} {'Generator':34} Evidence")
    for r in rows:
        print(f"{r['category']:32} {r['result']:6} {r['commit'][:14]:14} {r['generator']:34} {r['evidence']}")
        for p in r['problems']:
            print(f'    - {p}')
    ok = all(r['result'] == 'PASS' for r in rows)
    print(f"\n{sum(r['result'] == 'PASS' for r in rows)} of {len(rows)} categories pass"
          f"{'' if ok else '; the program is not ready for its flip PR'}")
    out = ROOT / 'build' / f'acceptance-bundle-{m}.json'
    out.write_text(json.dumps(dict(program=PROGRAM[m], head=head, ok=ok, categories=rows), indent=1) + '\n')
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
