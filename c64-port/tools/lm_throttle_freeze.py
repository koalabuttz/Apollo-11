"""Run the original-program oracle for lm-throttle and freeze digests.

Builds the host-only yaAGC driver tools/lm_throttle_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-throttle-native) is byte-identical, and writes
tests/lm_throttle_vectors.h (one digest per case: two 16-bit running sums
over the outcome, channel 14 and all 2048 erasable words) and
tests/lm_throttle_c64_vectors.h (every thirty-second). Also writes
build/lm-throttle-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_throttle.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_throttle_cases.c', 'src/lm_exec_routines.c', 'src/lm_admission_image.c',
          'src/lm_waitlist_image.c', 'src/waitlist.c', 'src/executive.c', 'src/p66_native.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 32


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_throttle_reference.c', *CORE,
                    '-o', 'build/lm-throttle-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-throttle-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-throttle-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-throttle: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_throttle_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channel 14 and all 2048 erasable words. */',
           f'#define LM_THR_VECTORS {len(digests)}u', *table('lm_thr_expected', digests)]
    (R / 'tests/lm_throttle_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_throttle_freeze.py: every',
           ' * sixteenth digest of tests/lm_throttle_vectors.h, for the C64 diagnostic. */',
           f'#define LM_THR_C64_STRIDE {STRIDE}u', f'#define LM_THR_C64_COUNT {len(c64)}u',
           *table('lm_thr_c64', c64)]
    (R / 'tests/lm_throttle_c64_vectors.h').write_text('\n'.join(out) + '\n')
    names = ['THROTTLE', 'THROTTLE+3', 'FLATOUT', 'WHATOUT']
    kinds = collections.Counter(f"{names[r[0] % 4]}:returned" for r in rows if r[1] == 0)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['31,2216 THROTTLE', '31,2221 THROTTLE+3', '31,2224', '31,2230', '31,2303', '31,2370 FLATOUT',
                         '31,2371 WHATOUT', '31,2400 MASSMULT', '31,3740 FASTCHNG'],
             'boundary': "each entry from a random image (FB bank 31, EB 7, channel 14 bits 1-5, MODREG 66 in a "
                         "quarter) to the caller's return in Q (SWRETURN, fixed-fixed 06000-06677 or bank 31); "
                         'compared: outcome, channel 14 and all 2048 erasable words',
             'full_physical_words': 2048}
    (B / 'lm-throttle-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-throttle cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
