"""Run the original-program oracle for imu-compensation and freeze digests.

Builds the host-only yaAGC driver tools/imu_compensation_reference.c, runs it
on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/imu-compensation-native) is byte-identical, and writes
tests/imu_compensation_vectors.h (one digest per case: two 16-bit running
sums over the kind, all 2048 erasable words and the interrupt-enable state)
and tests/imu_compensation_c64_vectors.h (C64 subsets). Also writes
build/imu-compensation-proof.json with the stop reached per routine.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / 'tools'))
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = [B / 'fixed-data/Luminary099/MAIN.agc.bin', B / 'fixed-data/Comanche055/MAIN.agc.bin']
NATIVE = ['src/imu_compensation.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
          'src/lm_interbank_routines.c', 'src/lm_interbank.c', 'src/cm_interbank_routines.c',
          'src/cm_interbank_complete.c', 'src/lm_exec_routines.c', 'src/lm_admission_image.c',
          'src/lm_waitlist_image.c', 'src/waitlist.c', 'src/executive.c', 'src/p66_native.c',
          'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c', 'tests/imu_compensation_cases.c']
CORE = NATIVE + ['tests/cm_executive_cases.c', str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'),
                 str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 37
TRIP_STRIDE = 16
ENTRY_CASES, ROUTINES, SITES, PLAIN_FIRST = 10240, 20, 6, 13312
NAMES = ['LM 06,3263 1/PIPA', 'LM 06,3352 NOVAC return', 'LM 06,3507 1/GYRO', 'LM 06,3535 IMUPULSE return',
         'LM 06,3537 IMUSTALL return', 'LM 06,3540 GCOMP1', 'LM 06,3555 NBDONLY', 'LM 06,3575 PIPASR return',
         'LM 06,3663 LASTBIAS', 'LM 06,3665 PIPUSE1 return', 'LM 06,3701 GCOMPZER',
         'CM 06,3262 1/PIPA', 'CM 06,3406 NOVAC return', 'CM 06,3474 1/GYRO', 'CM 06,3522 IMUPULSE return',
         'CM 06,3524 IMUSTALL return', 'CM 06,3525 GCOMP1', 'CM 06,3542 NBDONLY', 'CM 06,3636 LASTBIAS',
         'CM 06,3640 PIPUSE return']
STOPS = {0o4631: 'SWRETURN', 0o4616: 'BANKCALL', 0o4674: 'IBNKCALL', 0o5072: 'NOVAC', 0o5155: 'ENDOFJOB',
         0o4675: 'SWRETURN', 0o4662: 'BANKCALL', 0o5134: 'NOVAC', 0o5217: 'ENDOFJOB', 0o5716: 'BAILOUT1'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/imu_compensation_reference.c', *CORE,
                    '-o', 'build/imu-compensation-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/imu-compensation-reference', *map(str, ROPES)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/imu-compensation-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'imu-compensation: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/imu_compensation_freeze.py from the',
           ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of',
           ' * the kind, all 2048 erasable words and the interrupt-enable state. */',
           f'#define ICP_VECTORS {len(digests)}u', *table('icp_expected', digests)]
    (R / 'tests/imu_compensation_vectors.h').write_text('\n'.join(out) + '\n')
    entry = digests[:ENTRY_CASES:STRIDE]
    trips = [d for i, d in enumerate(digests[ENTRY_CASES:PLAIN_FIRST]) if i % SITES >= 4][::TRIP_STRIDE]
    plain = digests[PLAIN_FIRST::TRIP_STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/imu_compensation_freeze.py for the',
           ' * C64 diagnostics: every 37th entry case; every 16th Comanche round trip',
           ' * (sites 4 and 5) and every 16th plain Luminary round trip. */',
           f'#define ICP_C64_STRIDE {STRIDE}u', f'#define ICP_C64_COUNT {len(entry)}u',
           f'#define ICP_C64_TRIP_STRIDE {TRIP_STRIDE}u', f'#define ICP_C64_CM_TRIPS {len(trips)}u',
           f'#define ICP_C64_PLAIN_TRIPS {len(plain)}u',
           '#ifdef ICP_ENTRY_ONLY', *table('icp_c64', entry), '#else',
           *table('icp_c64_cm_trips', trips), *table('icp_c64_plain', plain), '#endif']
    (R / 'tests/imu_compensation_c64_vectors.h').write_text('\n'.join(out) + '\n')
    stops = collections.defaultdict(collections.Counter)
    for r in rows:
        n, z = r[0], r[2 + 5]
        if n < ENTRY_CASES:
            key = NAMES[n % ROUTINES]
        elif n < PLAIN_FIRST:
            key = f'round trip site {(n - ENTRY_CASES) % SITES}'
        else:
            key = f'plain LM round trip site {(n - PLAIN_FIRST) % 4}'
        stops[key][STOPS.get(z, 'caller return')] += 1
    proof = {'missions': ['Luminary099', 'Comanche055'],
             'rope_sha256': [hashlib.sha256(p.read_bytes()).hexdigest() for p in ROPES],
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'stops': {k: dict(sorted(v.items())) for k, v in stops.items()},
             'boundary': 'entry cases: from the routine to the first external address (SWRETURN, BANKCALL, '
                         'IBNKCALL, NOVAC, ENDOFJOB); round trips: TC BANKCALL 1/PIPA or GCOMPZER from every '
                         'genuine site to the caller Q+1, LM BAILOUT1 or CM NOVAC; plain LM round trips stop at NOVAC',
             'compared': '2048 erasable words (A, L 16-bit) and the interrupt-enable state'}
    (B / 'imu-compensation-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} imu-compensation cases equal the original programs')


if __name__ == '__main__':
    main()
