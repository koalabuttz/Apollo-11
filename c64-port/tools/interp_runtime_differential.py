"""Differential of the runtime interpreter (src/lm_interp_runtime.c,
src/cm_interp_runtime.c) against yaAGC, over a compiled-routine milestone's
cases (tools/interp_routine_differential.py): the same cases, the same
oracle and the same stops, with every interpretive point of the file run by
the interpreter instead of the file's compiled routines (the file's basic
routines stay). A case passes when the interpreter reaches the oracle's stop
with the same Z, erasable image and interrupt-enable state.

  interp_runtime_differential.py <spec>... [--cases N] [--show K] [--all]"""
import argparse
import collections
import os
import random
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import interp_routine_differential as D
import interp_specs

R, B = D.R, D.B
RT = ['src/lm_interp_runtime.c', 'src/cm_interp_runtime.c', 'src/rope_image_host.c', 'tools/interp_runtime_target.c']


def rtb_table(spec_id, spec, missions):
    """build/<id>-rtb.c: the spec's native RTB routines (its 'rtb' map, which
    the compiled routines call inline) as basic routines keyed by the RTB
    target, as a program registers them: irt_rtb_lm and irt_rtb_cm."""
    out = ['/* Generated by tools/interp_runtime_differential.py. */']
    for m in spec['missions']:
        out += [l for l in open(os.path.join(R, 'src/%s.c' % spec['base'][m])) if l.startswith('#include')]
    out += ['#include "cm_native_image.h"', '#include "agc_transfer.h"', '#define W s->words',
            '#ifdef IRT_RTB_TRACE', '#include <stdio.h>',
            '#define RTB_TRACE(n) do{if(st){unsigned i_;fprintf(stderr,"rtb %d refused Z %05o FB %05o EB %05o:",n,W[5],W[4],W[3]);'
            'for(i_=2;i_<2048u;++i_)if(W[i_]>077777u)fprintf(stderr," %04o=%06o",i_,W[i_]);fprintf(stderr,"\\n");}}while(0)',
            '#else', '#define RTB_TRACE(n) ((void)0)', '#endif']
    for cm, mi in enumerate(missions):
        m = ('lm', 'cm')[cm]
        ents = []
        if m in spec['missions']:
            for lab, x in sorted(spec.get('rtb', {}).items()):
                expr = x.get(m) if isinstance(x, dict) else None
                if not expr or lab not in mi.L.labels:
                    continue
                f = 'rtb_%s_%d' % (m, len(ents))
                if cm:
                    out.append('static enum exec_status %s(const agc_native_program *p,apollo_overlay_state *s,void *v){cm_native_io *c=v;'
                               'p66_bias_io l,*io=&l;int st;(void)p;l.superbank=c->superbank;l.interrupt_enabled=c->interrupt_enabled;'
                               'st=(int)(%s);c->superbank=l.superbank;c->interrupt_enabled=l.interrupt_enabled;(void)io;return st?EXEC_OUT_OF_SCOPE:EXEC_OK;}' % (f, expr))
                else:
                    out.append('static enum exec_status %s(const agc_native_program *p,apollo_overlay_state *s,void *v){p66_bias_io *io=v;(void)p;(void)io;'
                               'int st=(int)(%s);RTB_TRACE(%s);return st?EXEC_OUT_OF_SCOPE:EXEC_OK;}' % (f, expr, len(ents)))
                ents.append((mi.L.labels[lab], f))
        ents.sort()
        out.append('static const agc_routine_entry e_%s[%d]={%s};' % (m, max(1, len(ents)), ','.join('{%d,%s}' % e for e in ents) or '{0,0}'))
        out.append('const agc_routine_table irt_rtb_%s={e_%s,%d};' % (m, m, len(ents)))
    path = os.path.join(B, '%s-rtb.c' % spec_id)
    open(path, 'w').write('\n'.join(out) + '\n')
    return path


def build(spec_id, spec, missions):
    ref, _ = D.build(spec_id, spec)
    nat = os.path.join(B, '%s-runtime' % spec_id)
    obj = os.path.join(B, '%s-runtime-target.o' % spec_id)
    steps = min(60000, spec.get('max_steps', 200) * 40)
    subprocess.run(['cc', *D.FLAGS, '-c', '-Dirc_program=irc_program_compiled', spec['target'], '-o', obj], cwd=R, check=True)
    srcs = ['src/%s.c' % spec['base'][m] for m in spec['missions']] + spec.get('native_sources', []) + D.common(spec)
    subprocess.run(['cc', *D.FLAGS, *(['-DIRT_RTB_TRACE'] if os.environ.get('IRT_RTB_TRACE') else []), '-DIRC_MAX_STEPS=%d' % steps, *D.cut_flags(spec), *srcs, *RT, obj, rtb_table(spec_id, spec, missions),
                    'tools/interp_routine_native.c', '-o', nat], cwd=R, check=True)
    return ref, nat


def one(spec_id, a):
    spec = interp_specs.SPECS[spec_id]
    if spec.get('channel_inputs'):
        os.environ['IRC_INPUTS'] = '1'
    else:
        os.environ.pop('IRC_INPUTS', None)
    missions = [D.Mission(spec, m) if m in spec['missions'] else D.Absent(m) for m in ('lm', 'cm')]
    if spec.get('flow_states'):
        D.flow_states(spec_id, spec, missions)
    rng = random.Random('interp-routine:' + spec_id)
    cases = []
    for cm, mi in enumerate(missions):
        if mi.m not in spec['missions']:
            continue
        # The interpreter covers interpretive points; basic ones stay compiled.
        pts = [p for p in mi.points if a.all or mi.kinds[p] == 'i']
        for p in pts:
            for n in range(a.cases):
                seed, edits, ie, stop, sb = D.case(mi, p, n, rng)
                cases.append({'cm': cm, 'point': p, 'seed': seed, 'edits': D.Edits(edits), 'ie': ie, 'stop': stop, 'sb': sb})
    for m, mi in zip(('LM', 'CM'), missions):
        # (The oracle's stops among the interpreter's basic entries stay stops.)
        os.environ['IRT_STOPS_' + m] = ','.join(str(x) for x in getattr(mi, 'body_exits', []) + getattr(mi, 'externals', []))
        os.environ['IRT_RANGES_' + m] = ','.join('%d-%d' % (x, y) for x, y in getattr(getattr(mi, 'cp', None), 'ranges', []))
    os.environ['IRT_ROPE_LM'], os.environ['IRT_ROPE_CM'] = D.ROPES
    os.makedirs(B, exist_ok=True)
    path = os.path.join(B, '%s-runtime-cases.bin' % spec_id)
    ref, nat = build(spec_id, spec, missions)
    D.BUILT[:] = [ref, nat]
    if spec.get('resume_flow'):
        D.flow_seed(missions, cases, rng, ref, path)
    D.write_cases(path, missions, cases)
    rows_r = D.run([ref, *D.ROPES, path])
    rows_n = D.run([nat, path])
    bad = [i for i, (x, y) in enumerate(zip(rows_r, rows_n)) if x != y]
    # As in the compiled differential: a run that ends refusing at a basic
    # block with an I/O channel instruction waits for a channel model, and
    # is counted, not compared.
    chan = [i for i in bad if rows_n[i][1] != '0' and any(
        missions[cases[i]['cm']].cp.logical_of(p) == int(rows_n[i][2]) for p in missions[cases[i]['cm']].cp.channel_blocks)]
    bad = [i for i in bad if i not in chan]
    if chan:
        print('  (%d cases end at an I/O channel instruction of the file\'s basic code: not compared)' % len(chan))
    where = collections.Counter()
    for i in bad:
        mi = missions[cases[i]['cm']]
        where['%s %s %s' % (mi.m, mi.cp.where(cases[i]['point']), mi.cp.name(cases[i]['point']))] += 1
    print('%s: %d cases, %d differ' % (spec_id, len(cases), len(bad)))
    for k, n in where.most_common(a.show):
        i = next(j for j in bad if '%s %s' % (missions[cases[j]['cm']].m, missions[cases[j]['cm']].cp.where(cases[j]['point'])) in k)
        print('  %s x%d  (oracle %s, interpreter %s)' % (k, n, ' '.join(rows_r[i][1:3]), ' '.join(rows_n[i][1:3])))
    if a.dump and bad:
        # The words the first differing cases end with, oracle against interpreter.
        sub = path + '.show'
        show = bad[:a.dump]
        D.write_cases(sub, missions, [cases[i] for i in show])
        dr, dn = D.run([ref, *D.ROPES, sub, 'dump']), D.run([nat, sub, 'dump'])
        for j, i in enumerate(show):
            mi = missions[cases[i]['cm']]
            x, y = dr[j][4:], dn[j][4:]
            diff = ['%04o:%06o/%06o' % (k, int(x[k]), int(y[k])) for k in range(min(len(x), len(y))) if x[k] != y[k]]
            print('  case %d %s %s: Z %05o/%05o kind %s/%s  %s' % (i, mi.m, mi.cp.where(cases[i]['point']), int(dr[j][2]), int(dn[j][2]),
                                                        dr[j][1], dn[j][1], ' '.join(diff[:24])))
    return len(cases), len(bad)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('specs', nargs='*')
    ap.add_argument('--cases', type=int, default=16, help='cases per routine')
    ap.add_argument('--show', type=int, default=8)
    ap.add_argument('--dump', type=int, default=0, help='word diffs of the first N differing cases')
    ap.add_argument('--all', action='store_true', help='also cases from basic routines')
    a = ap.parse_args()
    total = bad = 0
    for s in a.specs or sorted(interp_specs.SPECS):
        try:
            n, b = one(s, a)
        except (subprocess.CalledProcessError, SystemExit, Exception) as e:   # (one spec's build trouble)
            print('%s: not run (%s)' % (s, str(e).splitlines()[0] if str(e) else type(e).__name__))
            continue
        total += n
        bad += b
    print('total: %d cases, %d differ' % (total, bad))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
