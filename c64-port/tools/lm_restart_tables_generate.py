"""Compile Luminary099 RESTART_TABLES into native constant data.

The restart tables are source data: SIZETAB index constants and, per phase, a
priority or delta-time word followed by a 2CADR. RESTARTS reads them through
PRDTTAB/CADRTAB/SIZETAB with an index; the native consumer does the same with
this array, keyed from PRDTTAB (01,2000). Each word comes from the unmodified
source listing and is checked against the assembled rope. The table also emits
the (group, phase) of every labelled table entry, and the two inline words
after RESTARTS' `TC FINDVAC` (2CADR INITDSP), for the composition tests.

  python3 tools/lm_restart_tables_generate.py           # write src/lm_restart_table_data.inc
  python3 tools/lm_restart_tables_generate.py --check   # fail if stale
"""
import argparse
import hashlib
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
from agc_sites_generate import listing_lines  # noqa: E402
from fixed_data_generate import fixed_address, rope_word  # noqa: E402

MISSION = 'Luminary099'
OUTPUT = 'src/lm_restart_table_data.inc'
BASE = fixed_address('01,2000')            # PRDTTAB
LABEL = re.compile(r'^(\d)\.(\d+)SPOT$')


def build():
    base = ROOT / 'build/fixed-data' / MISSION
    listing = (base / 'assembly.lst').read_text(errors='replace')
    rope = (base / 'MAIN.agc.bin').read_bytes()
    rows = list(listing_lines(listing))
    words, labels, first = [], [], None
    for path, line, address, emitted, label, op, operands in rows:
        if not path.startswith('RESTART_TABLES') or not emitted:
            continue
        physical = fixed_address(address)
        if first is None:
            first = physical
        assert physical == first + len(words), (path, line, address)
        for k, word in enumerate(emitted):
            assert rope_word(rope, physical + k) == word, (path, line)
        if op in ('OCT', 'DEC'):
            text = operands.split()[0]
            value = int(text.rstrip('D'), 10 if (op == 'DEC' or text.endswith('D')) else 8)
            if 'B-' not in operands:
                assert value == emitted[0] or (value < 0 and emitted[0] == 0o77777 + value), (path, line)
        match = LABEL.match(label)
        if match:
            labels.append((int(match[1]), int(match[2], 8), physical - BASE))
        words.extend(emitted)
    assert first == BASE + 2, 'SIZETAB is expected at 01,2002'
    initdsp = None
    for index, row in enumerate(rows):
        if row[0].startswith('RESTARTS_ROUTINE') and row[5] == 'TC' and row[6].split()[0] == 'FINDVAC':
            nxt = next(r for r in rows[index + 1:] if r[3])
            assert nxt[5] == '2CADR' and nxt[6].split()[0] == 'INITDSP', nxt
            physical = fixed_address(nxt[2])
            assert [rope_word(rope, physical), rope_word(rope, physical + 1)] == nxt[3]
            initdsp = (physical, nxt[3])
    assert initdsp is not None
    return words, labels, initdsp, hashlib.sha256(rope).hexdigest()


def render(words, labels, initdsp, rope_sha):
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_restart_tables_generate.py. */',
           f'/* {MISSION} RESTART_TABLES: {len(words)} source data words at 01,2002 onward, indexed',
           ' * like PRDTTAB/CADRTAB/SIZETAB (01,2000/2001/2002). No executable words.',
           f' * Oracle rope sha256 {rope_sha}. */',
           '#define LM_RESTART_TABLE_FIRST 2u',
           f'#define LM_RESTART_TABLE_WORDS {len(words)}u']
    physical, pair = initdsp
    bank, offset = divmod(physical, 1024)
    out.append(f'/* 2CADR INITDSP after RESTARTS `TC FINDVAC` at {bank:02o},{offset + 0o2000:04o}. */')
    out.append(f'#define LM_RESTART_INITDSP_SITE {physical}u')
    out.append(f'#define LM_RESTART_INITDSP_0 0{pair[0]:05o}u')
    out.append(f'#define LM_RESTART_INITDSP_1 0{pair[1]:05o}u')
    out.append('#ifndef LM_RESTART_INITDSP_ONLY')
    out.append(f'static const agc_word lm_restart_table_data[{len(words)}]={{')
    for i in range(0, len(words), 10):
        out.append(' ' + ','.join(f'0{w:05o}' for w in words[i:i + 10]) + ',')
    out.append('};')
    out.append('#endif')
    out.append('#ifdef LM_RESTART_TABLE_PHASES /* tests: every labelled table entry */')
    out.append(f'#define LM_RESTART_TABLE_PHASE_COUNT {len(labels)}u')
    out.append(f'static const uint8_t lm_restart_table_phases[{len(labels)}][2]={{')
    out.append(' ' + ','.join(f'{{{g - 1},0{p:o}}}' for g, p, _ in labels))
    out.append('};')
    out.append('#endif')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--json', help='also write the table rows as JSON (evidence)')
    args = parser.parse_args()
    words, labels, initdsp, rope_sha = build()
    text = render(words, labels, initdsp, rope_sha)
    if args.json:
        pathlib.Path(args.json).write_text(json.dumps(
            {'mission': MISSION, 'rope_sha256': rope_sha, 'first_physical': BASE + 2,
             'words': words, 'labels': [{'group': g, 'phase': p, 'pointer': o} for g, p, o in labels],
             'initdsp': {'physical': initdsp[0], 'words': initdsp[1]}}, indent=1) + '\n')
    path = ROOT / OUTPUT
    if args.check:
        if not path.exists() or path.read_text() != text:
            sys.exit(f'{OUTPUT} is stale; run tools/lm_restart_tables_generate.py')
        print(f'PASS: {OUTPUT} matches {len(words)} {MISSION} RESTART_TABLES words')
        return
    path.write_text(text)
    print(f'wrote {OUTPUT}: {len(words)} words, {len(labels)} labelled phases')


if __name__ == '__main__':
    main()
