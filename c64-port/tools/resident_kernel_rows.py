"""Pick the resident kernel's C64 rows (make resident-kernel-rows).

Builds tests/resident_kernel_trace.c with only the kernel's translation unit
(src/<m>_kernel.c, which includes src/resident_kernel_body.inc) under
--coverage, traces every case of the six certified service milestones that
has a yaAGC oracle with tools/c64_row_cover.py, and writes the fewest cases
that take every kernel branch arc the host corpus takes, with each case's
frozen yaAGC digest, to tests/<m>_kernel_c64_rows.h. The trace is kept in
build/resident-kernel-<m>-arcs.json (reused when present).

  resident_kernel_rows.py lm|cm FLAGS... -- SOURCES...
"""
import os
import pathlib
import re
import subprocess
import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import c64_row_cover as RC

R = RC.R
MODULES = {'lm': ('lm_exs', 'lm_exj', 'lm_exi'), 'cm': ('cm_exs', 'cm_exj', 'cm_exi')}
VECTORS = {'exs': 'exec_services', 'exj': 'exec_jobs', 'exi': 'exec_idle'}
REFUSED = 0x00020002


def vectors(prefix):
    mission, mod = prefix.split('_')
    text = (R / 'tests' / f'{mission}_{VECTORS[mod]}_vectors.h').read_text()
    body = text[text.index(f'{prefix}_expected'):]
    body = body[body.index('{') + 1:body.index('}')]
    return [int(x, 0) for x in re.findall(r'0x[0-9a-fA-F]+', body)]


def build(mission, flags, sources):
    objdir = R / 'build' / f'resident-kernel-{mission}-cover'
    subprocess.run(['rm', '-rf', str(objdir)], check=True)
    objdir.mkdir(parents=True)
    kernel = f'src/{mission}_kernel.c'
    objs = []
    cflags = ['-O0', '-std=c99', '-Iinclude', '-Itests', *[f for f in flags if not f.startswith('-Wl,')]]
    for i, src in enumerate([s for s in sources if s != kernel] + ['tests/resident_kernel_trace.c']):
        o = objdir / f'{i:03d}.o'
        subprocess.run(['cc', *cflags, '-c', src, '-o', str(o)], cwd=R, check=True)
        objs.append(str(o))
    o = objdir / f'{mission}_kernel.o'
    subprocess.run(['cc', *cflags, '--coverage', '-c', kernel, '-o', str(o)], cwd=R, check=True)
    exe = objdir / 'runner'
    subprocess.run(['cc', '--coverage', *[f for f in flags if f.startswith('-Wl,')], *objs, str(o), '-o', str(exe)],
                   cwd=R, check=True)
    return objdir, exe


def main(argv):
    mission = argv[0]
    cut = argv.index('--')
    flags, sources = argv[1:cut], argv[cut + 1:]
    expected = []
    for prefix in MODULES[mission]:
        expected += vectors(prefix)
    cases = [n for n, e in enumerate(expected) if e != REFUSED]
    objdir, exe = build(mission, flags, sources)
    path = R / 'build' / f'resident-kernel-{mission}-arcs.json'
    if path.exists():
        trace = RC.load(path)
    else:
        trace = RC.trace(objdir, cases, lambda n: [str(exe), str(n)])
        RC.save(path, trace)
    picked = RC.cover(trace, budget=1024)
    RC.check(trace, picked)
    # Plus every 64th case with an oracle, for breadth beyond the arcs.
    rows = sorted(set(picked) | set(cases[::64]))
    s = RC.summary(trace, rows)
    out = R / 'tests' / f'{mission}_kernel_c64_rows.h'
    lines = ['/* SPDX-License-Identifier: MIT; generated by tools/resident_kernel_rows.py. Do not edit.',
             f' * The resident kernel\'s C64 rows: {len(picked)} of the {s["host_cases_traced"]} {mission.upper()} cases with a',
             f' * yaAGC oracle take all {s["host_branch_arcs"]} kernel branch arcs the host cases take',
             ' * (tools/c64_row_cover.py), plus every 64th such case: flat case numbers',
             ' * (services, then jobs, then idle) and their frozen yaAGC digests. */',
             f'#define RK_C64_ROWS {len(rows)}u',
             'static const uint16_t rk_c64_case[RK_C64_ROWS]={' + ','.join(map(str, rows)) + '};',
             'static const uint32_t rk_c64_digest[RK_C64_ROWS]={' + ','.join('0x%08xul' % expected[n] for n in rows) + '};']
    out.write_text('\n'.join(lines) + '\n')
    print(f'{mission}: {len(picked)} rows take all {s["host_branch_arcs"]} kernel branch arcs of {len(trace)} traced cases; '
          f'{len(rows)} C64 rows with the stride')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
