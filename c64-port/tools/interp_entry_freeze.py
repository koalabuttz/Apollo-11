"""Run the original-program oracle for interp-entry and freeze digests.

Builds the host-only yaAGC driver tools/interp_entry_reference.c, runs it
on the unmodified Luminary099 and Comanche055 ropes, checks the native
snapshot (build/interp-entry-native lm|cm) is byte-identical, and writes
tests/interp_entry_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words,
SUPERBNK and the interrupt-enable bit) and
tests/interp_entry_c64_vectors.h (every sixteenth). Also writes
build/interp-entry-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPES = {'lm': B / 'fixed-data/Luminary099/MAIN.agc.bin', 'cm': B / 'fixed-data/Comanche055/MAIN.agc.bin'}
NATIVE = ['src/interp_entry.c', 'src/agc_transfer.c', 'src/standard_lead_routines.c', 'src/standard_lead.c',
          'src/standard_lead_interp.c', 'src/standard_lead_wake.c', 'src/lm_basic_wake.c', 'src/executive.c',
          'src/cm_basic_wake.c', 'src/cm_native_image.c', 'src/cm_dispatch.c', 'tests/interp_entry_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'src/cm_executive.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16
PER = 512
ENTRIES = {'lm': ['06037 INTPRET', '06041 INTPRET +2', '06050 INTRSM'],
           'cm': ['06006 INTPRET', '06010 INTPRET +2', '06017 INTRSM']}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/interp_entry_reference.c', *CORE,
                    '-o', 'build/interp-entry-reference'], cwd=R, check=True)
    full, c64, proof = [], [], {}
    for m in ('lm', 'cm'):
        ref = subprocess.run(['./build/interp-entry-reference', str(ROPES[m]), m], cwd=R, check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/interp-entry-native', m], cwd=R, check=True, capture_output=True).stdout
        assert ref == nat, f'interp-entry {m}: native differs from the original program'
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        digests = [digest(r[1:]) for r in rows]
        name = m.upper()
        full += [f'#define IE_{name}_VECTORS {len(digests)}u', *table(f'ie_{m}_expected', digests)]
        c64 += [f'#define IE_{name}_C64_COUNT {len(digests[::STRIDE])}u', *table(f'ie_{m}_c64', digests[::STRIDE])]
        kinds = collections.Counter(f"{ENTRIES[m][r[0] // PER]}:{('returned', 'alarm', 'refused')[r[1]]}" for r in rows)
        proof[m] = {'mission': ROPES[m].parent.name, 'rope_sha256': hashlib.sha256(ROPES[m].read_bytes()).hexdigest(),
                    'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
                    'outcomes': dict(sorted(kinds.items())), 'entries': ENTRIES[m]}
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/interp_entry_freeze.py from the',
            ' * original Luminary099 and Comanche055 programs (yaAGC oracle). Per-case digests of the',
            ' * outcome kind and, unless refused, all 2048 erasable words, SUPERBNK and IRQ enable. */']
    (R / 'tests/interp_entry_vectors.h').write_text('\n'.join(head + full) + '\n')
    head = ['/* SPDX-License-Identifier: MIT; generated by tools/interp_entry_freeze.py: every',
            ' * sixteenth digest of tests/interp_entry_vectors.h, for the C64 diagnostic. */',
            f'#define IE_C64_STRIDE {STRIDE}u']
    (R / 'tests/interp_entry_c64_vectors.h').write_text('\n'.join(head + c64) + '\n')
    proof.update({'boundary': 'one entry (INTPRET, INTPRET +2 or INTRSM) to NEWOPS; the original runs to the first time Z '
                              'reaches NEWOPS',
                  'compared': 'outcome kind; all 2048 erasable words (A, L, Q 16-bit), SUPERBNK, interrupt enable',
                  'full_physical_words': 2048})
    (B / 'interp-entry-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f"PASS: {proof['lm']['cases']} LM and {proof['cm']['cases']} CM interp-entry cases equal the original programs")


if __name__ == '__main__':
    main()
