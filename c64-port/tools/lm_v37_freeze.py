"""Run the original-program oracle for lm-v37 and freeze digests.

Builds the host-only yaAGC driver (tools/lm_v37_reference.c), runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-v37-native) is byte-identical, and writes
tests/lm_v37_vectors.h (one digest per case: two 16-bit running sums
over the printed values) and the C64 rows chosen by
native branch outcome (tools/a2_c64_rows.py: a greedy cover of the gcov arcs
every host case takes in every linked source; the freeze fails unless the
rows take them all) to
tests/lm_v37_c64_vectors.h. Also writes build/lm-v37-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import a2_c64_rows  # noqa: E402

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
# The milestone's linked sources (tools/mk/lm-v37.mk LM_V37_SRC), for the row cover.
SRC = ['src/lm_v37.c', 'src/lm_fresh_start.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/lm_interbank_routines.c', 'src/lm_interbank.c', 'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c', 'tests/lm_v37_cases.c']
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
CORE = ['tests/lm_v37_cases.c', 'src/lm_v37.c', 'src/lm_fresh_start.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c',
        'src/agc_transfer.c', 'src/agc_word.c', 'src/lm_interbank_routines.c', 'src/lm_interbank.c',
        'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/lm_v37_reference.c', *CORE, '-o', 'build/lm-v37-reference'],
                   cwd=R, check=True)
    ref = subprocess.run(['./build/lm-v37-reference', str(ROPE)], cwd=R, check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-v37-native'], cwd=R, check=True, capture_output=True).stdout
    if ref != nat:
        for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
            if a != b:
                x, y = a.split(), b.split()
                diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:10]
                raise SystemExit(f'case {i}: native differs from the original program at {diff}')
        raise SystemExit('native output length differs')
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    values = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_v37_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the interrupt-enable',
           ' * state, SUPERBNK, channels 11, 5, 6, 12, 13 and 14, the trap latches and all 2048 erasable words. */',
           f'#define LM_V37_VECTORS {len(values)}u']
    table(out, 'lm_v37_expected', values)
    (R / 'tests/lm_v37_vectors.h').write_text('\n'.join(out) + '\n')
    chosen, cover = a2_c64_rows.select('lm-v37', SRC, ['lm_v37_cases.h'], 'lm_v37_digest(&s,(uint16_t)n,&st);', len(values),
                                           stride=32, slots=32)  # every 16th row would push the BSS past $c000
    (R / 'tests/lm_v37_c64_vectors.h').write_text(a2_c64_rows.header('lm_v37_freeze.py', 'lm_v37', values, chosen, 32))
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only', 'cases': len(values),
             'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'entries': 'GOP00FIX, V37, V37RET, R00, V37XEQ, V37XEQC and the return after each TC out of bank 04 (32)',
             'boundary': 'entry state to the first point neither FRESH_START_AND_RESTART (banks 04, 05, fixed-fixed) nor INTER-BANK_COMMUNICATION owns, or SWRETURN',
             'full_physical_words': 2048, **cover}
    (B / 'lm-v37-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(values)} cases equal the original program; {len(chosen)} C64 rows take all '
          f'{cover["host_branch_arcs"]} host branch arcs')


if __name__ == '__main__':
    main()
