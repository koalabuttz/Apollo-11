"""Pick the C64 rows of a milestone by outcome.

A freeze tool builds its yaAGC oracle with -DCASE_TRACE=<path>
(tools/case_trace.h), which writes, per case, the fixed words the original
program executed inside the milestone's own code. Every branch outcome of
the original lands on a word of its own, so a set of rows whose traces
together cover every word the host cases execute takes every outcome the
host takes. rows() starts from every stride-th case and adds, greedily, the
case covering the most words still missing until nothing is missing.
"""
import pathlib
import re


def read(path):
    """{case: frozenset(words)} from a CASE_TRACE file."""
    out = {}
    for line in pathlib.Path(path).read_text().splitlines():
        n, *words = map(int, line.split())
        out[n] = frozenset(words)
    return out


def rows(trace, stride):
    """Sorted case numbers: every stride-th case plus a greedy cover of the rest."""
    chosen = set(range(0, len(trace), stride))
    host = frozenset().union(*trace.values())
    covered = set().union(*(trace[n] for n in chosen))
    while covered != host:
        best = max(sorted(trace), key=lambda n: len(trace[n] - covered))
        chosen.add(best)
        covered |= trace[best]
    return sorted(chosen)


def name(w):
    """bank,address for a physical fixed word (fixed-fixed as a bare address)."""
    if 2048 <= w < 4096:
        return f'{0o4000 + w - 2048:04o}'
    return f'{w // 1024:02o},{0o2000 + w % 1024:04o}'


# Words the CPU never starts an instruction at: constants, addresses and
# interpretive words (an empty opcode column is an interpretive operand or the
# second word of a two-word constant).
DATA = {'OCT', 'DEC', '2DEC', 'CADR', '2CADR', 'FCADR', '2FCADR', 'ADRES', 'GENADR', 'ECADR', 'REMADR',
        'BBCON', '2BCADR', 'VN', 'EBANK=', 'BANK', 'SETLOC', 'CALL', 'EXIT', 'STCALL', 'RTB', 'BHIZ'}


def listing(path):
    """{physical word: [opcode, ...]} from a yaYUL assembly listing (fixed columns)."""
    out = {}
    for line in pathlib.Path(path).read_text(errors='replace').splitlines():
        m = re.match(r'\S+,\S+: (\d\d),(\d{4}) ', line) or re.match(r'\S+,\S+: ()(\d{4})  ', line)
        if not m or len(line) < 34 or not line[33:38].strip().isdigit():
            continue
        z = int(m.group(2), 8)
        w = 2048 + z - 0o4000 if not m.group(1) else int(m.group(1), 8) * 1024 + z - 0o2000
        out.setdefault(w, []).append(line[65:74].strip())
    return out


def unexecuted_instructions(lst, owned, host):
    """Owned words that hold an instruction the CPU starts at yet no host case executed.

    A word right after EXTEND or INDEX runs in the same step as its prefix, so
    the trace credits the prefix; the step's outcome still lands on its own word."""
    bad = []
    for w in sorted(set(owned) - host):
        ops = [o for o in lst.get(w, []) if o]
        if not ops or any(o in DATA for o in ops):
            continue
        if any(o in ('EXTEND', 'INDEX') for o in lst.get(w - 1, [])):
            continue
        bad.append(name(w))
    return bad


def summary(trace, chosen, owned):
    """Proof fields: words executed on the host and by the C64 rows, and the owned words never executed."""
    host = frozenset().union(*trace.values())
    c64 = frozenset().union(*(trace[n] for n in chosen))
    assert c64 == host
    return {'c64_rows': len(chosen), 'c64_row_selection': 'every stride-th case plus a greedy cover: the C64 rows execute every fixed word the host cases execute (each branch outcome lands on its own word)',
            'host_words_executed': len(host), 'c64_words_executed': len(c64),
            'owned_words_never_executed': [name(w) for w in sorted(set(owned) - host)]}


def c64_header(tool, prefix, values, chosen):
    """The C64 vector header: the chosen case numbers and their digests."""
    out = [f'/* SPDX-License-Identifier: MIT; generated by tools/{tool}_freeze.py: the',
           ' * C64 rows (tools/c64_rows.py: every 16th case plus a greedy cover of every',
           ' * word the host cases execute) and their digests from the vectors header. */',
           f'#define {prefix.upper()}_C64_COUNT {len(chosen)}u']
    out.append(f'static const uint16_t {prefix}_c64_case[{len(chosen)}]={{')
    for i in range(0, len(chosen), 12):
        out.append(''.join(f'{n}u,' for n in chosen[i:i + 12]))
    out.append('};')
    out.append(f'static const uint32_t {prefix}_c64[{len(chosen)}]={{')
    for i in range(0, len(chosen), 6):
        out.append(''.join(f'0x{values[n]:08x}ul,' for n in chosen[i:i + 6]))
    out.append('};')
    return '\n'.join(out) + '\n'
