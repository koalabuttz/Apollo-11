"""Freeze actual source outputs; all 2048 physical words remain compared."""
import hashlib
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
WORDS = 2052
CHANGED = [0, 1, 2, 3, 4, 5, 6, 83, 84, 96, 102, 103, 104, 105, 106, 107]


def main():
    original = ((ROOT / 'build/noun-reader-lm.snapshots').read_bytes() +
                (ROOT / 'build/noun-reader-cm.snapshots').read_bytes())
    native = (ROOT / 'build/noun-reader-native.snapshots').read_bytes()
    inputs = (ROOT / 'build/noun-reader-input.snapshots').read_bytes()
    assert len(original) == 58368 * WORDS * 2
    assert native == original, 'full native/source states differ'
    assert len(inputs) == len(original)
    rows = []
    for base, count in ((0, 161), (30912, 143)):
        for parameter in range(count):
            n = base + 192 * parameter + parameter % 192
            row = struct.unpack_from('<2052H', original, n * WORDS * 2)
            assert row[0:2] == (n, 1)
            before = struct.unpack_from('<2052H', inputs, n * WORDS * 2)
            assert all(row[2 + i] == before[2 + i]
                       for i in range(2048) if i not in CHANGED), ('unexpected source write', n)
            assert row[-2:] == before[-2:], ('source I/O mutation', n)
            rows.append((n, [row[2 + i] for i in CHANGED]))
    lines = ['/* SPDX-License-Identifier: MIT',
             ' * Frozen independent original-source outputs, not native results.',
             ' * Full source snapshot SHA256: ' + hashlib.sha256(original).hexdigest(),
             ' * Generated by tools/freeze_noun_reader.py. */',
             '#ifndef NOUN_READER_VECTORS_H', '#define NOUN_READER_VECTORS_H',
             '#include <stdint.h>', '#define NOUN_READER_TARGET_CASES 304u',
             '#define NOUN_READER_CHANGED_WORDS 16u',
             'static const uint16_t noun_reader_changed[16] = {' +
             ','.join(str(i) for i in CHANGED) + '};',
             'static const uint16_t noun_reader_target_ids[304] = {']
    for i in range(0, len(rows), 16):
        lines.append('    ' + ','.join(str(n) for n, _ in rows[i:i+16]) + ',')
    lines.extend(['};', 'static const uint16_t noun_reader_expected[304][16] = {'])
    for _, words in rows:
        lines.append('    {' + ','.join('0%06o' % word for word in words) + '},')
    lines.extend(['};', '#endif', ''])
    (ROOT / 'tests/noun_reader_vectors.h').write_text('\n'.join(lines))
    print('PASS: frozen 304 source states; each noun and scale pair in both missions')


if __name__ == '__main__':
    main()
