"""Run the original-program oracle for lm-p-axis and freeze digests.

Builds the host-only yaAGC driver tools/lm_p_axis_reference.c, runs it on the
unmodified Luminary099 rope, checks the native snapshot (build/lm-p-axis-native)
is byte-identical on every case the native routines accept, and writes
tests/lm_p_axis_vectors.h (one digest per case: two 16-bit running sums over
the outcome, channels 12 and 13, the interrupt-enable bit and all 2048
erasable words), then has tools/lane_f_c64_rows.py choose the C64 rows
(tests/lm_p_axis_c64_vectors.h) by outcome. Cases the native routines refuse
are left out of the comparison; their digest is of the unchanged input image,
which the host test checks. The oracle executes DV with yaAGC's register-level
SimulateDV for every dividend (tools/prepare_hardware_dv.py,
docs/GENERAL_DIVIDE.md), as ai_dv does. Writes build/lm-p-axis-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_p_axis.c', 'src/agc_fast_ops.c', 'src/agc_fast_window.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_p_axis_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(B / 'agc_engine_hardware_dv.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Itools', '-I' + str(E)]
REFUSED = 1
NAMES = ['PAXIS', '16,2223', '16,2224', 'BACKP', '16,2653', 'SUPERJOB', '16,2773', '16,3154', '16,3403', '16,3424',
         '16,3443', 'CALCPERR', '16,3500', '16,3512', '16,3550', 'BACKP']

# Destinations of the file's exits: (FB bank, Z) in switched fixed memory.
EXITS = {(0o16, 0o2000): 'CHEKBITS', (0o16, 0o3641): 'RATELOOP', (0o16, 0o3736): 'ACDT+C12',
         (0o17, 0o2072): 'CALLQERR', 0o4674: 'IBNKCALL', 0o5275: 'NOQBRSM +1', 0o5567: 'ALARM', 0o5634: 'BAILOUT',
         0o5753: 'WRITEP -1', 0o5754: 'WRITEP'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    if not (B / 'agc_engine_hardware_dv.o').exists():
        subprocess.run([sys.executable, 'tools/prepare_hardware_dv.py'], cwd=R, check=True)
    subprocess.run(['cc', *FLAGS, 'tools/lm_p_axis_reference.c', *CORE,
                    '-o', 'build/lm-p-axis-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-p-axis-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-p-axis-native'], cwd=R, check=True, capture_output=True).stdout
    rrows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    nrows = [list(map(int, line.split())) for line in nat.decode().splitlines()]
    assert [r[0] for r in rrows] == [r[0] for r in nrows] == list(range(len(nrows)))
    compared = [n for n in nrows if n[1] != REFUSED]
    for n in compared:
        assert n == rrows[n[0]], f'lm-p-axis case {n[0]}: native differs from the original program'
    refused = [n[0] for n in nrows if n[1] == REFUSED]
    digests = [digest(r[1:]) for r in nrows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_p_axis_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channels 12 and 13, the interrupt-enable bit and all 2048 erasable words',
           ' * (a refused case: its unchanged input image). */',
           f'#define LM_PA_VECTORS {len(digests)}u', *table('lm_pa_expected', digests)]
    (R / 'tests/lm_p_axis_vectors.h').write_text('\n'.join(out) + '\n')
    subprocess.run([sys.executable, 'tools/lane_f_c64_rows.py', 'lm-p-axis'], cwd=R, check=True)
    outcome = ['left the file', 'refused', 'none']
    kinds = collections.Counter(f"{NAMES[r[0] % 16]}:{outcome[r[1]]}" for r in nrows)
    oracle_refused = collections.Counter(outcome[rrows[n][1]] for n in refused)
    # Where each compared case left the file (rows are case, kind, channel
    # 12, channel 13, interrupt enable, then the image: FB is word 4, Z 5).
    exits = collections.Counter(EXITS.get((r[5 + 4] >> 10, r[5 + 5]) if r[5 + 5] < 0o4000 else r[5 + 5],
                                          "CALCPERR's return in Q") for r in compared)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(nrows), 'compared_cases': len(compared),
             'compared_sha256': hashlib.sha256('\n'.join(' '.join(map(str, n)) for n in compared).encode()).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'exits': dict(sorted(exits.items())),
             'dv': 'yaAGC SimulateDV for every dividend (tools/prepare_hardware_dv.py)',
             'refused_cases': len(refused), 'refused_oracle_outcomes': dict(sorted(oracle_refused.items())),
             'entries': ['16,2213 PAXIS', '16,2223', '16,2224', '16,2316 BACKP', '16,2653', '16,2666 SUPERJOB',
                         '16,2773', '16,3154', '16,3403', '16,3424', '16,3443', '16,3446 CALCPERR', '16,3500',
                         '16,3512', '16,3550'],
             'boundary': 'each entry from a random image (FB bank 16, EB 6, random channels 12, 13 and 31, a '
                         'random interrupt-enable bit, erasable words of random widths with +-0 frequent) until '
                         'the original leaves 16,2213-3640 (TC, TCF, DTCB or TC Q to a destination outside); '
                         'compared: outcome, channels 12 and 13, the interrupt-enable bit and all 2048 erasable '
                         'words',
             'full_physical_words': 2048}
    (B / 'lm-p-axis-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(compared)} lm-p-axis cases equal the original program '
          f'({len(refused)} refused): {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
