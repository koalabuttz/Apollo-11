"""Per-milestone evidence: SHA256 manifest in git, bulk bytes in GitHub releases.

Each milestone owns evidence/<id>/ and evidence/<id>/SHA256.json. Files are
stored either in the tree (small, reviewable text such as a proof summary, at
most 256 KiB, opt-in with --tree) or, by default, as assets of the GitHub
release `evidence-<id>`. Release-stored files stay on disk under
evidence/<id>/ but are ignored by git (evidence/<id>/.gitignore is generated).
The legacy flat evidence/ files and evidence/SHA256.json are frozen.

  evidence.py add <id> FILE... [--tree]   copy FILEs into evidence/<id>/ and record them
  evidence.py push <id>                   send release-stored files to the upload workflow
  evidence.py fetch <id>... | --coverage  download release-stored files and verify them
  evidence.py verify [<id>...] [--remote] check local bytes (and, with --remote, published assets)

`push` commits the bytes on top of HEAD to a throwaway branch
evidence-upload/<id>; .github/workflows/evidence-upload.yml publishes them as
release assets, verifies every hash and deletes the branch, so the bytes never
reach the port branch history.
"""
import argparse
import hashlib
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[1]
REPOSITORY = ROOT.parent
EVIDENCE = ROOT / 'evidence'
MANIFEST = 'SHA256.json'
TREE_LIMIT = 256 * 1024
PART = 90 * 1024 * 1024
MAX_ASSETS = 900
UPLOAD_DIR = '.evidence-upload'
ID = re.compile(r'^[a-z0-9][a-z0-9-]*$')
NAME = re.compile(r'^[A-Za-z0-9][A-Za-z0-9._-]*$')


def repo_slug():
    if os.environ.get('EVIDENCE_REPO'):
        return os.environ['EVIDENCE_REPO']
    try:
        url = subprocess.check_output(['git', 'remote', 'get-url', 'origin'], cwd=REPOSITORY,
                                      text=True, stderr=subprocess.DEVNULL).strip()
        match = re.search(r'github\.com[:/]([^/]+/[^/]+?)(?:\.git)?/?$', url)
        if match:
            return match.group(1)
    except (OSError, subprocess.CalledProcessError):
        pass
    return 'koalabuttz/Apollo-11'


def digest(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        while chunk := f.read(1 << 20):
            h.update(chunk)
    return h.hexdigest()


def asset_name(name, record):
    return f"{record['sha256'][:16]}-{name}"


def asset_url(milestone, name, record):
    return (f'https://github.com/{repo_slug()}/releases/download/'
            f'evidence-{milestone}/{asset_name(name, record)}')


def check_id(milestone):
    if not ID.match(milestone) or milestone.startswith('legacy-'):
        raise SystemExit(f'invalid milestone id: {milestone}')
    return milestone


def load(milestone):
    path = EVIDENCE / milestone / MANIFEST
    if not path.is_file():
        return {'schema_version': 1, 'milestone': milestone,
                'release': f'evidence-{milestone}', 'files': {}}
    data = json.loads(path.read_text())
    if data.get('schema_version') != 1 or data.get('milestone') != milestone:
        raise SystemExit(f'{path}: bad manifest header')
    return data


def save(data):
    folder = EVIDENCE / data['milestone']
    folder.mkdir(parents=True, exist_ok=True)
    data['files'] = dict(sorted(data['files'].items()))
    (folder / MANIFEST).write_text(json.dumps(data, indent=2) + '\n')
    released = [name for name, record in data['files'].items() if record['store'] == 'release']
    ignore = '# Generated by tools/evidence.py: these bytes live in the release, not in git.\n'
    (folder / '.gitignore').write_text(ignore + ''.join(f'/{name}\n' for name in released))


def milestones():
    return sorted(path.parent.name for path in EVIDENCE.glob(f'*/{MANIFEST}'))


def cmd_add(args):
    data = load(check_id(args.id))
    folder = EVIDENCE / args.id
    folder.mkdir(parents=True, exist_ok=True)
    for source in args.files:
        source = pathlib.Path(source)
        name = source.name
        if not NAME.match(name) or name in (MANIFEST, '.gitignore'):
            raise SystemExit(f'unsupported evidence file name: {name}')
        size = source.stat().st_size
        if args.tree and size > TREE_LIMIT:
            raise SystemExit(f'{name}: {size} bytes is over the {TREE_LIMIT}-byte in-tree limit')
        target = folder / name
        if source.resolve() != target.resolve():
            shutil.copyfile(source, target)
        data['files'][name] = {'sha256': digest(target), 'bytes': size,
                               'store': 'tree' if args.tree else 'release'}
        print(('tree   ' if args.tree else 'release'), name, size)
    if sum(r['store'] == 'release' for r in data['files'].values()) > MAX_ASSETS:
        raise SystemExit(f'over {MAX_ASSETS} release files; archive related files into one tarball')
    save(data)
    return 0


def git(*args, env=None, data=None):
    return subprocess.run(['git', *args], cwd=REPOSITORY, check=True, env=env, input=data,
                          stdout=subprocess.PIPE).stdout.decode().strip()


def cmd_push(args):
    data = load(check_id(args.id))
    released = {n: r for n, r in data['files'].items() if r['store'] == 'release'}
    if not released:
        print('nothing to upload: no release-stored files')
        return 0
    if subprocess.run(['git', 'cat-file', '-e', 'HEAD:.github/workflows/evidence-upload.yml'],
                      cwd=REPOSITORY).returncode:
        raise SystemExit('HEAD lacks .github/workflows/evidence-upload.yml; branch from the current port tip')
    with tempfile.TemporaryDirectory() as tmp:
        env = dict(os.environ, GIT_INDEX_FILE=os.path.join(tmp, 'index'))
        git('read-tree', 'HEAD', env=env)

        def stage(path, oid):
            git('update-index', '--add', '--cacheinfo', f'100644,{oid},{path}', env=env)

        stage(f'{UPLOAD_DIR}/manifest.json',
              git('hash-object', '-w', '--stdin', data=json.dumps(data, indent=2).encode()))
        for name, record in released.items():
            path = EVIDENCE / args.id / name
            if not path.is_file() or digest(path) != record['sha256']:
                raise SystemExit(f'{path} is missing or does not match the manifest')
            with open(path, 'rb') as f:
                index = 0
                while chunk := f.read(PART):
                    stage(f'{UPLOAD_DIR}/{name}.part{index:03d}', git('hash-object', '-w', '--stdin', data=chunk))
                    index += 1
                if index == 0:
                    stage(f'{UPLOAD_DIR}/{name}.part000', git('hash-object', '-w', '--stdin', data=b''))
        tree = git('write-tree', env=env)
    commit = git('commit-tree', tree, '-p', 'HEAD', '-m', f'Evidence upload for {args.id}')
    ref = f'refs/heads/evidence-upload/{args.id}'
    subprocess.run(['git', 'push', '--force', 'origin', f'{commit}:{ref}'], cwd=REPOSITORY, check=True)
    print(f'PUSHED {len(released)} files to {ref}; the evidence-upload workflow publishes '
          f'release evidence-{args.id}. Check with: tools/evidence.py verify {args.id} --remote')
    return 0


def download(url, target, record):
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=target.parent, prefix='.download-')
    try:
        with os.fdopen(fd, 'wb') as out, urllib.request.urlopen(url, timeout=120) as response:
            shutil.copyfileobj(response, out, 1 << 20)
        if digest(tmp) != record['sha256']:
            raise SystemExit(f'{url}: SHA256 mismatch')
        os.replace(tmp, target)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


def coverage_paths():
    paths = set()

    def walk(node):
        if isinstance(node, dict):
            if isinstance(node.get('path'), str) and node['path'].startswith('evidence/'):
                paths.add(node['path'])
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    walk(json.loads((ROOT / 'docs/port-coverage.json').read_text()))
    return paths


def cmd_fetch(args):
    wanted = {}
    for milestone in args.ids:
        wanted[milestone] = set(load(milestone)['files'])
    if args.coverage:
        for path in coverage_paths():
            parts = pathlib.PurePosixPath(path).parts
            if len(parts) == 3 and (EVIDENCE / parts[1] / MANIFEST).is_file():
                wanted.setdefault(parts[1], set()).add(parts[2])
    count = 0
    if args.coverage:
        # Legacy certificates cite flat evidence that lean checkouts may skip.
        for path in sorted(coverage_paths()):
            if path.count('/') == 1 and not (ROOT / path).exists():
                blob = subprocess.run(['git', 'cat-file', 'blob', f'HEAD:c64-port/{path}'], cwd=REPOSITORY,
                                      stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
                if blob.returncode == 0:
                    (ROOT / path).write_bytes(blob.stdout)
                    count += 1
    for milestone, names in sorted(wanted.items()):
        data = load(milestone)
        for name in sorted(names):
            record = data['files'].get(name)
            if record is None or record['store'] != 'release':
                continue
            target = EVIDENCE / milestone / name
            if target.is_file() and digest(target) == record['sha256']:
                continue
            download(asset_url(milestone, name, record), target, record)
            count += 1
    print(f'PASS: fetched {count} release evidence files')
    return 0


def remote_exists(url):
    request = urllib.request.Request(url, method='HEAD')
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.status == 200
    except urllib.error.HTTPError:
        return False


def cmd_verify(args):
    errors = []
    ids = args.ids or milestones()
    for milestone in ids:
        data = load(milestone)
        folder = EVIDENCE / milestone
        for name, record in data['files'].items():
            path = folder / name
            if record.get('store') not in ('tree', 'release') or not NAME.match(name):
                errors.append(f'{milestone}/{name}: bad record')
                continue
            if record['store'] == 'tree' or path.is_file():
                if not path.is_file():
                    errors.append(f'{milestone}/{name}: missing in-tree file')
                elif digest(path) != record['sha256'] or path.stat().st_size != record['bytes']:
                    errors.append(f'{milestone}/{name}: SHA256/size mismatch')
            if record['store'] == 'tree' and record['bytes'] > TREE_LIMIT:
                errors.append(f'{milestone}/{name}: in-tree file over {TREE_LIMIT} bytes')
            if record['store'] == 'release' and args.remote and \
                    not remote_exists(asset_url(milestone, name, record)):
                errors.append(f'{milestone}/{name}: release asset not published '
                              f'(run tools/evidence.py push {milestone})')
        listed = set(data['files']) | {MANIFEST, '.gitignore'}
        for path in folder.iterdir():
            if path.is_file() and path.name not in listed and not path.name.startswith('.download-'):
                errors.append(f'{milestone}/{path.name}: file not in the manifest')
    for error in errors:
        print('FAIL:', error, file=sys.stderr)
    if not errors:
        print(f'PASS: {len(ids)} milestone evidence manifests' + (' (assets published)' if args.remote else ''))
    return 1 if errors else 0


def cmd_publish_upload(args):
    """Run by .github/workflows/evidence-upload.yml on an evidence-upload/<id> push."""
    folder = pathlib.Path(args.folder)
    data = json.loads((folder / 'manifest.json').read_text())
    milestone = check_id(data['milestone'])
    tag = f'evidence-{milestone}'
    if subprocess.run(['gh', 'release', 'view', tag], stdout=subprocess.DEVNULL,
                      stderr=subprocess.DEVNULL).returncode:
        subprocess.run(['gh', 'release', 'create', tag, '--target', args.target, '--title', tag,
                        '--notes', f'Evidence for port milestone `{milestone}`. '
                        'Hashes: c64-port/evidence/' + milestone + '/SHA256.json'], check=True)
    existing = set(subprocess.check_output(
        ['gh', 'release', 'view', tag, '--json', 'assets', '--jq', '.assets[].name'],
        text=True).split())
    with tempfile.TemporaryDirectory() as tmp:
        for name, record in data['files'].items():
            if record['store'] != 'release' or asset_name(name, record) in existing:
                continue
            target = pathlib.Path(tmp) / asset_name(name, record)
            with open(target, 'wb') as out:
                for part in sorted(folder.glob(f'{name}.part[0-9][0-9][0-9]')):
                    out.write(part.read_bytes())
            if digest(target) != record['sha256'] or target.stat().st_size != record['bytes']:
                raise SystemExit(f'{name}: uploaded bytes do not match the manifest')
            subprocess.run(['gh', 'release', 'upload', tag, str(target)], check=True)
            target.unlink()
            print('uploaded', name)
    print('PASS: release', tag, 'holds every release-stored file')
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest='command', required=True)
    p = sub.add_parser('add')
    p.add_argument('id')
    p.add_argument('files', nargs='+')
    p.add_argument('--tree', action='store_true', help='keep these small files in git')
    p.set_defaults(func=cmd_add)
    p = sub.add_parser('push')
    p.add_argument('id')
    p.set_defaults(func=cmd_push)
    p = sub.add_parser('fetch')
    p.add_argument('ids', nargs='*')
    p.add_argument('--coverage', action='store_true',
                   help='also fetch release evidence cited by docs/port-coverage.json')
    p.set_defaults(func=cmd_fetch)
    p = sub.add_parser('verify')
    p.add_argument('ids', nargs='*')
    p.add_argument('--remote', action='store_true')
    p.set_defaults(func=cmd_verify)
    p = sub.add_parser('publish-upload')
    p.add_argument('folder')
    p.add_argument('--target', required=True)
    p.set_defaults(func=cmd_publish_upload)
    args = parser.parse_args()
    return args.func(args)


if __name__ == '__main__':
    sys.exit(main())
