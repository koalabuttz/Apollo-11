"""Run the original-program oracle for lm-ags-init and freeze digests.

Builds the host-only yaAGC driver tools/lm_ags_init_reference.c (on yaAGC
with the hardware divide, build/agc_engine_hardware_dv.o), runs it on the
unmodified Luminary099 rope, and checks every case the native snapshot
(build/lm-ags-init-native) runs is byte-identical to it; a case the native
routine refuses must leave its image unchanged. Writes
tests/lm_ags_init_vectors.h (one digest per case: two 16-bit running sums
over the kind and, unless refused, all 2048 erasable words and the
interrupt-enable state), tests/lm_ags_init_c64_vectors.h (the C64 rows,
chosen by outcome by tools/lane_f_c64_rows.py) and
build/lm-ags-init-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import re
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_ags_init.c', 'src/lm_interp_orders.c', 'src/lm_interp_steps.c', 'src/agc_image_ops.c',
          'src/agc_hardware_divide.c', 'src/agc_transfer.c', 'src/agc_word.c', 'src/agc_multiword.c',
          'tests/lm_ags_init_cases.c']
CORE = NATIVE + ['tests/cm_executive_cases.c', str(B / 'agc_engine_hardware_dv.o'),
                 str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Isrc', '-Itools', '-I' + str(E)]
REFUSED = 2
STOPS = {0o5567: 'ALARM', 0o5472: 'ENDEXT', 0o5516: 'DOWNFLAG', 0o4616: 'BANKCALL', 0o5126: 'CHANG2',
         0o6070: 'NEWOPS outside the file (LEMPREC, CSMPREC, a caller of SCALEVEC)', 0o220: 'TC 00220',
         0o3573: 'RTB LOADTIME', 0o3772: 'RTB VECSGNAG'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def keys():
    src = (R / 'src/lm_ags_init.c').read_text()
    body = re.search(r'ags_routine_keys\[AGS_ROUTINES\]=\{(.*?)\};', src, re.S).group(1)
    return ['32,' + a[1:] for a in re.findall(r'B32\((0[0-7]+)\)', body)]


def main():
    if not (B / 'agc_engine_hardware_dv.o').exists():
        subprocess.run([sys.executable, 'tools/prepare_hardware_dv.py'], cwd=R, check=True)
    subprocess.run(['cc', *FLAGS, '-w', 'tools/lm_ags_init_reference.c', *CORE,
                    '-o', 'build/lm-ags-init-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-ags-init-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout.decode().splitlines()
    nat = subprocess.run(['./build/lm-ags-init-native'], cwd=R, check=True,
                         capture_output=True).stdout.decode().splitlines()
    names = keys()
    assert len(ref) == len(nat) and len(ref) % len(names) == 0
    rows, refused, stops = [], collections.Counter(), collections.defaultdict(collections.Counter)
    for i, (a, b) in enumerate(zip(nat, ref)):
        r = list(map(int, a.split()))
        assert r[0] == i
        key = names[i % len(names)]
        if r[1] == REFUSED:
            refused[key] += 1
        else:
            assert a == b, f'lm-ags-init case {i} ({key}): native differs from the original program'
            z = r[2 + 5]
            stops[key][STOPS.get(z, f'Z {z:05o}')] += 1
        rows.append(r)
    digests = [digest(r[1:2] if r[1] == REFUSED else r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_ags_init_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the kind and, unless',
           ' * refused, all 2048 erasable words and the interrupt-enable state. */',
           f'#define AGS_VECTORS {len(digests)}u', *table('ags_expected', digests)]
    (R / 'tests/lm_ags_init_vectors.h').write_text('\n'.join(out) + '\n')
    subprocess.run([sys.executable, 'tools/lane_f_c64_rows.py', 'lm-ags-init'], cwd=R, check=True)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle_engine': 'yaAGC with the hardware divide (build/agc_engine_hardware_dv.o); scalers frozen',
             'cases': len(rows), 'compared': len(rows) - sum(refused.values()),
             'refused': dict(sorted(refused.items())),
             'snapshot_sha256': hashlib.sha256('\n'.join(nat).encode()).hexdigest(),
             'stops': {k: dict(sorted(v.items())) for k, v in sorted(stops.items())},
             'boundary': 'from each routine key to the first instruction outside AGS_INITIALIZATION, the '
                         'interpreter and SWCALL (ags_leaves)',
             'compared_words': '2048 erasable words (A, L 16-bit) and the interrupt-enable state'}
    (B / 'lm-ags-init-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {proof["compared"]} of {len(rows)} lm-ags-init cases equal the original program '
          f'({len(rows) - proof["compared"]} refused)')


if __name__ == '__main__':
    main()
