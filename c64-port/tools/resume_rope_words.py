"""Fixed words for the RESUME rope-reader cases (#198): sixteen ZRUPT-1
addresses per mission, eight in banks 030-033 (SUPERBNK 0060) and eight in
040-043 (SUPERBNK 0100), with the original rope's words there. Writes
tests/resume_rope_words.h, which lm-t6rupt and rupt-lead-ins cases read
through the program's fixed_data, as the resident kernel does. An includer
defines RESUME_ROPE_LM or RESUME_ROPE_CM for its mission's table.

  python3 tools/resume_rope_words.py [--check]
"""
import pathlib
import sys

R = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(R / 'tools'))
from fixed_data_generate import rope_word  # noqa: E402

OUT = R / 'tests/resume_rope_words.h'


def addresses(seed):
    """Deterministic offsets 0..01776 (so ZRUPT stays in 02001..03777)."""
    x, out = seed, []
    for k in range(16):
        x = (x * 1103515245 + 12345) & 0xffffffff
        bank = (0o30 if k < 8 else 0o40) + k % 4
        out.append(bank * 1024 + (x >> 8) % 0o1777)
    return out


def render():
    lines = ['/* SPDX-License-Identifier: MIT; generated by tools/resume_rope_words.py from the original ropes:',
             ' * ZRUPT-1 words in banks 030-033 and 040-043 for the RESUME rope-reader cases (#198). */',
             '#define RESUME_ROPE_WORDS 16u']
    for name, mission, seed in (('lm', 'Luminary099', 0x5e5e), ('cm', 'Comanche055', 0xc0c0)):
        rope = (R / 'build/fixed-data' / mission / 'MAIN.agc.bin').read_bytes()
        phys = addresses(seed)
        lines.append(f'#ifdef RESUME_ROPE_{name.upper()}')
        lines.append(f'static const uint16_t {name}_resume_rope_physical[16]={{' +
                     ','.join(f'{p}u' for p in phys) + '};')
        lines.append(f'static const uint16_t {name}_resume_rope_word[16]={{' +
                     ','.join(f'0{rope_word(rope, p):05o}u' for p in phys) + '};')
        lines.append('#endif')
    return '\n'.join(lines) + '\n'


def main():
    text = render()
    if '--check' in sys.argv[1:]:
        if OUT.read_text() != text:
            sys.exit(f'{OUT.relative_to(R)} is stale; run tools/resume_rope_words.py')
        return
    OUT.write_text(text)
    print(f'wrote {OUT.relative_to(R)}')


if __name__ == '__main__':
    main()
