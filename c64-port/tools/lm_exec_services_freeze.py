"""Run the original-program oracle for lm-exec-services and freeze digests.

Builds the host-only yaAGC driver tools/lm_exec_services_reference.c, runs it
on the unmodified Luminary099 rope, checks the native snapshot
(build/lm-exec-services-native) is byte-identical, and writes
tests/lm_exec_services_vectors.h (one digest per case: two 16-bit running sums
over the outcome kind and, unless refused, all 2048 erasable words) and
tests/lm_exec_services_c64_vectors.h (every sixteenth). Also writes
build/lm-exec-services-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_exec_routines.c', 'src/lm_admission_image.c', 'src/lm_waitlist_image.c', 'src/waitlist.c',
          'src/executive.c', 'src/p66_native.c', 'src/lm_restart_select.c', 'src/lm_restart_routines.c',
          'src/agc_transfer.c', 'src/agc_multiword.c', 'tests/lm_restart_select_cases.c',
          'tests/lm_restart_routines_cases.c', 'tests/lm_exec_services_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-I' + str(E)]
STRIDE = 16


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    subprocess.run(['cc', *FLAGS, 'tools/lm_exec_services_reference.c', *CORE,
                    '-o', 'build/lm-exec-services-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-exec-services-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-exec-services-native'], cwd=R, check=True, capture_output=True).stdout
    assert ref == nat, 'lm-exec-services: native differs from the original program'
    rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    assert [r[0] for r in rows] == list(range(len(rows)))
    digests = [digest(r[1:]) for r in rows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_services_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind and, unless refused, all 2048 erasable words. */',
           f'#define LM_EXS_VECTORS {len(digests)}u', *table('lm_exs_expected', digests)]
    (R / 'tests/lm_exec_services_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = digests[::STRIDE]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_exec_services_freeze.py: every',
           ' * sixteenth digest of tests/lm_exec_services_vectors.h, for the C64 diagnostic. */',
           f'#define LM_EXS_C64_STRIDE {STRIDE}u', f'#define LM_EXS_C64_COUNT {len(c64)}u',
           *table('lm_exs_c64', c64)]
    (R / 'tests/lm_exec_services_c64_vectors.h').write_text('\n'.join(out) + '\n')
    kinds = collections.Counter()
    for r in rows:
        cohort = 'restart' if r[0] < 4096 else 'site' if r[0] < 8184 else 'task'
        kinds[f"{cohort}:{('returned', 'alarm', 'refused')[r[1]]}"] += 1
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'cases': len(rows), 'snapshot_sha256': hashlib.sha256(ref).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'entries': ['05072 NOVAC', '05105 FINDVAC', '05173 TWIDDLE', '05203 WAITLIST', '05277 LONGCALL',
                         '01,3452 LNGCALL2', '01,3466 LONGCYCL', '01,3506 LONGRTRN', '01,3515 TCF LONGRTRN',
                         '01,3516 GETCADR'],
             'boundary': 'restart: RESTARTS to SWRETURN through the selected services; site: every genuine '
                         'call site to the caller return; task: LONGCYCL to TASKOVER, GETCADR to the task; '
                         'alarm: BAILOUT1/POODOO1 entry; refused: LONGCYCL reaching the constant DPBIT14',
             'full_physical_words': 2048}
    (B / 'lm-exec-services-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(rows)} lm-exec-services cases equal the original program: {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
