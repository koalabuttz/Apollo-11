"""Freeze the yaAGC results of tests/resident_cdu_cases.c.

Builds tools/resident_cdu_reference.c against Virtual AGC
(deps/virtualagc/yaAGC), runs it on the unmodified LM rope (the drive does
not depend on the rope) and writes tests/resident_cdu_vectors.h: one digest
per block of 64 periods. Host only; needs the yaAGC objects.
"""
from pathlib import Path
import subprocess

BLOCK = 64
ROOT = Path(__file__).resolve().parents[1]
E = ROOT / 'deps/virtualagc/yaAGC'
EXE = ROOT / 'build/resident-cdu-reference'


def mix(h, v):
    h = ((h ^ (v & 0xff)) * 16777619) & 0xffffffff
    return ((h ^ (v >> 8)) * 16777619) & 0xffffffff


def main():
    EXE.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', f'-I{E}', 'tools/resident_cdu_reference.c',
                    'tests/resident_cdu_cases.c', E / 'agc_engine.o', E / 'agc_engine_init.o', E / 'rfopen.o',
                    '-o', EXE], cwd=ROOT, check=True)
    out = subprocess.run([EXE, 'evidence/fixed-data-lm-original.rope.bin'], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout.split('\n')
    digests = [int(line.split()[2], 16) for line in out if line.startswith('C ')]
    blocks = []
    for i in range(0, len(digests), BLOCK):
        h = 2166136261
        for d in digests[i:i + BLOCK]:
            h = mix(mix(h, d & 0xffff), d >> 16)
        blocks.append(f'0x{h:08x}u')
    text = ['/* SPDX-License-Identifier: MIT\n * GENERATED by tools/resident_cdu_vectors.py from yaAGC'
            ' (tools/resident_cdu_reference.c). */\n',
            '#ifndef RESIDENT_CDU_VECTORS_H\n#define RESIDENT_CDU_VECTORS_H\n#include <stdint.h>\n'
            '#include "resident_cdu_cases.h"\n',
            'static const uint32_t rc_vectors[RC_PERIODS / RC_BLOCK] = {\n']
    for i in range(0, len(blocks), 8):
        text.append(' ' + ', '.join(blocks[i:i + 8]) + ',\n')
    text.append('};\n#endif\n')
    (ROOT / 'tests/resident_cdu_vectors.h').write_text(''.join(text))
    print(f'wrote tests/resident_cdu_vectors.h ({len(digests)} periods, {len(blocks)} blocks)')


if __name__ == '__main__':
    main()
