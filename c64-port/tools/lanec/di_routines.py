#!/usr/bin/env python3
# SPDX-License-Identifier: MIT
"""Routine tables of the DISPLAY_INTERFACE_ROUTINES modules for the native
control-transfer ABI (docs/NATIVE_TRANSFER_ABI.md).

  python3 tools/lanec/di_routines.py [--check]

Each table entry is a point (bank, Z) at which a Lane C display-interface
suite enters its native module and whose results match the unchanged
original program (tools/lanec/diff.py): build/lanec-native --entries lists
the points each suite's accepted cases start at. A point claimed by two
modules is an error. Writes (or with --check compares) src/lanec_di_routines.inc,
sorted by physical address (agc_fixed_physical) as the trampoline requires.

It also writes tests/lanec_di_transfer_cases.inc, the round-trip cases of
the di-transfer suite: every genuine BANKCALL/IBNKCALL/POSTJUMP site
(src/{lm,cm}_interbank_sites.inc) whose CADR names a registered point, each
with up to CASES_PER_SITE accepted cases of that point's suite (spread over
the suite's cases) whose state the round trip starts from.

It checks the tables against each mission's listing: every labelled
instruction of the file is registered, except internal subroutines that no
other source file names (they are reached only by a TC inside the file and
compiled into their callers), and so is every word where an external callee
returns into the file (the word after a TC/TCR to a label outside the file,
past its inline operands; ENDOFJOB never returns).
"""
import pathlib, re, subprocess, sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import wholefile  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/lanec_di_routines.inc'
CASES = ROOT / 'tests/lanec_di_transfer_cases.inc'
CASES_PER_SITE = 4
MODULES = ('dsp', 'mark', 'play', 'sleep', 'idle', 'nvdsp')


def physical(bank, z):
    return 2048 + z - 0o4000 if z >= 0o4000 else bank * 1024 + z - 0o2000


def main():
    subprocess.run(['make', '-s', 'SKIP_EVIDENCE_RESTORE=1', 'build/lanec-native'], cwd=ROOT, check=True)
    points = {'LM': {}, 'CM': {}}
    accepted = {'LM': {}, 'CM': {}}
    for mod in MODULES:
        out = subprocess.run(['build/lanec-native', '--entries', f'di-{mod}'], cwd=ROOT, check=True,
                             capture_output=True, text=True).stdout
        for line in out.split('\n'):
            if not line:
                continue
            mission, bank, z, n = line.split()
            bank, z = int(bank, 8), int(z, 8)
            if z < 0o2000:
                sys.exit(f'FAIL: {mission} di-{mod} entry {z:o} is not in fixed memory')
            key = physical(bank, z)
            if points[mission].setdefault(key, (mod, bank, z))[0] != mod:
                sys.exit(f'FAIL: {mission} {bank:o},{z:04o} is claimed by di-{points[mission][key][0]} and di-{mod}')
            accepted[mission].setdefault(key, []).append(int(n))
    for mission in ('LM', 'CM'):
        check_listing(mission, points[mission])
    text = ['/* SPDX-License-Identifier: MIT */',
            '/* Generated by tools/lanec/di_routines.py: every point at which a Lane C',
            ' * DISPLAY_INTERFACE_ROUTINES suite enters its native module, keyed by',
            ' * physical address and sorted. Do not edit. */']
    for mission in ('LM', 'CM'):
        rows = sorted(points[mission].items())
        ml = mission.lower()
        text.append(f'#define LANEC_DI_{mission}_ROUTINES {len(rows)}u')
        text.append(f'static const agc_routine_entry {ml}_entries[LANEC_DI_{mission}_ROUTINES] = {{')
        for key, (mod, bank, z) in rows:
            where = f'{bank:02o},{z:04o}' if z < 0o4000 else f'FF,{z:04o}'
            text.append(f'    {{ {key}u, {mod}_{ml} }},   /* {where} */')
        text.append('};')
        # the same points, one table per module (a program may register a subset)
        for mod in MODULES:
            mine = [(key, z) for key, (m, _, z) in rows if m == mod]
            text.append(f'static const agc_routine_entry {ml}_{mod}_entries[{len(mine)}] = {{ '
                        + ', '.join(f'{{ {key}u, {mod}_{ml} }}' for key, _ in mine) + ' };')
        for mod in MODULES:
            text.append(f'const agc_routine_table lanec_di_{ml}_{mod} = {{ {ml}_{mod}_entries, '
                        f'{sum(1 for m in rows if m[1][0] == mod)}u }};')
    text = '\n'.join(text) + '\n'
    cases = transfer_cases(points, accepted)
    stale = [p for p, body in ((OUT, text), (CASES, cases)) if not p.exists() or p.read_text() != body]
    if '--check' in sys.argv:
        if stale:
            sys.exit(f'FAIL: {", ".join(str(p.relative_to(ROOT)) for p in stale)} stale; run tools/lanec/di_routines.py')
        print(f'PASS: {OUT.relative_to(ROOT)} current ({len(points["LM"])} LM, {len(points["CM"])} CM routines), '
              f'{CASES.relative_to(ROOT)} current')
    else:
        OUT.write_text(text)
        CASES.write_text(cases)
        print(f'wrote {OUT.relative_to(ROOT)} ({len(points["LM"])} LM, {len(points["CM"])} CM routines) '
              f'and {CASES.relative_to(ROOT)}')


def check_listing(mission, points):
    wholefile.FILE = 'DISPLAY_INTERFACE_ROUTINES.agc'
    rows = wholefile.listing_words(mission)
    wholefile.original_lines(mission, rows)
    origin = ROOT.parent / wholefile.ORIGINAL[mission]
    src = (origin / wholefile.FILE).read_text(errors='replace').splitlines()
    others = '\n'.join(p.read_text(errors='replace') for p in sorted(origin.glob('*.agc')) if p.name != wholefile.FILE)
    fields = [r['text'].split('#', 1)[0].split() for r in rows]
    data = [any(f in wholefile.DATA for f in fs) for fs in fields]
    where = [physical(int(r['bank'] or '0', 8), r['addr']) for r in rows]
    labels = {fs[0] for r, fs in zip(rows, fields) if fs and not src[r['line'] - 1][:1].isspace()}
    internal, returns = [], 0
    for i, (r, fs) in enumerate(zip(rows, fields)):
        if data[i] or not fs:
            continue
        if not src[r['line'] - 1][:1].isspace() and where[i] not in points:
            if re.search(rf'(?<![\w+\-/*.]){re.escape(fs[0])}(?![\w+\-/*.])', others):
                sys.exit(f'FAIL: {mission} label {fs[0]} is named outside the file but not registered')
            internal.append(fs[0])
        if len(fs) >= 2 and fs[-2] in ('TC', 'TCR') and fs[-1] not in labels and fs[-1] not in ('Q', 'ENDOFJOB'):
            j = i + 1
            while j < len(rows) and data[j]:
                j += 1
            returns += 1
            if j < len(rows) and where[j] not in points:
                sys.exit(f'FAIL: {mission} return from {fs[-1]} at {r["bank"]},{rows[j]["addr"]:04o} not registered')
    print(f'PASS: {mission} every label registered but the internal subroutines {", ".join(internal)}; '
          f'all {returns} external-callee returns registered')


def transfer_cases(points, accepted):
    rows = []
    for mission in ('LM', 'CM'):
        inc = (ROOT / f'src/{mission.lower()}_interbank_sites.inc').read_text()
        sites = re.findall(r'\{(\d+)u,(0[0-7]+)\}, /\* (\S+) (\w+) (\w+) (.*?) <- (.*?) \*/', inc)
        callee = re.search(r'_callee\[\d+\]=\{(.*?)\};', inc, re.S).group(1).replace('\n', '').split(',')
        callee = [int(c, 8) for c in callee if c.strip()]
        if len(callee) != len(sites):
            sys.exit(f'FAIL: {mission} site table not parsed')
        for (phys, word, where, kind, form, label, source), tc in zip(sites, callee):
            word = int(word, 8)
            target = (word >> 10) * 1024 + (word & 0o1777)
            if form != 'CADR' or kind == 'USPRCADR' or word < 0o2000 or target not in points[mission]:
                continue
            mod = points[mission][target][0]
            ns = accepted[mission][target]
            pick = sorted({ns[i * len(ns) // CASES_PER_SITE] for i in range(min(CASES_PER_SITE, len(ns)))})
            for n in pick:
                rows.append(f'    {{ {int(phys)}u, 0{tc:o}u, {n}u, {MODULES.index(mod)}u, LANEC_{mission} }},'
                            f'   /* {where} {kind} {label.split()[0]} <- {source.split(":")[0]} */')
    c64 = [r for r in rows if r.split(', ')[3] == f'{MODULES.index("dsp")}u' and 'LANEC_LM' in r]
    return '\n'.join(['/* SPDX-License-Identifier: MIT */',
                      '/* Generated by tools/lanec/di_routines.py: di-transfer round-trip cases',
                      ' * (site physical address, its TC target, case of the target\'s suite, suite',
                      ' * index in MODULES order, mission). Do not edit. */',
                      f'#define LANEC_DI_TRANSFER_CASES {len(rows)}u',
                      '#ifndef LANEC_DI_TRANSFER_C64',
                      'static const transfer_case cases[LANEC_DI_TRANSFER_CASES] = {'] + rows + ['};', '#endif',
                      '/* di-transfer-c64: the Luminary099 cases whose destination is a display-start',
                      ' * entry (lanec_di_dsp). */',
                      f'#define LANEC_DI_TRANSFER_C64_CASES {len(c64)}u',
                      'static const transfer_case c64_cases[LANEC_DI_TRANSFER_C64_CASES] = {'] + c64 + ['};']) + '\n'


if __name__ == '__main__':
    main()
