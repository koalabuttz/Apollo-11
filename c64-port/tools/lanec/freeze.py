"""Freeze every STRIDE-th case of a suite's oracle results as {case, CRC-32} pairs for the C64 diagnostic (same hash as tests/lanec_case.c).

  python3 tools/lanec/freeze.py SUITE STRIDE   # after tools/lanec/diff.py SUITE

Pick STRIDE coprime with twice the suite's entry count, so the frozen subset
reaches every entry in both missions (case n uses entry n % ENTRIES and
mission (n / ENTRIES) % 2 in the Lane C suites).

A case the native routine refused (diff.py --refusals) is frozen from the
native row instead: the unchanged entry state with status 1.
"""
import pathlib, sys, zlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
suite, stride = sys.argv[1], int(sys.argv[2])
rows = (ROOT / f'build/lanec-{suite}-oracle.txt').read_bytes().splitlines()
native = (ROOT / f'build/lanec-{suite}-native.txt').read_bytes().splitlines()
out = []
for row, mine in list(zip(rows, native))[::stride]:
    if mine.split()[-1] == b'1':
        row = mine
    v = [int(x) for x in row.split()]
    h = zlib.crc32(b''.join(x.to_bytes(2, 'little') for x in v[1:]))
    out.append(f'    {{{v[0]}u, 0x{h:08x}u}},')
name = suite.replace('-', '_')
text = '\n'.join([
    '/* SPDX-License-Identifier: MIT */',
    f'/* Generated by tools/lanec/freeze.py {suite} {stride}: Virtual AGC oracle result hashes (refusals: the unchanged state). */',
    f'static const struct {{ uint32_t n, hash; }} lanec_frozen[] = {{', *out, '};', ''])
(ROOT / f'tests/lanec_{name}_c64.h').write_text(text)
print(f'wrote tests/lanec_{name}_c64.h with {len(out)} cases')
