#!/usr/bin/env python3
"""Freeze lossless bounded complete arithmetic states after oracle equality."""
import hashlib,pathlib
from frozen_words import encode_rows,c_header
root=pathlib.Path(__file__).resolve().parents[1]
data=(root/'build/dp-divide-reference.snapshots').read_bytes()
assert data==(root/'build/dp-divide-native.snapshots').read_bytes()
rows=[list(map(int,l.split())) for l in data.decode().splitlines()]
assert len(rows)==163840 and all(len(r)==19 for r in rows)
indices=sorted(set(list(range(64))+[31*i for i in range(256)]+[32768+511*i for i in range(256)]))
packed=encode_rows([rows[i][1:] for i in indices])
s='/* SPDX-License-Identifier: MIT\n * Generated by tools/freeze_dp_divide.py from unchanged historical assembly\n * with pinned hardware DV. Full snapshot SHA256: '+hashlib.sha256(data).hexdigest()+'\n */\n'
s+='#ifndef DP_DIVIDE_VECTORS_H\n#define DP_DIVIDE_VECTORS_H\n'+c_header(packed,'dp_divide')
s+='\n#ifdef DP_DIVIDE_FROZEN_IMPLEMENTATION\nconst uint32_t dp_divide_reference_cases[DP_DIVIDE_FROZEN_ROWS]={\n'
for i in range(0,len(indices),16): s+='    '+','.join(str(n)+'u' for n in indices[i:i+16])+',\n'
s+='};\n#else\nextern const uint32_t dp_divide_reference_cases[DP_DIVIDE_FROZEN_ROWS];\n#endif\n#endif\n'
(root/'tests/dp_divide_vectors.h').write_text(s)
print(f'Frozen {len(indices)} DDV/BDDV states, 18 words including path; {packed.storage_bytes} packed bytes + {len(indices)*4} case-index bytes')
