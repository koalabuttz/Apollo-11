"""Build the native x86_64 flight program (docs/X86-FLIGHT.md): for each
mission, platform/x86/flight_main.c and flight_dispatch.c over every lane's
routine tables (tools/flight_store_build.py --host-only:
build/flight-store/<m>-host.inc, <m>-sites.inc and the host objects), with
the routine costs of docs/flight-routine-mct.json (tools/x86_flight_mct.py). One binary per mission and
interpretive mode: build/x86-flight/x86-flight-<m> (compiled interpretive
routines, the interpreter core where none holds a point) and
x86-flight-<m>-core (the core runs all interpretive code).

Each table is marked complete, uncertified or shared code
(build/x86-flight/<m>-status.inc, from docs/port-coverage.json);
--certified-only (X86_CERTIFIED_ONLY) links no uncertified table.

  x86_flight_build.py [--host-cc CC] [--skip-index] [--missions lm,cm] [--modes compiled,core] [--certified-only]
"""
import argparse, json, os, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORE = ROOT / 'build/flight-store'
OUT = ROOT / 'build/x86-flight'
MCT = ROOT / 'docs/flight-routine-mct.json'
MODES = {'compiled': ('FD_INTERP_COMPILED', ''), 'core': ('FD_INTERP_CORE', '-core')}


def mct_table(m):
    """build/x86-flight/<m>_mct.inc from docs/flight-routine-mct.json."""
    d = json.loads(MCT.read_text())[m]
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f'{m}_mct.inc'
    text = (f'/* Generated by tools/x86_flight_build.py from docs/flight-routine-mct.json. */\n'
            f'#define FD_MCT_BASIC {d["default"]["basic"]}.0\n#define FD_MCT_INTERP {d["default"]["interp"]}.0\n'
            'static const fd_cost_entry fd_mct[]={\n' + ''.join(f'{{{k}u,{i}u,{c}u}},\n' for i, k, c, *_ in d['points']) + '};\n')
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def table_status(m):
    """build/x86-flight/<m>-status.inc: each table's certification, by the
    files of docs/port-coverage.json whose native_files list the source that
    defines it: 'c' when one of them is complete, 'u' when none is,
    'x' when no file lists the source (shared support code)."""
    owners = {}
    for f in json.loads((ROOT / 'docs/port-coverage.json').read_text())['files']:
        for nc in f.get('native_coverage') or []:
            for nf in nc.get('native_files', []):
                owners.setdefault(nf, set()).add(f['status'])
    defined = {}
    for o in sorted((STORE / 'host').glob('*.o')):
        out = subprocess.run(['nm', '--defined-only', str(o)], capture_output=True, text=True, check=True).stdout
        for line in out.splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] in 'DR':
                defined.setdefault(parts[2], f'src/{o.stem}.c')
    names = re.findall(r'^FLIGHT_TABLE\((\w+),', (STORE / f'{m}-host.inc').read_text(), re.M)
    rows = []
    for n in names:
        st = owners.get(defined.get(n, ''), set())
        rows.append((n, 'x' if not st else 'c' if 'complete' in st else 'u', defined.get(n, '?')))
    path = OUT / f'{m}-status.inc'
    text = ('/* Generated by tools/x86_flight_build.py: each table\'s certification (c complete, u not yet, '
            'x shared code no file lists), from docs/port-coverage.json. */\n'
            + ''.join(f'{{"{n}",\'{k}\'}}, /* {src} */\n' for n, k, src in rows))
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


# Every link of platform/x86/flight_dispatch.c: lmi_goto_any's exit(3) on
# an erasable CADR cycle becomes a stuck step (flight_dispatch.c, fd_cycle).
LINK = ['-Wl,--wrap=exit']


def flags(m, define, certified_only=False):
    """The compile flags of the x86 program's sources for mission m."""
    mct_table(m)
    table_status(m)
    return ['-std=c99', '-O2', '-g', '-Wall', '-Wextra', '-Werror', '-Iinclude', '-Itests', '-Iplatform/x86',
            f'-DRK_{m.upper()}=1', f'-DX86_INTERP_MODE={define}',
            f'-DFLIGHT_HOST_TABLES="{STORE / f"{m}-host.inc"}"', f'-DFLIGHT_HOST_SITES="{STORE / f"{m}-sites.inc"}"',
            f'-DFLIGHT_MCT="{OUT / f"{m}_mct.inc"}"', f'-DFLIGHT_STATUS="{OUT / f"{m}-status.inc"}"',
            '-D_POSIX_C_SOURCE=199309L'] + (['-DX86_CERTIFIED_ONLY=1'] if certified_only else [])


def build(cc, m, mode, certified_only=False):
    define, suffix = MODES[mode]
    suffix += '-certified' if certified_only else ''
    flags_ = flags(m, define, certified_only)
    objs = []
    # Each file is written under a per-process name and renamed into place,
    # so a check running the binary never sees a half-written one (#1034).
    tmp = f'.{os.getpid()}.tmp'
    for src in ('flight_dispatch', 'flight_main'):
        o = OUT / f'{src}_{m}{suffix}.o'
        subprocess.run([cc, *flags_, '-c', f'platform/x86/{src}.c', '-o', str(o) + tmp], cwd=ROOT, check=True)
        os.replace(str(o) + tmp, o)
        objs.append(str(o))
    exe = OUT / f'x86-flight-{m}{suffix}'
    host = sorted(str(p) for p in (STORE / 'host').glob('*.o'))
    subprocess.run([cc, *objs, *host, *LINK, '-Wl,--gc-sections', '-lm', '-o', str(exe) + tmp], cwd=ROOT, check=True)
    os.replace(str(exe) + tmp, exe)
    return exe


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--host-cc', default=os.environ.get('CC', 'cc'))
    p.add_argument('--skip-index', action='store_true', help='reuse build/flight-store/<m>-host.inc and host objects')
    p.add_argument('--missions', default='lm,cm')
    p.add_argument('--modes', default='compiled,core')
    p.add_argument('--certified-only', action='store_true',
                   help='X86_CERTIFIED_ONLY: link no table of a file that is not complete (binaries named -certified)')
    a = p.parse_args()
    if not a.skip_index:
        subprocess.run([sys.executable, 'tools/flight_store_build.py', '--host-only', '--host-cc', a.host_cc],
                       cwd=ROOT, check=True)
    for m in a.missions.split(','):
        for mode in a.modes.split(','):
            print(f'built {build(a.host_cc, m, mode, a.certified_only).relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
