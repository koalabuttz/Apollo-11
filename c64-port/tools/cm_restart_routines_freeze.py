"""Run the original-program oracle for cm-restart-routines and freeze digests.

Builds the host-only yaAGC driver (tools/cm_restart_routines_reference.c),
runs it on the unmodified Comanche055 rope for the selection, composition and
NEWPHASE cases, checks the native snapshots (build/cm-restart-routines-native)
are byte-identical, and writes tests/cm_restart_routines_vectors.h (one digest
per case: two 16-bit running sums over the printed values) and every
sixteenth digest to tests/cm_restart_routines_c64_vectors.h. Also writes
build/cm-restart-routines-proof.json.
"""
import hashlib
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Comanche055/MAIN.agc.bin'
CORE = ['tests/cm_restart_routines_cases.c', 'src/cm_restart_routines.c', 'src/agc_transfer.c',
        'src/agc_word.c', 'src/agc_multiword.c', 'tests/cm_executive_cases.c',
        str(E / 'agc_engine.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
KINDS = ('select', 'compose', 'newphase')


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(lines, name, values):
    lines.append(f'static const uint32_t {name}[{len(values)}]={{')
    for i in range(0, len(values), 6):
        lines.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    lines.append('};')


def main():
    subprocess.run(['cc', '-std=c99', '-O2', '-Iinclude', '-Itests', '-Isrc', '-I' + str(E),
                    'tools/cm_restart_routines_reference.c', *CORE, '-o', 'build/cm-restart-routines-reference'],
                   cwd=R, check=True)
    digests, shas = {}, {}
    for kind in KINDS:
        ref = subprocess.run(['./build/cm-restart-routines-reference', kind, str(ROPE)], cwd=R,
                             check=True, capture_output=True).stdout
        nat = subprocess.run(['./build/cm-restart-routines-native', kind], cwd=R,
                             check=True, capture_output=True).stdout
        if ref != nat:
            for i, (a, b) in enumerate(zip(ref.decode().splitlines(), nat.decode().splitlines())):
                if a != b:
                    x, y = a.split(), b.split()
                    diff = [(k, x[k], y[k]) for k in range(min(len(x), len(y))) if x[k] != y[k]][:8]
                    raise SystemExit(f'{kind} case {i}: native differs from the original program at {diff}')
            raise SystemExit(f'{kind}: native output length differs')
        rows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
        assert [r[0] for r in rows] == list(range(len(rows)))
        digests[kind] = [digest(r[1:]) for r in rows]
        shas[kind] = hashlib.sha256(ref).hexdigest()
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_restart_routines_freeze.py from the',
           ' * original Comanche055 program (yaAGC oracle). Per-case digests of the status',
           ' * (or service calls) and all 2048 erasable words. */']
    for kind in KINDS:
        out.append(f'#define CM_RR_{kind.upper()}_VECTORS {len(digests[kind])}u')
    for kind in KINDS:
        table(out, f'cm_rr_{kind}_expected', digests[kind])
    (R / 'tests/cm_restart_routines_vectors.h').write_text('\n'.join(out) + '\n')
    c64 = ['/* SPDX-License-Identifier: MIT; generated by tools/cm_restart_routines_freeze.py: every',
           ' * sixteenth digest of tests/cm_restart_routines_vectors.h, for the C64 diagnostic. */',
           '#define CM_RR_C64_STRIDE 16u']
    for kind in KINDS:
        values = digests[kind][::16]
        c64.append(f'#define CM_RR_{kind.upper()}_C64_COUNT {len(values)}u')
        table(c64, f'cm_rr_{kind}_c64', values)
    (R / 'tests/cm_restart_routines_c64_vectors.h').write_text('\n'.join(c64) + '\n')
    proof = {'mission': 'Comanche055', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle': 'yaAGC (deps/virtualagc), host only',
             'cases': {k: len(digests[k]) for k in KINDS},
             'snapshot_sha256': shas,
             'entries': ['01,3520 RESTARTS', '01,3533 GETPART2', '01,3755 PHSPART2', '4114 NEWPHASE'],
             'boundary': 'select: TC GOLOC-1 (Z 0704) or X.1 TC FINDVAC; compose: RESTARTS to SWRETURN '
                         'with each selected service recorded and returned to Q+2; newphase: TC NEWPHASE '
                         'site to the caller L+2',
             'full_physical_words': 2048}
    (B / 'cm-restart-routines-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print('PASS: ' + ', '.join(f'{len(digests[k])} {k}' for k in KINDS) + ' cases equal the original program')


if __name__ == '__main__':
    main()
