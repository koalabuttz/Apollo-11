"""Run the original-program oracle for lm-landing-displays and freeze digests.

Builds the host-only yaAGC driver tools/lm_landing_displays_reference.c (on
yaAGC with the hardware divide, build/agc_engine_hardware_dv.o), runs it on
the unmodified Luminary099 rope, checks the native snapshot
(build/lm-landing-displays-native) is byte-identical on every case the native
routines accept, and writes tests/lm_landing_displays_vectors.h (one digest
per case: two 16-bit running sums over the outcome, channels 12 and 14 and
all 2048 erasable words) and tests/lm_landing_displays_c64_vectors.h (the C64
rows, chosen by outcome by tools/lane_f_c64_rows.py). Cases the native
routines refuse are left out of the comparison; their digest is of the
unchanged input image, which the host test checks. Writes
build/lm-landing-displays-proof.json.
"""
import collections
import hashlib
import json
import pathlib
import subprocess
import sys

R = pathlib.Path(__file__).resolve().parents[1]
B = R / 'build'
E = R / 'deps/virtualagc/yaAGC'
ROPE = B / 'fixed-data/Luminary099/MAIN.agc.bin'
NATIVE = ['src/lm_landing_displays.c', 'src/agc_image_ops.c', 'src/agc_hardware_divide.c', 'src/agc_transfer.c',
          'src/agc_multiword.c', 'tests/lm_landing_displays_cases.c']
CORE = NATIVE + ['src/agc_word.c', 'tests/cm_executive_cases.c',
                 str(B / 'agc_engine_hardware_dv.o'), str(E / 'agc_engine_init.o'), str(E / 'rfopen.o')]
FLAGS = ['-std=c99', '-O2', '-DP66_NATIVE_DISPATCH_ONLY', '-ffunction-sections', '-fdata-sections',
         '-Wl,--gc-sections', '-Iinclude', '-Itests', '-Itools', '-I' + str(E)]
REFUSED = 1
NAMES = ['LANDISP', 'INTLZE', '21,2364', '21,2476', 'LANDISP', '21,2476', 'LANDISP', '21,2476']
# Where the file's exits go (Z).
EXITS = {0o5261: 'TASKOVER', 0o5173: 'TWIDDLE (ADRES INTLZE)', 0o5224: 'VARDELAY', 0o1714: 'TC LADQSAVE (another word)',
         0o5014: 'TC 05014 (WOR CHAN14 run as TC)', 0o300: 'TC 00300 (BITS8/7 run as TC)'}


def digest(values):
    a = b = 0
    for v in values:
        a = (a + v) & 0xffff
        b = (b + a) & 0xffff
    return b << 16 | a


def table(name, values):
    out = [f'static const uint32_t {name}[{len(values)}]={{']
    for i in range(0, len(values), 6):
        out.append(''.join(f'0x{v:08x}ul,' for v in values[i:i + 6]))
    out.append('};')
    return out


def main():
    if not (B / 'agc_engine_hardware_dv.o').exists():
        subprocess.run([sys.executable, 'tools/prepare_hardware_dv.py'], cwd=R, check=True)
    subprocess.run(['cc', *FLAGS, 'tools/lm_landing_displays_reference.c', *CORE,
                    '-o', 'build/lm-landing-displays-reference'], cwd=R, check=True)
    ref = subprocess.run(['./build/lm-landing-displays-reference', str(ROPE)], cwd=R,
                         check=True, capture_output=True).stdout
    nat = subprocess.run(['./build/lm-landing-displays-native'], cwd=R, check=True, capture_output=True).stdout
    rrows = [list(map(int, line.split())) for line in ref.decode().splitlines()]
    nrows = [list(map(int, line.split())) for line in nat.decode().splitlines()]
    assert [r[0] for r in rrows] == [r[0] for r in nrows] == list(range(len(nrows)))
    compared = [n for n in nrows if n[1] != REFUSED]
    for n in compared:
        assert n == rrows[n[0]], f'lm-landing-displays case {n[0]}: native differs from the original program'
    refused = [n[0] for n in nrows if n[1] == REFUSED]
    digests = [digest(r[1:]) for r in nrows]
    out = ['/* SPDX-License-Identifier: MIT; generated by tools/lm_landing_displays_freeze.py from the',
           ' * original Luminary099 program (yaAGC oracle). Per-case digests of the outcome',
           ' * kind, channels 12 and 14 and all 2048 erasable words',
           ' * (a refused case: its unchanged input image). */',
           f'#define LM_LAD_VECTORS {len(digests)}u', *table('lm_lad_expected', digests)]
    (R / 'tests/lm_landing_displays_vectors.h').write_text('\n'.join(out) + '\n')
    subprocess.run([sys.executable, 'tools/lane_f_c64_rows.py', 'lm-landing-displays'], cwd=R, check=True)
    outcome = ['left the file', 'refused', 'none']
    kinds = collections.Counter(f"{NAMES[r[0] % 8]}:{outcome[r[1]]}" for r in nrows)
    oracle_refused = collections.Counter(outcome[rrows[n][1]] for n in refused)
    # Where each compared case left the file (rows are case, kind, channels
    # 12 and 14, then the image: Z is word 5).
    exits = collections.Counter(EXITS.get(r[4 + 5], f'Z {r[4 + 5]:05o}') for r in compared)
    proof = {'mission': 'Luminary099', 'rope_sha256': hashlib.sha256(ROPE.read_bytes()).hexdigest(),
             'oracle_engine': 'yaAGC with the hardware divide (build/agc_engine_hardware_dv.o)',
             'cases': len(nrows), 'compared_cases': len(compared),
             'compared_sha256': hashlib.sha256('\n'.join(' '.join(map(str, n)) for n in compared).encode()).hexdigest(),
             'outcomes': dict(sorted(kinds.items())),
             'exits': dict(sorted(exits.items())),
             'refused_cases': len(refused), 'refused_oracle_outcomes': dict(sorted(oracle_refused.items())),
             'entries': ['21,2154 LANDISP', '21,2365 INTLZE', '21,2364', '21,2476'],
             'boundary': 'each entry from a random image (FB bank 21, EB 7, random channels 12 and 30, channel 14 '
                         'without the CDU and gyro drive bits, the tested flag bits set or clear, LADQSAVE holding '
                         'ALTROUT +1 or ALTOUT +1 in three cases in four, erasable words of random widths with +-0 '
                         'frequent) until the original leaves 21,2154-3076 (TC or TCF to TASKOVER, TWIDDLE, '
                         'VARDELAY, TC LADQSAVE to a word other than ALTROUT +1 and ALTOUT +1, and the CCS and TS '
                         'exits that run a data word as TC); compared: outcome, channels 12 and 14 and all 2048 '
                         'erasable words',
             'full_physical_words': 2048}
    (B / 'lm-landing-displays-proof.json').write_text(json.dumps(proof, indent=1) + '\n')
    print(f'PASS: {len(compared)} lm-landing-displays cases equal the original program '
          f'({len(refused)} refused): {dict(sorted(kinds.items()))}')


if __name__ == '__main__':
    main()
