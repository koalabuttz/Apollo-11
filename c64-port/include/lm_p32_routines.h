#ifndef LM_P32_ROUTINES_H
#define LM_P32_ROUTINES_H
/* Luminary099 P32-P35_P72-P75: P32/P72 with ALMXITA and ALMXIT (bank 35,
 * 02027-02215) as routines of the control-transfer ABI
 * (docs/NATIVE_TRANSFER_ABI.md, docs/LM-P32.md). io is a p66_bias_io.
 *
 * Basic (keyed by Z in bank 35):
 *   P32 (2027) TC AVFLAGA; (2030) TC P32STRT; P72 (2031) TC AVFLAGP;
 *   P32STRT (2032) DCA P30ZERO, DXCH CENTANG, TC P32/P72A;
 *   after ALMXIT's EXIT: (2044) CA MPAC, TC VARALARM; (2046) CAF V05N09,
 *   TC BANKCALL (CADR GOFLASH); its returns (2051) TC GOTOPOOH, (2052) TC
 *   -4 (recycle is P32/P72A);
 *   P32/P72A (2053) TC P20FLGON; (2054) P30ZERO into NN +1, TCSI and
 *   TCSI +1, on into VN0611; VN0611 (2060) CAF V06N11, TC VNPOOH; (2062)
 *   TC INTPRET; (2112) TC VN0611; after VN0655's EXIT: (2114) CAF V06N55,
 *   TC BANKCALL (CADR GOFLASH); its returns (2117) TC GOTOPOOH, (2120) TC
 *   +2, (2121) TC -5; (2122) CAF V06N37, TC VNPOOH; (2124) TC INTPRET;
 *   after the EXIT at 2172: (2173) CAF V06N75, TC VNPOOH; (2175) TC
 *   INTPRET.
 * Interpretive (keyed by LOC under BANKSET at NEWOPS in bank 35):
 *   ALMXITA (2036) SXA,2 CSIALRM, on into ALMXIT; ALMXIT (2040) LXC,1
 *   CSIALRM, SLOAD* ALARM/TB -1,1, EXIT;
 *   (2063) DLOAD DCOMP TCSI, BMN VN0655, else DLOAD TETLEM, STCALL TDEC1
 *   PRECSET; (2072) where PRECSET returns: RVEC and VVEC from RACT3 and
 *   VACT3 (VSR* 0,2), SET RVSW, DPPOSMAX, STCALL RDESIRED TIMERAD; (2106)
 *   where TIMERAD returns: DAD TDEC2, STORE TCSI, EXIT; VN0655 (2113)
 *   EXIT;
 *   (2125) DLOAD TCSI, STCALL TIG SELECTMU; P32/P72B (2131) CALL ADVANCE;
 *   (2133) SETPD 0D, VPASS1, RPASS1, TCSI, TTPI and TWOPI pushed, CALL
 *   INTINT; (2146) CALL PASSIVE; (2150) CALL CSI/A;
 *   P32/P72C (2152) BON FINALFLG P32/P72D, else SET UPDATFLG;
 *   P32/P72D (2156) DLOAD T1TOT2; P32/P72E (2160) STORE T1TOT2, 60MIN
 *   taken off while positive; DLOAD T2TOT3; P32/P72F (2166) the same into
 *   T2TOT3; EXIT;
 *   (2176) VLOAD DELVEET1, CALL S32/33.1; (2201) STOVL DELVEET1 RACT2,
 *   STOVL RACT1 DELVEET2, AXT,1 VN0682, CALL DISDVLVC; (2210) DLOAD TTPI,
 *   STCALL TTPI0 VN1645; (2214) GOTO P32/P72B. */
#include "agc_transfer.h"
#include "p66_bias.h"
#define LM_P32_B35(z) ((uint16_t)(035u*1024u+((z)-02000u)))
#define LM_P32_INTERPRETIVE_ROUTINES 19u
#define LM_P32_BASIC_ROUTINES 21u
extern const agc_routine_table lm_p32_interpretive_routines;
extern const agc_routine_table lm_p32_basic_routines;
#endif
