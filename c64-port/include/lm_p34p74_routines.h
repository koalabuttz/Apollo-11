#ifndef LM_P34P74_ROUTINES_H
#define LM_P34P74_ROUTINES_H
/* Luminary099 P34-35_P74-75 P34/P74 (bank 35, 02545-02724) as routines of
 * the control-transfer ABI (docs/NATIVE_TRANSFER_ABI.md, docs/LM-P34P74.md).
 * io is a p66_bias_io.
 *
 * Basic (keyed by Z in bank 35):
 *   P34 (2545) TC AVFLAGA; (2546) TC P34/P74A; P74 (2547) TC AVFLAGP;
 *   P34/P74A (2550) TC P20FLGON; (2551) CAF V06N37, TC VNPOOH;
 *   (2553) EXTEND, DCA 130DEG, DXCH CENTANG, CAF P30ZERO, TS NN, TC
 *          DISPLAYE; (2561) TC INTPRET;
 *   (2615) TC ALARM (OCT 611); (2617) CAF V05N09, TC BANKCALL (CADR
 *          GOFLASH); GOFLASH's returns (2622) TC GOTOPOOH, (2623) TC
 *          P34/P74A, (2624) TC -7;
 *   (2633) TC DISPLAYE; (2634) TC P34/P74E; (2636) CAF V06N37, TC VNPOOH;
 *   P34/P74E (2640) TC INTPRET; (2714) CAF V06N58, TC VNPOOH; (2716) TC
 *          INTPRET.
 * Interpretive (keyed by LOC under BANKSET at NEWOPS in bank 35):
 *   (2562) CLEAR ETPIFLAG, DLOAD TTPI, STODL TIG ELEV, BZE P34/P74B, SET
 *          ETPIFLAG; P34/P74B (2572) CALL SELECTMU;
 *   P34/P74C (2574) DLOAD ZEROVECS, SET ITSWICH, BON ETPIFLAG SWCHSET or
 *          CLEAR ITSWICH, SWCHSET STORE NOMTPI, on into INTLOOP;
 *   INTLOOP (2604) DLOAD TTPI, DAD NOMTPI, STCALL TDEC1 PRECSET;
 *   (2611) CALL S33/34.1; (2613) BZE SWCHCLR, else EXIT;
 *   SWCHCLR (2625) BONCLR ITSWICH INTLOOP, BON ETPIFLAG P34/P74D, EXIT;
 *   P34/P74D (2635) EXIT;
 *   (2641) SETPD 0D, DLOAD RTX1, STODL X1 CENTANG, PUSH COS, STODL CSTH,
 *          SIN, STOVL SNTH RPASS3, VSR* 0,2, STOVL RVEC VPASS3, VSR* 0,2,
 *          SET RVSW, STCALL VVEC TIMETHET;
 *   (2664) DLOAD TTPI, STORE INTIME, DAD T, STCALL TPASS4 S34/35.2;
 *   (2673) VLOAD DELVEET3, ABVAL, STOVL DELVTPI VPASS4, VSU VTPRIME,
 *          ABVAL, STOVL DELVTPF RACT3, PDVL VIPRIME, CALL PERIAPO1;
 *   (2706) CALL SHIFTR1; (2710) STODL POSTTPI TTPI, STORE TIG, EXIT;
 *   (2717) CALL S34/35.5; (2721) CALL VN1645; (2723) GOTO P34/P74C. */
#include "agc_transfer.h"
#include "p66_bias.h"
#define LM_P34P74_B35(z) ((uint16_t)(035u*1024u+((z)-02000u)))
#define LM_P34P74_INTERPRETIVE_ROUTINES 16u
#define LM_P34P74_BASIC_ROUTINES 18u
extern const agc_routine_table lm_p34p74_interpretive_routines;
extern const agc_routine_table lm_p34p74_basic_routines;
#endif
