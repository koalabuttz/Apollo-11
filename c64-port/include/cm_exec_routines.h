/* Comanche055 Executive and Waitlist service entries as native routines of
 * the control-transfer ABI (docs/NATIVE_TRANSFER_ABI.md); io is cm_native_io.
 *
 * NOVAC 05134 and FINDVAC 05147 (cm_admission_zero) and WAITLIST 05245 and
 * TWIDDLE 05235 (cm_waitlist_extended) take the inline 2CADR (TWIDDLE: ADRES)
 * at Q from the compiled site table (cm_exec_site_table) or from erasable,
 * and continue at the caller's return, or at BAILOUT 07755/POODOO 05721 with
 * the source alarm code.
 *
 * LONGCALL is the WAITLIST.agc LONGCALL/LONGCYCL/GETCADR task chain. Unlike
 * Luminary's, Comanche's LNGCALL2 has no delta-time check:
 *   LONGCALL 05342     delta time in A,L, task 2CADR at Q; DTCB to LNGCALL2
 *   LNGCALL2 01,3461   saves the return 2CADR in LONGEXIT; LONGCYCL
 *   LONGCYCL 01,3465   (also a Waitlist task) MUCHTIME or LASTTIME up to
 *                      TC WAITLIST with 2CADR LONGCYCL or GETCADR
 *   LONGRTRN 01,3505   and 01,3514 (TCF LONGRTRN), where WAITLIST returns:
 *                      DTCB to LONGEXIT, then LONGEXIT := TASKOVER
 *   GETCADR  01,3515   (a Waitlist task) DTCB to the task 2CADR.
 * The two LONGCYCL branches that would execute the constant words DPBIT14
 * (a positive-zero or negative high word with a nonpositive low word) have
 * no producer and are EXEC_OUT_OF_SCOPE, as is a LONGEXIT or LONGCADR
 * address of 0 or above 07777.
 *
 * Task services, run inside T3RUPT (program->hardware->in_interrupt set):
 *   FIXDELAY 05267 (DEC at Q), VARDELAY 05272 (delay in A)
 *                      requeue the task's remainder (cm_waitlist_internal),
 *                      then TASKOVER, or BAILOUT/POODOO with 1203/1204
 *   TASKOVER 05324     RUPTAGN -0: resume the interrupted program at
 *                      ZRUPT-1 and clear in_interrupt; +1: dispatch the next
 *                      due task (T3RUPT2, cm_task_transfer)
 *   T3RUPT vector 04014  the T3 lead-in (ARUPT, BANKRUPT, QRUPT) and dispatch
 * TASKOVER and the vector need program->hardware. */
extern const agc_routine_table cm_exec_routines;
/* Every genuine NOVAC/FINDVAC/WAITLIST/LONGCALL/TWIDDLE/FIXDELAY inline
 * operand, generated by tools/agc_sites_generate.py cm-exec. */
const agc_site_operand *cm_exec_site_table(uint16_t *count);

#define CM_EXEC_T3RUPT_VECTOR 04014u
#define CM_EXEC_NOVAC 05134u
#define CM_EXEC_FINDVAC 05147u
