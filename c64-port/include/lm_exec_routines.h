/* Luminary099 Executive and Waitlist service entries as native routines of
 * the control-transfer ABI (docs/NATIVE_TRANSFER_ABI.md); io is p66_bias_io.
 *
 * NOVAC 05072 and FINDVAC 05105 (lm_admission_image) and WAITLIST 05203 and
 * TWIDDLE 05173 (lm_waitlist_image) take the inline 2CADR (TWIDDLE: ADRES)
 * at Q from the compiled site table (lm_exec_site_table) or from erasable,
 * and continue at the caller's return, or at BAILOUT1/POODOO1 with the
 * source alarm code.
 *
 * LONGCALL is the WAITLIST.agc LONGCALL/LONGCYCL/GETCADR task chain:
 *   LONGCALL 05277     delta time in A,L, task 2CADR at Q; DTCB to LNGCALL2
 *   LNGCALL2 01,3452   saves the return 2CADR in LONGEXIT; LONGCYCL or the
 *                      LONGPOOH alarm (TC POODOO1, OCT 01204)
 *   LONGCYCL 01,3466   (also a Waitlist task) MUCHTIME or LASTTIME up to
 *                      TC WAITLIST with 2CADR LONGCYCL or GETCADR
 *   LONGRTRN 01,3506   and 01,3515 (TCF LONGRTRN), where WAITLIST returns:
 *                      DTCB to LONGEXIT, then LONGEXIT := TASKOVER
 *   GETCADR  01,3516   (a Waitlist task) DTCB to the task 2CADR.
 * The two LONGCYCL branches that would execute the constant words DPBIT14
 * (a positive-zero or negative high word with a nonpositive low word) have
 * no producer and are EXEC_OUT_OF_SCOPE, as is a LONGEXIT or LONGCADR
 * address of 0 or above 07777. */
extern const agc_routine_table lm_exec_routines;
/* Every genuine NOVAC/FINDVAC/WAITLIST/LONGCALL/TWIDDLE inline operand,
 * generated by tools/agc_sites_generate.py lm-exec. */
const agc_site_operand *lm_exec_site_table(uint16_t *count);

#define LM_EXEC_NOVAC 05072u
#define LM_EXEC_FINDVAC 05105u
#define LM_EXEC_TWIDDLE 05173u
#define LM_EXEC_WAITLIST 05203u
#define LM_EXEC_TASKOVER 05261u
#define LM_EXEC_LONGCALL 05277u
#define LM_EXEC_BAILOUT1 05716u
#define LM_EXEC_POODOO1 05726u
#define LM_EXEC_LNGCALL2 03452u
#define LM_EXEC_LONGCYCL 03466u
#define LM_EXEC_LONGRTRN 03506u
#define LM_EXEC_MUCHRTRN 03515u
#define LM_EXEC_GETCADR 03516u
#define LM_EXEC_LONGCADR 01147u
#define LM_EXEC_LONGBASE 01151u
#define LM_EXEC_LONGTIME 01153u
#define LM_EXEC_LONGEXIT 01434u
#endif
