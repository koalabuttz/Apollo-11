#ifndef LANEC_EV_ROUTINES_H
#define LANEC_EV_ROUTINES_H
/* EXTENDED_VERBS (Luminary099 and Comanche055) as native routines of the
 * control-transfer ABI (docs/NATIVE_TRANSFER_ABI.md). Every entry and every
 * point where a callee returns into the file that a Lane C suite verifies is
 * registered at its physical address and runs that module's
 * lanec_ev_*_dispatch; LANEC_OUT_OF_SCOPE is EXEC_OUT_OF_SCOPE. The Luminary
 * interpretive words (lanec_ev_lmi) are interpretive routines keyed by LOC
 * under BANKSET. Each module has its own tables, one per mission, in its own
 * source file (src/lanec_ev_<module>_routines.c, generated by
 * tools/lanec/routines.py ev), so a flight-store module links one module's
 * code alone; a program registers the tables of the modules it runs.
 *
 * The modules read and write channels 12, 14, 30, 31 and 33 besides the
 * superbank and interrupt enable, so io is the mission's downtelemetry
 * device record, which carries them: an lm_dntm_io for Luminary (its first
 * member the p66_bias_io the INTER-BANK and Executive routines take; output
 * channel 11 comes from program->hardware as for the display interface, and
 * the routines refuse when that is NULL) and a cm_dntm_io for Comanche (its
 * cm_native_io first). */
#include "agc_transfer.h"
#include "lanec.h"
#include "lanec_di_routines.h"   /* lanec_put_tables */
#include "lm_downtelemetry.h"
#include "cm_downtelemetry.h"
extern const agc_routine_table lanec_ev_lm_front, lanec_ev_lm_short, lanec_ev_lm_align, lanec_ev_lm_radar,
    lanec_ev_lm_dap, lanec_ev_lm_time, lanec_ev_lm_track;
extern const agc_routine_table lanec_ev_cm_front, lanec_ev_cm_short, lanec_ev_cm_align, lanec_ev_cm_dap,
    lanec_ev_cm_time, lanec_ev_cm_track;
/* every module's basic table, in module order (addresses), for a program that registers them all */
#define LANEC_EV_LM_TABLES &lanec_ev_lm_front, &lanec_ev_lm_short, &lanec_ev_lm_align, &lanec_ev_lm_radar, \
    &lanec_ev_lm_dap, &lanec_ev_lm_time, &lanec_ev_lm_track
#define LANEC_EV_LM_TABLE_COUNT 7u
#define LANEC_EV_CM_TABLES &lanec_ev_cm_front, &lanec_ev_cm_short, &lanec_ev_cm_align, &lanec_ev_cm_dap, \
    &lanec_ev_cm_time, &lanec_ev_cm_track
#define LANEC_EV_CM_TABLE_COUNT 6u
/* lanec_ev_lmi's points, all interpretive (src/lanec_ev_lmi_routines.c) */
extern const agc_routine_table lanec_ev_lm_interpretive;
/* INTPRET (fixed-fixed 06037) for this file's TC INTPRET callers only: Q must
 * name one of lanec_ev_lm_interpretive's points. A program registers it in
 * place of a general INTPRET routine, which is the interpreter's (none yet). */
extern const agc_routine_table lanec_ev_lm_intpret;
/* A module's routine: the module's dispatch on the mission's device record,
 * and INTPRET for the points of the table given (src/lanec_ev_routines.c). */
typedef enum lanec_status (*lanec_ev_dispatch)(apollo_overlay_state *, lanec_io *, enum lanec_mission);
enum exec_status lanec_ev_run_lm(const agc_native_program *, apollo_overlay_state *, lm_dntm_io *, lanec_ev_dispatch);
enum exec_status lanec_ev_run_cm(const agc_native_program *, apollo_overlay_state *, cm_dntm_io *, lanec_ev_dispatch);
enum exec_status lanec_ev_intpret_lm(const agc_native_program *, apollo_overlay_state *, lm_dntm_io *,
                                     const agc_routine_table *);
#endif
